// Команда docs собирает документацию в HTML.
//
// Отдельной командой, а не подкомандой takt: в образ она не едет
// и базы не касается — это инструмент сборки, а не часть продукта.
//
// Запуск: make docs. Итог — docs/html/*.html, самодостаточные страницы
// без единой внешней ссылки: их читают в закрытом контуре, с флешки
// и из папки на диске.
package main

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"

	"github.com/findias/takt/internal/docs"
	"github.com/findias/takt/internal/version"
)

// Что собираем и как называем в оглавлении. Список явный: README
// и требования адресованы разным людям, и порядок здесь — порядок
// чтения, а не алфавит.
// Порядок — порядок чтения, а не алфавит, и он же порядок Diátaxis:
// обучение, задача, справка, объяснение. Эти четыре отвечают на разные
// вопросы, и смешанные в одном тексте мешают друг другу: учиться удобно
// последовательно, задачу решать точечно, справку читать таблицей.
var исходники = []источник{
	{"docs/индекс.md", "О продукте"},
	{"docs/старт.md", "Первые 15 минут"},
	{"docs/как.md", "Как сделать"},
	{"docs/справочник.md", "Справочник"},
	{"docs/памятка.md", "Памятка"},
	{"docs/устройство.md", "Устройство"},
	{"docs/установка.md", "Установка"},
	{"REQUIREMENTS.md", "Требования"},
	{"CHANGELOG.md", "Что менялось"},
}

type источник struct {
	путь, имя string
}

// Английские страницы — весь набор, а не два текста «что это и как
// начать», как было раньше.
//
// Возражение против второго набора было записано здесь же и звучало
// так: перевод разойдётся с оригиналом, потому что у него нет прогона,
// который упадёт, когда оригинал поправят. Возражение верное, и снято
// оно ровно тем, чего не хватало: `internal/translation` держит
// отпечаток русского исходника в самой английской странице и падает,
// когда оригинал ушёл вперёд. Порядок тот же, что у русских, —
// обучение, задача, справка, объяснение.
var английские = []источник{
	{"docs/en/overview.md", "Overview"},
	{"docs/en/quickstart.md", "First 15 minutes"},
	{"docs/en/howto.md", "How to"},
	{"docs/en/reference.md", "Reference"},
	{"docs/en/cheatsheet.md", "Cheat sheet"},
	{"docs/en/architecture.md", "Design decisions"},
	{"docs/en/install.md", "Installation"},
}

// Снимки, на которые ссылается документация. Копируются в сборку:
// страница обязана открываться из папки на диске, а картинка,
// оставшаяся в web/screenshots, там не откроется.
var снимки = map[string]string{
	"список-досок.png": "web/screenshots/02-список-досок.png",
	"доска.png":        "web/screenshots/03-доска.png",
	"карточка.png":     "web/screenshots/09-карточка-работа.png",
	"таблица.png":      "web/screenshots/12-таблица.png",
	"поток.png":        "web/screenshots/14-поток.png",
	"команда.png":      "web/screenshots/19-команда.png",
}

func main() {
	корень, err := os.Getwd()
	если(err)
	// Куда складывать: обычно рядом с исходниками, но проверка
	// пересборки просит временный каталог — ей нужно сравнить,
	// а не переписать.
	вывод := filepath.Join(корень, "docs", "html")
	if свой := os.Getenv("DOCS_OUT"); свой != "" {
		вывод = свой
	}
	если(os.MkdirAll(вывод, 0o755))

	оглавление := make([]docs.Пункт, 0, len(исходники)+1)
	for _, и := range исходники {
		оглавление = append(оглавление, docs.Пункт{Файл: имяHTML(и.путь), Имя: и.имя})
	}
	// Переход на другой язык — такой же пункт оглавления: ссылка,
	// спрятанная в подвале, не находится тем, кто её ищет.
	оглавление = append(оглавление, docs.Пункт{Файл: "en/overview.html", Имя: "In English"})

	английскоеОглавление := []docs.Пункт{}
	for _, и := range английские {
		английскоеОглавление = append(английскоеОглавление,
			docs.Пункт{Файл: имяHTML(и.путь), Имя: и.имя})
	}
	английскоеОглавление = append(английскоеОглавление,
		docs.Пункт{Файл: "../индекс.html", Имя: "По-русски"})

	// Снимки кладутся дважды: рядом с исходниками — чтобы картинки
	// работали и в markdown, который читают в репозитории, — и в сборку,
	// чтобы страница открывалась из папки на диске.
	//
	// Свежие берутся из `web/screenshots`, куда их кладёт `make screens`.
	// Каталог этот в поставку не входит, и на чистом клоне его нет —
	// поэтому источник запасной: снимки, уже лежащие в `docs/снимки`.
	// Без запасного сборка документации требовала бы браузера и стенда,
	// то есть `make check` не проходил бы там, где ничего этого нет, —
	// в закрытом контуре и в CI. Ровно на этом проверка и падала.
	назначения := []string{
		filepath.Join(корень, "docs", "снимки"),
		filepath.Join(корень, "docs", "en", "снимки"),
		filepath.Join(вывод, "снимки"),
	}
	for _, куда := range назначения {
		если(os.MkdirAll(куда, 0o755))
	}
	for имя := range снимки {
		raw := прочестьСнимок(корень, имя)
		for _, куда := range назначения {
			если(os.WriteFile(filepath.Join(куда, имя), raw, 0o644))
		}
	}

	версия := версияСборки()
	собранные := make([]docs.Страница, 0, len(исходники))
	for _, и := range исходники {
		raw, err := os.ReadFile(filepath.Join(корень, и.путь))
		если(err)
		заголовок, тело := docs.Отрисовать(string(raw))
		if заголовок == "" {
			заголовок = и.имя
		}
		страница := docs.Страница{
			Файл: имяHTML(и.путь), Заголовок: заголовок, Имя: и.имя, HTML: тело,
		}
		готово := docs.Собрать(страница, оглавление, версия)
		если(os.WriteFile(filepath.Join(вывод, страница.Файл), []byte(готово), 0o644))
		fmt.Printf("  %s → docs/html/%s\n", и.путь, страница.Файл)
		собранные = append(собранные, страница)
	}

	// Английские страницы — своим каталогом и со своим оглавлением.
	каталогEn := filepath.Join(вывод, "en")
	если(os.MkdirAll(каталогEn, 0o755))
	если(os.MkdirAll(filepath.Join(каталогEn, "снимки"), 0o755))
	for имя := range снимки {
		если(os.WriteFile(filepath.Join(каталогEn, "снимки", имя),
			прочестьСнимок(корень, имя), 0o644))
	}
	for _, и := range английские {
		raw, err := os.ReadFile(filepath.Join(корень, и.путь))
		если(err)
		заголовок, тело := docs.Отрисовать(string(raw))
		if заголовок == "" {
			заголовок = и.имя
		}
		страница := docs.Страница{
			Файл: имяHTML(и.путь), Заголовок: заголовок, Имя: и.имя, Язык: "en", HTML: тело,
		}
		готово := docs.Собрать(страница, английскоеОглавление, версия)
		если(os.WriteFile(filepath.Join(каталогEn, страница.Файл), []byte(готово), 0o644))
		fmt.Printf("  %s → docs/html/en/%s\n", и.путь, страница.Файл)
	}

	// Всё одним файлом: его отдают вложением и с него печатают —
	// браузер печатает открытое, а не восемь страниц по ссылкам.
	одним := docs.СобратьВсё(собранные, версия)
	если(os.WriteFile(filepath.Join(вывод, "всё.html"), []byte(одним), 0o644))
	fmt.Println("  все разделы → docs/html/всё.html")
}

func имяHTML(путь string) string {
	имя := filepath.Base(путь)
	return strings.TrimSuffix(имя, filepath.Ext(имя)) + ".html"
}

// Версия для подписи: вшитая, если собирали через make, иначе —
// спрошенная у git. Отсутствие версии в подписи документации значит,
// что на вопрос «это про какую вашу» страница отвечает молчанием.
func версияСборки() string {
	if version.Задана() {
		return version.Строка()
	}
	out, err := exec.Command("git", "describe", "--tags", "--always", "--dirty").Output()
	if err != nil {
		return "не задана"
	}
	return strings.TrimSpace(string(out))
}

// прочестьСнимок берёт снимок там, где он есть: сперва свежий
// из `web/screenshots`, потом уже лежащий в `docs/снимки`.
//
// Порядок именно такой: `make screens` кладёт свежие, и сборка обязана
// брать их, а не молча оставлять вчерашние. Но каталога `web/screenshots`
// в поставке нет, и требовать его — значит требовать браузера и стенда
// от всякого, кто собирает документацию.
func прочестьСнимок(корень, имя string) []byte {
	raw, err := os.ReadFile(filepath.Join(корень, снимки[имя]))
	if os.IsNotExist(err) {
		raw, err = os.ReadFile(filepath.Join(корень, "docs", "снимки", имя))
		if os.IsNotExist(err) {
			если(fmt.Errorf("снимка %s нет ни в %s, ни в docs/снимки: "+
				"снимите заново — `make screens`", имя, снимки[имя]))
		}
	}
	если(err)
	return raw
}

func если(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, "документация не собралась:", err)
		os.Exit(1)
	}
}
