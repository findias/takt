// Команда docs собирает документацию в HTML.
//
// Отдельной командой, а не подкомандой board: в образ она не едет
// и базы не касается — это инструмент сборки, а не часть продукта.
//
// Запуск: make docs. Итог — docs/html/*.html, самодостаточные страницы
// без единой внешней ссылки: их читают в закрытом контуре, с флешки
// и из папки на диске.
package main

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"

	"github.com/konkov/agile/internal/docs"
	"github.com/konkov/agile/internal/version"
)

// Что собираем и как называем в оглавлении. Список явный: README
// и требования адресованы разным людям, и порядок здесь — порядок
// чтения, а не алфавит.
// Порядок — порядок чтения, а не алфавит, и он же порядок Diátaxis:
// обучение, задача, справка, объяснение. Эти четыре отвечают на разные
// вопросы, и смешанные в одном тексте мешают друг другу: учиться удобно
// последовательно, задачу решать точечно, справку читать таблицей.
var исходники = []struct{ путь, имя string }{
	{"docs/индекс.md", "О продукте"},
	{"docs/старт.md", "Первые 15 минут"},
	{"docs/как.md", "Как сделать"},
	{"docs/справочник.md", "Справочник"},
	{"docs/памятка.md", "Памятка"},
	{"docs/устройство.md", "Устройство"},
	{"README.md", "Установка"},
	{"REQUIREMENTS.md", "Требования"},
	{"CHANGELOG.md", "Что менялось"},
}

// Снимки, на которые ссылается документация. Копируются в сборку:
// страница обязана открываться из папки на диске, а картинка,
// оставшаяся в web/screenshots, там не откроется.
var снимки = map[string]string{
	"список-досок.png": "web/screenshots/02-список-досок.png",
	"доска.png":        "web/screenshots/03-доска.png",
	"карточка.png":     "web/screenshots/09-карточка-работа.png",
	"таблица.png":      "web/screenshots/12-таблица.png",
	"поток.png":        "web/screenshots/14-поток.png",
	"команда.png":      "web/screenshots/19-команда.png",
}

func main() {
	корень, err := os.Getwd()
	если(err)
	// Куда складывать: обычно рядом с исходниками, но проверка
	// пересборки просит временный каталог — ей нужно сравнить,
	// а не переписать.
	вывод := filepath.Join(корень, "docs", "html")
	if свой := os.Getenv("DOCS_OUT"); свой != "" {
		вывод = свой
	}
	если(os.MkdirAll(вывод, 0o755))

	оглавление := make([]docs.Пункт, 0, len(исходники))
	for _, и := range исходники {
		оглавление = append(оглавление, docs.Пункт{Файл: имяHTML(и.путь), Имя: и.имя})
	}

	// Снимки кладутся дважды: рядом с исходниками — чтобы картинки
	// работали и в markdown, который читают в репозитории, — и в сборку,
	// чтобы страница открывалась из папки на диске. Источник один,
	// `web/screenshots`: там они и снимаются проверкой.
	for _, куда := range []string{filepath.Join(корень, "docs", "снимки"), filepath.Join(вывод, "снимки")} {
		если(os.MkdirAll(куда, 0o755))
		for имя, откуда := range снимки {
			raw, err := os.ReadFile(filepath.Join(корень, откуда))
			если(err)
			если(os.WriteFile(filepath.Join(куда, имя), raw, 0o644))
		}
	}

	версия := версияСборки()
	собранные := make([]docs.Страница, 0, len(исходники))
	for _, и := range исходники {
		raw, err := os.ReadFile(filepath.Join(корень, и.путь))
		если(err)
		заголовок, тело := docs.Отрисовать(string(raw))
		if заголовок == "" {
			заголовок = и.имя
		}
		страница := docs.Страница{
			Файл: имяHTML(и.путь), Заголовок: заголовок, Имя: и.имя, HTML: тело,
		}
		готово := docs.Собрать(страница, оглавление, версия)
		если(os.WriteFile(filepath.Join(вывод, страница.Файл), []byte(готово), 0o644))
		fmt.Printf("  %s → docs/html/%s\n", и.путь, страница.Файл)
		собранные = append(собранные, страница)
	}

	// Всё одним файлом: его отдают вложением и с него печатают —
	// браузер печатает открытое, а не восемь страниц по ссылкам.
	одним := docs.СобратьВсё(собранные, версия)
	если(os.WriteFile(filepath.Join(вывод, "всё.html"), []byte(одним), 0o644))
	fmt.Println("  все разделы → docs/html/всё.html")
}

func имяHTML(путь string) string {
	имя := filepath.Base(путь)
	return strings.TrimSuffix(имя, filepath.Ext(имя)) + ".html"
}

// Версия для подписи: вшитая, если собирали через make, иначе —
// спрошенная у git. Отсутствие версии в подписи документации значит,
// что на вопрос «это про какую вашу» страница отвечает молчанием.
func версияСборки() string {
	if version.Задана() {
		return version.Строка()
	}
	out, err := exec.Command("git", "describe", "--tags", "--always", "--dirty").Output()
	if err != nil {
		return "не задана"
	}
	return strings.TrimSpace(string(out))
}

func если(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, "документация не собралась:", err)
		os.Exit(1)
	}
}
