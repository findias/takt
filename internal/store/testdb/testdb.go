// Package testdb отвечает на один вопрос: где база для проверок —
// и что делать, если её нет.
//
// Раньше ответ был «молча пропустить». `go test ./...` без
// TEST_DATABASE_URL печатал «ok» у каждого пакета, пропустив 248
// проверок из 259: зелено, полно и неправда. Такой прогон выглядит
// как проверка, а проверено при нём одиннадцать штук — модели клиента
// и разбор адресов.
//
// Теперь молчания нет. Либо база задана — тогда проверки идут; либо
// прогон объявлен коротким (`go test -short ./...`) — тогда пропуск
// был выбран человеком и виден в команде; либо прогон падает и
// объясняет, что делать. Отказ называет обе дороги, потому что
// «не найдено» вместо «нельзя» отправляет искать несуществующую
// поломку.
package testdb

import (
	"context"
	"os"
	"sync"
	"testing"

	"github.com/konkov/agile/internal/store"
)

// Объяснение печатается один раз: без базы падает каждая проверка,
// и двести пятьдесят одинаковых абзацев топят то единственное, ради
// чего они написаны.
var said sync.Once

// URL возвращает адрес базы для проверок.
//
// Вызывается из вспомогательной функции пакета, а не из каждого теста:
// решение одно на пакет, и повторять его в сотне мест значило бы
// однажды написать его иначе.
func URL(t *testing.T) string {
	t.Helper()
	url := os.Getenv("TEST_DATABASE_URL")
	if url != "" {
		return url
	}
	if testing.Short() {
		t.Skip("короткий прогон: проверки против базы пропущены намеренно")
	}
	message := "не задан TEST_DATABASE_URL"
	said.Do(func() {
		message = "не задан TEST_DATABASE_URL, а без базы эти проверки не значат ничего.\n" +
			"Поднять базу и прогнать всё: make check (или make test-integration).\n" +
			"Сознательно обойтись без базы: go test -short ./... — тогда пропуск " +
			"виден в самой команде, а не только в выводе."
	})
	t.Fatal(message)
	return ""
}

// Open открывает базу для проверок и закрывает её после теста.
func Open(t *testing.T) *store.Store {
	t.Helper()
	db, err := store.Open(context.Background(), URL(t))
	if err != nil {
		t.Fatalf("подключение к тестовой базе: %v", err)
	}
	t.Cleanup(db.Close)
	return db
}
