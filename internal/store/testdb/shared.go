package testdb

import (
	"context"
	"sync"
	"testing"

	"github.com/konkov/agile/internal/store"
)

var (
	sharedOnce sync.Once
	sharedDB   *store.Store
	sharedErr  error
)

// Shared возвращает один пул на весь прогон пакета.
//
// Раньше каждая проверка открывала свой: `store.Open` поднимает пул
// с MinConns = 2, то есть два настоящих соединения заводятся и рвутся
// на каждый тест. В пакете доски таких тестов полторы сотни, и время
// уходило не в проверяемое, а в рукопожатия.
//
// Делить пул между проверками безопасно ровно потому, что область
// видимости выставляется транзакционным `set_config` (третий довод
// `true`): соединение возвращается в пул чистым, и следующая проверка
// не наследует чужого арендатора. Будь это иначе, общий пул стал бы
// не ускорением, а способом увидеть чужие данные — то есть проверкой,
// проверяющей не то.
//
// Пул не закрывается: он живёт до конца тестового бинарника, и закрыть
// его после первой же проверки значило бы оставить остальные без базы.
func Shared(t *testing.T) *store.Store {
	t.Helper()
	url := URL(t)
	sharedOnce.Do(func() {
		sharedDB, sharedErr = store.Open(context.Background(), url)
	})
	if sharedErr != nil {
		t.Fatalf("подключение к тестовой базе: %v", sharedErr)
	}
	return sharedDB
}
