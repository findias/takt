// NotContainer — условие «карточка c — не контейнер» для запросов,
// где карточка названа псевдонимом c (этап 32.6).
//
// Контейнер — карточка с внуками, то есть эпик: его работа уже посчитана
// частями. Поэтому он не занимает места в лимите колонки и не входит
// в метрики потока — эпик, шедший три месяца, иначе раздувал бы
// 85-ю процентиль, а по ней считаются обещание доски и прогноз.
// Фича с задачами (без внуков) остаётся работой.
//
// Контейнер определяется деревом в момент счёта, а не полем: появились
// внуки — стал контейнером, ушли — снова работа. Дерево — то, что видит
// спрашивающий: внуки на недоступной ему доске отсекаются политиками,
// и для него такой эпик остаётся работой. Обходить политики ради
// редкого случая значило бы ослабить изоляцию.
//
// Одна строка на все запросы — доске, метрикам и выгрузке негде
// разойтись в том, что считать контейнером.
const NotContainer = `not exists (
	select 1 from card_links ck1
	  join cards ckm on ckm.id = ck1.to_card and ckm.archived_at is null
	  join card_links ck2 on ck2.from_card = ckm.id and ck2.kind = 'subtask'
	  join cards ckg on ckg.id = ck2.to_card and ckg.archived_at is null
	 where ck1.from_card = c.id and ck1.kind = 'subtask')`
