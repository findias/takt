// Миграция обязана быть совместимой с предыдущей версией приложения.
//
// Обещание это никем не давалось и ничем не проверялось, а требуется оно
// устройством выкладки: миграция идёт хуком `pre-upgrade`, то есть
// до замены подов. Между её завершением и выкаткой новой версии старый
// код работает на новой схеме — секунды при удачном раскладе, минуты
// при неудачном, и всё время выкладки, если она застряла. Переименование
// колонки, снятие умолчания, удаление ставшего лишним ломают в это окно
// каждый запрос, и ломают у заказчика, а не у нас.
//
// Оттуда же второе, и оно хуже: `helm rollback` вернёт поды, но не схему.
// «Откатились» окажется неправдой ровно в тот раз, когда миграция была
// несовместимой, — то есть в единственный, когда откат и понадобился.
//
// Поэтому опасные операции не запрещены намертво, а требуют названной
// причины прямо в файле. Правило то же, что у остальных проверок здесь:
// решение, принятое молча, отличается от решения, принятого вслух,
// именно тем, что второе видно в ревью.
//
// Порядок для того, что всё-таки надо убрать: версия N перестаёт
// использовать колонку, выкатывается, и только версия N+1 её удаляет.
// Тогда старый код в окне выкладки уже без неё.

// сПравила — номер, с которого действует проверка. До него миграции
// писались, когда продукт ещё никому не ставили: у первой чужой
// установки нет ни одной из этих версий, и переписывать историю ради
// зелёного прогона значило бы врать о прошлом.
const сПравила = 51

// опасные — операции, ломающие предыдущую версию приложения, и то,
// чем именно. Проверка — функция, а не одно выражение: у «not null
// без умолчания» условие составное, а заглядывания вперёд в здешних
// регулярных выражениях нет.
var опасные = []struct {
	имя  string
	есть func(код string) bool
	чем  string
}{
	{
		"drop column",
		совпадает(`(?i)\bdrop\s+column\b`),
		"старый код читает и пишет эту колонку — в окне выкладки каждый его запрос отказывает",
	},
	{
		"rename",
		совпадает(`(?i)\balter\s+table\s+\S+\s+rename\b`),
		"переименование — то же удаление для старого кода: он ходит по прежнему имени",
	},
	{
		"drop table",
		совпадает(`(?i)\bdrop\s+table\b`),
		"старый код ходит в эту таблицу",
	},
	{
		"add column … not null без default",
		добавляетОбязательнуюБезУмолчания,
		"старый код вставляет строки без этой колонки, и вставка отказывает; нужен default",
	},
	{
		"set not null",
		совпадает(`(?i)\balter\s+column\s+\S+\s+set\s+not\s+null\b`),
		"старый код мог писать сюда NULL",
	},
	{
		"drop default",
		совпадает(`(?i)\balter\s+column\s+\S+\s+drop\s+default\b`),
		"старый код полагался на умолчание и не заполняет колонку сам",
	},
}

func совпадает(выражение string) func(string) bool {
	re := regexp.MustCompile(выражение)
	return re.MatchString
}

var добавлениеКолонки = regexp.MustCompile(`(?is)\badd\s+column\b(.*?)(?:,\s*add\b|;)`)

// Новая обязательная колонка без умолчания — самая незаметная из
// опасных: миграция проходит, схема выглядит правильной, а ломается
// вставка в старом коде, который об этой колонке не знает.
func добавляетОбязательнуюБезУмолчания(код string) bool {
	for _, кусок := range добавлениеКолонки.FindAllStringSubmatch(код, -1) {
		объявление := strings.ToLower(кусок[1])
		if strings.Contains(объявление, "not null") && !strings.Contains(объявление, "default") {
			return true
		}
	}
	return false
}

// маркер — как объявляется осознанное исключение. Требуется текст
// после двоеточия: маркер без объяснения — это тот же молчаливый
// пропуск, только с ключевым словом.
var маркер = regexp.MustCompile(`(?i)--\s*ломает старую версию:\s*(\S.*)`)

func TestMigrationsStayCompatibleWithThePreviousVersion(t *testing.T) {
	файлы, err := fs.Glob(migrations.FS, "*.sql")
	if err != nil {
		t.Fatal(err)
	}
	sort.Strings(файлы)
	if len(файлы) == 0 {
		t.Fatal("миграций не найдено — проверка ничего не проверяет")
	}

	проверено := 0
	for _, файл := range файлы {
		номер, ok := номерМиграции(файл)
		if !ok {
			t.Errorf("имя миграции не начинается с номера: %s", файл)
			continue
		}
		if номер < сПравила {
			continue
		}
		проверено++

		raw, err := fs.ReadFile(migrations.FS, файл)
		if err != nil {
			t.Fatal(err)
		}
		объявлено := маркер.FindSubmatch(raw)
		код := безКомментариев(string(raw))

		for _, опасная := range опасные {
			if !опасная.есть(код) {
				continue
			}
			if объявлено == nil {
				t.Errorf("%s: %s — %s.\n"+
					"Так можно, но вслух: строка «-- ломает старую версию: <почему это допустимо>» "+
					"в самом файле. Обычный порядок другой: версия N перестаёт этим пользоваться, "+
					"выкатывается, и только версия N+1 удаляет.",
					файл, опасная.имя, опасная.чем)
			}
		}
	}
	if проверено == 0 {
		t.Logf("миграций с номером %d и выше пока нет — проверять нечего", сПравила)
	}
}

// Номер миграции — часть её имени, и он же порядок применения. Дырка
// или повтор означают, что две ветки завели миграцию с одним номером,
// и у кого-то из двоих она не применится вовсе.
func TestMigrationNumbersAreUniqueAndDense(t *testing.T) {
	файлы, err := fs.Glob(migrations.FS, "*.sql")
	if err != nil {
		t.Fatal(err)
	}
	номера := map[int]string{}
	for _, файл := range файлы {
		номер, ok := номерМиграции(файл)
		if !ok {
			t.Errorf("имя миграции не начинается с номера: %s", файл)
			continue
		}
		if прежний, занят := номера[номер]; занят {
			t.Errorf("номер %d занят дважды: %s и %s — у кого-то из двоих миграция не применится",
				номер, прежний, файл)
		}
		номера[номер] = файл
	}
	for n := 1; n <= len(номера); n++ {
		if _, есть := номера[n]; !есть {
			t.Errorf("в цепочке нет номера %d: пропуск означает, что миграцию удалили задним числом", n)
		}
	}
}

func номерМиграции(файл string) (int, bool) {
	имя := path.Base(файл)
	if len(имя) < 4 {
		return 0, false
	}
	n, err := strconv.Atoi(имя[:4])
	if err != nil {
		return 0, false
	}
	return n, true
}

// безКомментариев убирает строчные комментарии: в них опасные слова
// стоят законно — там их как раз и объясняют.
func безКомментариев(sql string) string {
	out := make([]string, 0, 64)
	for _, строка := range strings.Split(sql, "\n") {
		if i := strings.Index(строка, "--"); i >= 0 {
			строка = строка[:i]
		}
		out = append(out, строка)
	}
	return strings.Join(out, "\n")
}
