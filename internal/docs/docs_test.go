package docs_test

import (
	"os"
	"path/filepath"
	"regexp"
	"runtime"
	"strings"
	"testing"
)

// Документация сверяется с продуктом, а не живёт рядом с ним.
//
// Цена документа, который никто не сверяет, в этом проекте уже измерена:
// три сверки подряд нашли двадцать шесть расхождений, и почти каждое —
// обещание, жившее только в тексте. Документация для пользующихся
// врёт по-своему: она называет кнопку, которой нет, вкладку, которую
// переименовали, роль, которой не бывает. Читающий при этом решает,
// что не понял, — и идёт спрашивать.
//
// Проверяется то, что можно проверить дословно: подписи в «ёлочках»,
// названия ролей и видимостей, ссылки на файлы и упомянутые команды.
// Смысл текста не проверяется ничем и проверяться не может — это
// сказано вслух, чтобы зелёный прогон не читался как «документация
// верна».

func корень(t *testing.T) string {
	t.Helper()
	_, файл, _, ok := runtime.Caller(0)
	if !ok {
		t.Fatal("не найти собственный путь")
	}
	return filepath.Join(filepath.Dir(файл), "..", "..")
}

// Все документы, включая переводы: подкаталоги обходятся тоже.
// Первая редакция читала только `docs/*.md`, и английские страницы
// не проверялись ничем — ни ссылки, ни подписи. Перевод без проверки
// расходится с продуктом быстрее оригинала: его перечитывают реже.
func документы(t *testing.T) map[string]string {
	t.Helper()
	out := map[string]string{}
	база := filepath.Join(корень(t), "docs")
	err := filepath.Walk(база, func(путь string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		if info.IsDir() || !strings.HasSuffix(путь, ".md") {
			return nil
		}
		raw, err := os.ReadFile(путь)
		if err != nil {
			return err
		}
		относительный, _ := filepath.Rel(корень(t), путь)
		out[filepath.ToSlash(относительный)] = string(raw)
		return nil
	})
	if err != nil {
		t.Fatalf("документации нет вовсе: %v", err)
	}
	if len(out) == 0 {
		t.Fatal("в docs/ нет ни одного документа — проверка ничего не проверяет")
	}
	return out
}

// клиент — подписи интерфейса, а не весь исходный текст.
//
// Первая редакция сверяла со всем содержимым `.tsx`, и для русских
// подписей этого хватало: по-русски в коде написаны только они
// и комментарии. Для английских — нет: «Create» находится в любом
// файле, где есть React, и переведённая кнопка проходила проверку.
//
// Поэтому берутся строковые литералы и текст между тегами — то, что
// человек и правда видит.
func клиент(t *testing.T) string {
	t.Helper()
	var b strings.Builder
	база := filepath.Join(корень(t), "web", "src")
	err := filepath.Walk(база, func(путь string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		if info.IsDir() || !(strings.HasSuffix(путь, ".tsx") || strings.HasSuffix(путь, ".ts")) {
			return nil
		}
		raw, err := os.ReadFile(путь)
		if err != nil {
			return err
		}
		текст := string(raw)
		for _, m := range литерал.FindAllStringSubmatch(текст, -1) {
			b.WriteString(m[1] + m[2] + m[3] + "\n")
		}
		for _, m := range междуТегами.FindAllStringSubmatch(текст, -1) {
			b.WriteString(strings.Join(strings.Fields(m[1]), " ") + "\n")
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	// Справка внутри приложения — тоже интерфейс, но её подписи
	// («Что нового», «Для администратора установки») живут на сервере,
	// в internal/help, а не в клиенте.
	справка, err := filepath.Glob(filepath.Join(корень(t), "internal", "help", "*.go"))
	if err != nil {
		t.Fatal(err)
	}
	for _, путь := range справка {
		if strings.HasSuffix(путь, "_test.go") {
			continue
		}
		raw, err := os.ReadFile(путь)
		if err != nil {
			t.Fatal(err)
		}
		for _, m := range литерал.FindAllStringSubmatch(string(raw), -1) {
			b.WriteString(m[1] + m[2] + m[3] + "\n")
		}
	}
	return b.String()
}

// В ёлочках в документации стоят подписи интерфейса: «Сохранить вид»,
// «Структура», «Доступ». Если такой подписи в клиенте нет — либо её
// переименовали, либо документация выдумала.
// Строковый литерал в трёх видах кавычек и текст между тегами JSX:
// вместе это и есть то, что показывается человеку.
var (
	литерал = regexp.MustCompile("\"([^\"\\n]*)\"|'([^'\\n]*)'|`([^`]*)`")
	// Перенос строки внутри разметки — вёрстка, а не часть подписи:
	// «Сохранить вид» в JSX стоит на своей строке между тегами.
	междуТегами = regexp.MustCompile(`>([^<>{}]{2,80})<`)
)

var вЁлочках = regexp.MustCompile(`«([^»]{2,40})»`)

// Название соседней страницы в ссылке: «[«Справочник»](справочник.md)».
// Это заголовок документа, а не элемент интерфейса, и сверять его
// с подписями клиента незачем.
var ссылкаСЁлочками = regexp.MustCompile(`\[«[^»]+»\]\([^)]+\)`)

// Подписью считается то, что начинается с заглавной буквы: в ёлочках
// стоят и цитаты («что мы обещали и на когда»), и они — речь, а не
// элементы интерфейса. Правило грубое, зато не требует списка
// исключений, который сам стал бы местом, где прячут расхождения.
func подпись(строка string) bool {
	руны := []rune(строка)
	return len(руны) > 0 && строка != strings.ToLower(строка) &&
		string(руны[0]) == strings.ToUpper(string(руны[0]))
}

func TestDocsNameOnlyRealLabels(t *testing.T) {
	текст := клиент(t)
	for файл, содержимое := range документы(t) {
		// Ёлочки внутри ссылки — название соседней страницы, а не
		// подпись в интерфейсе: «[«Справочник»](справочник.md)».
		без := ссылкаСЁлочками.ReplaceAllString(содержимое, "")
		for _, m := range вЁлочках.FindAllStringSubmatch(без, -1) {
			// Перенос строки в markdown — верстка, а не часть подписи.
			название := strings.Join(strings.Fields(m[1]), " ")
			if !подпись(название) {
				continue
			}
			// Подпись может быть собрана из кусков (`Завести карточку
			// в «Очередь»`), поэтому ищем вхождение, а не равенство.
			if !strings.Contains(текст, название) {
				t.Errorf("%s называет «%s», а в интерфейсе такой подписи нет: "+
					"её переименовали или её не было", файл, название)
			}
		}
	}
}

// Английские страницы называют кнопки так, как их показывает английский
// интерфейс, жирным: **Save view**. Проверка та же, что у ёлочек:
// подписи в клиенте нет — её переименовали или документация выдумала.
//
// Подписью считается жирное с заглавной буквы. Жирное перед тире —
// термин списка («**Create a board** — on the main screen»), а жирное
// со знаком препинания на конце — выделенная фраза, а не кнопка.
// Пары ищутся все подряд, даже в один знак (**…**): пропущенная
// короткая пара сбивала счёт, и подписью становился текст между двумя
// выделениями.
var жирное = regexp.MustCompile(`\*\*([^*\n]+?)\*\*( —)?`)

// Страницы для работающих на доске: на страницах для ставящих жирным
// выделяют мысли, а не кнопки.
var страницыДляРаботающих = []string{
	"docs/overview.md", "docs/quickstart.md", "docs/howto.md",
	"docs/reference.md", "docs/cheatsheet.md", "docs/glossary.md",
}

func TestEnglishDocsNameOnlyRealLabels(t *testing.T) {
	текст := клиент(t)
	все := документы(t)
	for _, файл := range страницыДляРаботающих {
		содержимое, ok := все[файл]
		if !ok {
			t.Fatalf("страницы %s нет — список проверки устарел", файл)
		}
		for _, m := range жирное.FindAllStringSubmatch(содержимое, -1) {
			название := m[1]
			// Знак препинания на конце — выделенная фраза; кроме «?»:
			// им кончается подпись поля «What needs doing?».
			if m[2] != "" || strings.ContainsAny(название[len(название)-1:], ".,;:!") || !подпись(название) {
				continue
			}
			if !strings.Contains(текст, название) {
				t.Errorf("%s называет **%s**, а в интерфейсе такой подписи нет: "+
					"её переименовали или её не было", файл, название)
			}
		}
	}
}

// Ссылки на файлы обязаны вести на существующее: документация читается
// целиком редко, а по ссылкам ходят всегда.
var ссылка = regexp.MustCompile(`\]\(([^)#]+)\)`)

func TestDocsLinksLeadSomewhere(t *testing.T) {
	for файл, содержимое := range документы(t) {
		for _, m := range ссылка.FindAllStringSubmatch(содержимое, -1) {
			цель := m[1]
			if strings.HasPrefix(цель, "http") {
				continue
			}
			путь := filepath.Join(корень(t), filepath.Dir(файл), цель)
			if _, err := os.Stat(путь); err != nil {
				t.Errorf("%s ссылается на %s, которого нет", файл, цель)
			}
		}
	}
}

// Названные пути API и подкоманды обязаны существовать: «запустите
// takt doctor» в документе к продукту без такой команды — это
// потерянный час того, кто читает.
func TestDocsMentionRealCommandsAndPaths(t *testing.T) {
	main, err := os.ReadFile(filepath.Join(корень(t), "cmd", "takt", "main.go"))
	if err != nil {
		t.Fatal(err)
	}
	маршруты := ""
	каталог := filepath.Join(корень(t), "internal", "httpapi")
	записи, err := os.ReadDir(каталог)
	if err != nil {
		t.Fatal(err)
	}
	for _, з := range записи {
		if !strings.HasSuffix(з.Name(), ".go") || strings.Contains(з.Name(), "_test") {
			continue
		}
		raw, _ := os.ReadFile(filepath.Join(каталог, з.Name()))
		маршруты += string(raw)
	}

	команда := regexp.MustCompile("`takt ([a-z]+)`")
	адрес := regexp.MustCompile("`(/(?:api|scim)/[a-zA-Z0-9/_{}.-]*)`")
	for файл, содержимое := range документы(t) {
		for _, m := range команда.FindAllStringSubmatch(содержимое, -1) {
			if !strings.Contains(string(main), `case "`+m[1]+`"`) &&
				!strings.Contains(string(main), `command == "`+m[1]+`"`) {
				t.Errorf("%s зовёт `takt %s`, а такой подкоманды нет", файл, m[1])
			}
		}
		for _, m := range адрес.FindAllStringSubmatch(содержимое, -1) {
			// Из адреса берём начало до первого параметра: документация
			// называет семейство («/scim/v2»), а не конкретный маршрут.
			начало := strings.SplitN(strings.TrimPrefix(m[1], "/api/v1"), "{", 2)[0]
			начало = strings.TrimSuffix(начало, "/")
			if начало == "" || !strings.Contains(маршруты, начало) {
				t.Errorf("%s называет адрес %s, которого в маршрутах нет", файл, m[1])
			}
		}
	}
}

// Роли и видимости названы теми же словами, что в интерфейсе:
// «Наблюдатель области» и «Наблюдающий» — разница, из-за которой
// человек ищет несуществующую настройку.
func TestDocsUseTheSameWordsAsTheProduct(t *testing.T) {
	// Словарь — раздел `names` русского каталога: с выбором языка
	// (ROADMAP 30.2) слова переехали туда из shared/api/names.ts.
	raw, err := os.ReadFile(filepath.Join(корень(t), "web", "src", "shared", "i18n", "ru.ts"))
	if err != nil {
		t.Fatal(err)
	}
	начало := strings.Index(string(raw), "\n  names: {")
	if начало < 0 {
		t.Fatal("в русском каталоге нет раздела names — сверять не с чем")
	}
	конец := strings.Index(string(raw)[начало:], "\n  },")
	словарь := string(raw)[начало : начало+конец]
	слова := regexp.MustCompile(`'([А-ЯЁ][^']+)'`).FindAllStringSubmatch(словарь, -1)
	if len(слова) == 0 {
		t.Fatal("словарь названий пуст — сверять не с чем")
	}

	// Обратная сторона: документы обязаны пользоваться этими словами,
	// а не своими. Проверяем, что каждое слово словаря где-то в docs/
	// встречается: роль или видимость, о которой не сказано нигде,
	// означает дыру в документации, а не лишнее слово в коде.
	весь := ""
	for _, содержимое := range документы(t) {
		весь += содержимое
	}
	for _, m := range слова {
		if !strings.Contains(весь, m[1]) {
			t.Errorf("документация нигде не говорит про «%s», хотя продукт это показывает", m[1])
		}
	}
}

// Перевод и оригинал ссылаются друг на друга.
//
// Страница на другом языке, о которой не сказано на первой, — это
// страница, которую не найдут: её адрес знает только тот, кто её
// собирал. Проверка следит за обеими сторонами: русский обзор ведёт
// на английский, английский — обратно.
func TestTranslationsAreReachableFromBothSides(t *testing.T) {
	документы := документы(t)
	английский, ok := документы["docs/overview.md"]
	if !ok {
		t.Fatal("обзора на английском нет")
	}
	русский, ok := документы["docs/ru/индекс.md"]
	if !ok {
		t.Fatal("обзора на русском нет")
	}
	if !strings.Contains(английский, "ru/индекс.md") && !strings.Contains(английский, "По-русски") {
		t.Error("английский обзор не ведёт на русскую страницу: её не найдут")
	}
	if !strings.Contains(русский, "overview.md") {
		t.Error("русский обзор не ведёт обратно на английскую документацию")
	}
}
