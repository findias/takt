// Отрисовка в HTML: что именно она обязана делать.
//
// Проверяется не «похоже на markdown», а те четыре вещи, из-за которых
// собранная страница врёт: заголовок теряется, таблица рассыпается,
// ссылка ведёт на исходник вместо соседней страницы, а разметка внутри
// кода разбирается как разметка.

func TestRenderKeepsStructure(t *testing.T) {
	заголовок, тело := docs.Отрисовать("# Заголовок страницы\n\n" +
		"Абзац с **жирным** и `кодом`.\n\n" +
		"## Раздел\n\n" +
		"- первый пункт\n- второй пункт\n\n" +
		"| № | Что | Чем |\n| --- | --- | --- |\n| Т1 | Требование | `файл.go` |\n")
	if заголовок != "Заголовок страницы" {
		t.Errorf("заголовок страницы %q — по нему называется вкладка браузера", заголовок)
	}
	для := map[string]string{
		"<h1>":           "заголовок первого уровня",
		"<h2>":           "заголовок второго уровня",
		"<strong>жирным": "жирный",
		"<code>кодом":    "код в строке",
		"<ul>":           "список",
		"<table>":        "таблица",
		"<th>№</th>":     "шапка таблицы",
		"<td>Т1</td>":    "тело таблицы",
	}
	for что, зачем := range для {
		if !strings.Contains(тело, что) {
			t.Errorf("в отрисованном нет %s (%s)", что, зачем)
		}
	}
	// Разделитель таблицы — разметка, а не строка данных.
	if strings.Contains(тело, "---") {
		t.Error("разделитель таблицы попал в отрисованное как данные")
	}
}

func TestRenderLinksToNeighbouringPages(t *testing.T) {
	_, тело := docs.Отрисовать("Смотри [для владельца](для-владельца.md) и [README](../README.md).")
	if !strings.Contains(тело, `href="для-владельца.html"`) {
		t.Errorf("ссылка ведёт на исходник, а не на соседнюю страницу: %s", тело)
	}
	if !strings.Contains(тело, `href="README.html"`) {
		t.Errorf("ссылка через каталог не переведена: %s", тело)
	}
}

func TestRenderEscapesWhatItShould(t *testing.T) {
	_, тело := docs.Отрисовать("Текст с <script>alert(1)</script> и `<b>кодом</b>`.")
	if strings.Contains(тело, "<script>") {
		t.Error("разметка из исходника уехала в страницу как разметка")
	}
	if !strings.Contains(тело, "&lt;b&gt;кодом&lt;/b&gt;") {
		t.Errorf("разметка внутри кода должна остаться видимой: %s", тело)
	}
}

// Страница обязана быть самодостаточной.
//
// Её читают там, где её открыли: в закрытом контуре, с флешки,
// из папки на диске. Ссылка на чужой адрес там показывает голый текст,
// а в худшем случае сообщает наружу, что страницу открыли.
func TestBuiltPagesAskNothingFromTheInternet(t *testing.T) {
	for имя, содержимое := range собранные(t) {
		for _, чужое := range []string{"src=\"http", "href=\"http", "//fonts.", "<script"} {
			if strings.Contains(содержимое, чужое) {
				t.Errorf("%s тянет чужое (%s): страница обязана открываться без сети", имя, чужое)
			}
		}
	}
}

// Собранное — из сегодняшнего исходника, а не из вчерашнего.
//
// Второй набор текстов, набранный в HTML руками, разойдётся с первым
// в тот же день и разойдётся молча: у текста нет прогона, который
// упадёт. Проверка пересобирает страницы во временный каталог
// и сверяет с лежащими рядом.
func TestBuiltPagesMatchTheirSources(t *testing.T) {
	времянка := t.TempDir()
	cmd := exec.Command("go", "run", "./cmd/docs")
	cmd.Dir = корень(t)
	cmd.Env = append(os.Environ(), "DOCS_OUT="+времянка)
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("сборка документации не прошла: %v\n%s", err, out)
	}
	for имя, лежит := range собранные(t) {
		свежее, err := os.ReadFile(filepath.Join(времянка, имя))
		if err != nil {
			t.Errorf("%s собран из исходника, которого больше нет", имя)
			continue
		}
		if безВерсии(string(свежее)) != безВерсии(лежит) {
			t.Errorf("%s разошёлся с исходником: пересоберите `make docs` "+
				"и не правьте HTML руками", имя)
		}
	}
}

// Версия в подписи меняется с каждым коммитом: `git describe` даёт
// новый хеш, и страница, собранная вчера, отличается от сегодняшней
// одной строкой. Сравнивать её незачем — проверка следит за текстом,
// а не за тем, когда его собрали; иначе она краснеет после каждого
// коммита и приучает пересобирать не глядя.
// Ловится подпись в подвале, а не любое слово «версия»: оно
// встречается и в тексте документов, и вырезать все такие места
// значило бы перестать сверять целые абзацы. Поэтому выражение
// привязано к самому подвалу, а не к виду версии.
//
// Прежде оно ловило вид — «v0.1.0-9-g003ba51-dirty» или «не задана», —
// и на этом сломалось: `actions/checkout` берёт неглубокий клон без
// тегов, `git describe --tags --always` отдаёт голый хеш, под вид
// он не подходил, и в CI расходились все страницы разом. Ошибка была
// не в них: сверять с тегами в клоне без тегов нечего.
// Мест два: подвал каждой страницы и врезка на сводной «all.html»,
// где версия стоит в тексте, а не в подвале.
var подписьВерсии = regexp.MustCompile(
	`(<footer>Takt, (?:version|версия) ` +
		`|Every section in one file\. Version )(?:не задана|[^\s<]+)`)

func безВерсии(страница string) string {
	return подписьВерсии.ReplaceAllString(страница, "${1}…")
}

func собранные(t *testing.T) map[string]string {
	t.Helper()
	каталог := filepath.Join(корень(t), "docs", "html")
	записи, err := os.ReadDir(каталог)
	if err != nil {
		t.Fatalf("собранной документации нет: %v", err)
	}
	out := map[string]string{}
	for _, з := range записи {
		if !strings.HasSuffix(з.Name(), ".html") {
			continue
		}
		raw, err := os.ReadFile(filepath.Join(каталог, з.Name()))
		if err != nil {
			t.Fatal(err)
		}
		out[з.Name()] = string(raw)
	}
	if len(out) == 0 {
		t.Fatal("в docs/html нет ни одной страницы")
	}
	return out
}

// Документация обязана собираться из одного репозитория.
//
// Снимки экранов делает `make screens` — стендом и настоящим браузером,
// в `web/screenshots`, и каталог этот в поставку не входит. Сборка
// брала их только оттуда, и на чистом клоне разваливалась: `make check`
// падал на `TestBuiltPagesMatchTheirSources` сообщением про
// несуществующий `03-доска.png`. Локально этого было не видно — снимки
// лежали, — а в CI и в закрытом контуре не проходило ничего.
//
// Поэтому у сборки есть запасной источник: снимки, уже лежащие
// в `docs/снимки`. Работает он ровно до тех пор, пока там лежит всё,
// на что документация ссылается, — это и проверяется. Иначе запасной
// источник тихо перестанет быть запасным, и поломка вернётся тем же
// способом: зелено на своей машине, красно у всех остальных.
func TestScreenshotsShipWithTheDocs(t *testing.T) {
	ссылка := regexp.MustCompile(`!\[[^\]]*\]\(([^)]+)\)`)
	страницы, err := filepath.Glob(filepath.Join(корень(t), "docs", "*.md"))
	if err != nil {
		t.Fatal(err)
	}
	английские, err := filepath.Glob(filepath.Join(корень(t), "docs", "en", "*.md"))
	if err != nil {
		t.Fatal(err)
	}
	страницы = append(страницы, английские...)
	if len(страницы) == 0 {
		t.Fatal("в docs не нашлось ни одной страницы — " +
			"проверка бы молча ничего не проверяла")
	}

	нашлось := 0
	for _, путь := range страницы {
		raw, err := os.ReadFile(путь)
		if err != nil {
			t.Fatal(err)
		}
		for _, найдено := range ссылка.FindAllStringSubmatch(string(raw), -1) {
			адрес := найдено[1]
			if strings.Contains(адрес, "://") {
				continue
			}
			нашлось++
			картинка := filepath.Join(filepath.Dir(путь), адрес)
			сведения, err := os.Stat(картинка)
			if err != nil {
				t.Errorf("%s ссылается на %s, которого в репозитории нет: "+
					"страница откроется с битой картинкой, а сборка "+
					"документации упадёт на чистом клоне",
					отКорня(t, путь), адрес)
				continue
			}
			if сведения.Size() == 0 {
				t.Errorf("%s ссылается на пустой %s", отКорня(t, путь), адрес)
			}
		}
	}
	if нашлось == 0 {
		t.Error("ни одна страница не ссылается на картинку — " +
			"либо снимки ушли из документации, либо проверка ищет не то")
	}
}

func отКорня(t *testing.T, путь string) string {
	t.Helper()
	короткий, err := filepath.Rel(корень(t), путь)
	if err != nil {
		return путь
	}
	return короткий
}
