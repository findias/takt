// Отрисовка документации в HTML.
//
// Источник один — те же файлы `.md`, из которых читают в репозитории.
// Второй набор текстов, набранный в HTML руками, разошёлся бы с первым
// в тот же день, и разошёлся бы молча: у текста нет прогона, который
// упадёт.
//
// Разметка своя, без библиотеки, и это не гордость, а правило проекта:
// установка не должна требовать интернета, а зависимость ради разбора
// заголовков и таблиц — плата за то, что делается двумя сотнями строк.
// Разбирается ровно то, что встречается в наших документах; всё
// остальное отрисовщик оставляет как есть, а не догадывается.
package docs

import (
	"fmt"
	"html"
	"regexp"
	"strings"
)

// Страница — один документ: имя файла, заголовок и готовый HTML.
type Страница struct {
	Файл string
	// Заголовок — первый `#` документа: им называется вкладка браузера.
	Заголовок string
	// Имя — короткое название раздела в оглавлении. Отличается
	// от заголовка намеренно: «Доска» в заголовке обзора и в заголовке
	// руководства по установке — одно слово, а разделы разные.
	Имя string
	// Язык страницы: «ru» или «en». Объявляется в разметке — по нему
	// диктор выбирает произношение, а браузер перенос слов.
	Язык string
	HTML string
}

var (
	заголовок   = regexp.MustCompile(`^(#{1,4})\s+(.*)$`)
	списокТире  = regexp.MustCompile(`^[-*]\s+(.*)$`)
	списокЧисло = regexp.MustCompile(`^\d+\.\s+(.*)$`)
	разделитель = regexp.MustCompile(`^\|[\s:|-]+\|$`)
	ссылка      = regexp.MustCompile(`\[([^\]]+)\]\(([^)]+)\)`)
	картинка    = regexp.MustCompile(`^!\[([^\]]*)\]\(([^)]+)\)\s*$`)
	жирный      = regexp.MustCompile(`\*\*([^*]+)\*\*`)
	код         = regexp.MustCompile("`([^`]+)`")
	// Явный якорь — комментарием строкой выше заголовка:
	// `<!-- anchor: find-card -->`. Нужен там, где на раздел ссылается
	// приложение (справка с экрана, ROADMAP 30.3): якорь из текста
	// менялся бы с каждой правкой формулировки и на каждом языке свой,
	// а явный — один у оригинала и перевода. Комментарием, а не
	// `{#id}` в самом заголовке: `.md` читают и на GitHub, и там
	// такая приписка видна как текст.
	явныйЯкорь = regexp.MustCompile(`^<!--\s*anchor:\s*([a-z0-9-]+)\s*-->$`)
	неСлово    = regexp.MustCompile(`[^\p{L}\p{N}]+`)
)

// якорьИзТекста — идентификатор раздела без явного якоря: годится для
// оглавления страницы, но не для ссылок из приложения — он меняется
// вместе с текстом заголовка.
func якорьИзТекста(текст string) string {
	простой := strings.ToLower(обычныйТекст(текст))
	return strings.Trim(неСлово.ReplaceAllString(простой, "-"), "-")
}

// Отрисовать переводит markdown в HTML тела страницы, которая ляжет
// в корень сборки.
func Отрисовать(источник string) (заголовокСтраницы, тело string) {
	return отрисовать(источник, "")
}

// ОтрисоватьВложенную — то же для страницы, собираемой в подкаталог:
// переводы лежат в `ru/`, и путь к соседям у них свой.
func ОтрисоватьВложенную(источник string) (заголовокСтраницы, тело string) {
	return отрисовать(источник, "../")
}

// вверх — чем начинается ссылка на страницу вне своего каталога.
func отрисовать(источник, вверх string) (заголовокСтраницы, тело string) {
	строчный := func(текст string) string { return разметка(текст, вверх) }
	строки := strings.Split(источник, "\n")
	var out strings.Builder
	var список []string
	видСписка := ""
	var таблица [][]string
	вКоде := false
	var кодовый []string
	// Явный якорь, объявленный строкой выше, ждёт своего заголовка.
	следующийЯкорь := ""

	закрытьСписок := func() {
		if len(список) == 0 {
			return
		}
		fmt.Fprintf(&out, "<%s>\n", видСписка)
		for _, пункт := range список {
			fmt.Fprintf(&out, "<li>%s</li>\n", пункт)
		}
		fmt.Fprintf(&out, "</%s>\n", видСписка)
		список = nil
		видСписка = ""
	}
	закрытьТаблицу := func() {
		if len(таблица) == 0 {
			return
		}
		out.WriteString("<div class=\"tablewrap\"><table>\n<thead><tr>")
		for _, ячейка := range таблица[0] {
			fmt.Fprintf(&out, "<th>%s</th>", строчный(ячейка))
		}
		out.WriteString("</tr></thead>\n<tbody>\n")
		for _, строка := range таблица[1:] {
			out.WriteString("<tr>")
			for _, ячейка := range строка {
				fmt.Fprintf(&out, "<td>%s</td>", строчный(ячейка))
			}
			out.WriteString("</tr>\n")
		}
		out.WriteString("</tbody>\n</table></div>\n")
		таблица = nil
	}

	for i := 0; i < len(строки); i++ {
		строка := строки[i]

		if strings.HasPrefix(строка, "```") {
			if вКоде {
				fmt.Fprintf(&out, "<pre><code>%s</code></pre>\n",
					html.EscapeString(strings.Join(кодовый, "\n")))
				кодовый = nil
				вКоде = false
			} else {
				закрытьСписок()
				закрытьТаблицу()
				вКоде = true
			}
			continue
		}
		if вКоде {
			кодовый = append(кодовый, строка)
			continue
		}

		// Комментарий разметки — служебная строка, а не текст. Такой
		// строкой английская страница помечает, с какой русской она
		// переведена и в каком её состоянии (см. internal/translation);
		// показывать это читателю незачем.
		if обрезка := strings.TrimSpace(строка); strings.HasPrefix(обрезка, "<!--") &&
			strings.HasSuffix(обрезка, "-->") {
			if m := явныйЯкорь.FindStringSubmatch(обрезка); m != nil {
				следующийЯкорь = m[1]
			}
			continue
		}

		if strings.TrimSpace(строка) == "" {
			закрытьСписок()
			закрытьТаблицу()
			continue
		}

		// Картинка — отдельный блок, а не часть абзаца: подпись
		// в alt обязательна, иначе снимок для незрячего — пустое место
		// посреди текста.
		if m := картинка.FindStringSubmatch(строка); m != nil {
			закрытьСписок()
			закрытьТаблицу()
			fmt.Fprintf(&out, `<figure><img src="%s" alt="%s" loading="lazy">`+"\n"+
				`<figcaption>%s</figcaption></figure>`+"\n",
				html.EscapeString(m[2]), html.EscapeString(m[1]), html.EscapeString(m[1]))
			continue
		}

		if m := заголовок.FindStringSubmatch(строка); m != nil {
			закрытьСписок()
			закрытьТаблицу()
			уровень := len(m[1])
			id := следующийЯкорь
			следующийЯкорь = ""
			if id == "" {
				id = якорьИзТекста(m[2])
			}
			текст := строчный(m[2])
			if уровень == 1 && заголовокСтраницы == "" {
				заголовокСтраницы = обычныйТекст(m[2])
			}
			// У заголовка страницы якоря нет: ссылка на страницу и есть
			// ссылка на её начало.
			if уровень == 1 {
				fmt.Fprintf(&out, "<h1>%s</h1>\n", текст)
			} else {
				fmt.Fprintf(&out, "<h%d id=\"%s\">%s</h%d>\n", уровень, html.EscapeString(id), текст, уровень)
			}
			continue
		}

		// Таблица: строка, начинающаяся и кончающаяся вертикальной чертой.
		if strings.HasPrefix(строка, "|") && strings.HasSuffix(strings.TrimSpace(строка), "|") {
			закрытьСписок()
			if разделитель.MatchString(strings.TrimSpace(строка)) {
				continue
			}
			ячейки := strings.Split(strings.Trim(strings.TrimSpace(строка), "|"), "|")
			for j := range ячейки {
				ячейки[j] = strings.TrimSpace(ячейки[j])
			}
			таблица = append(таблица, ячейки)
			continue
		}
		закрытьТаблицу()

		if m := списокТире.FindStringSubmatch(строка); m != nil {
			if видСписка != "ul" {
				закрытьСписок()
				видСписка = "ul"
			}
			список = append(список, строчный(m[1]))
			continue
		}
		if m := списокЧисло.FindStringSubmatch(строка); m != nil {
			if видСписка != "ol" {
				закрытьСписок()
				видСписка = "ol"
			}
			список = append(список, строчный(m[1]))
			continue
		}
		// Продолжение пункта списка: строка с отступом под ним.
		if len(список) > 0 && strings.HasPrefix(строка, "  ") {
			список[len(список)-1] += " " + строчный(strings.TrimSpace(строка))
			continue
		}

		// Абзац: собираем до пустой строки, чтобы перенос в исходнике
		// не превращался в перенос на экране.
		абзац := []string{строка}
		for i+1 < len(строки) && strings.TrimSpace(строки[i+1]) != "" &&
			!strings.HasPrefix(строки[i+1], "#") && !strings.HasPrefix(строки[i+1], "|") &&
			!strings.HasPrefix(строки[i+1], "```") &&
			списокТире.FindStringSubmatch(строки[i+1]) == nil &&
			списокЧисло.FindStringSubmatch(строки[i+1]) == nil {
			i++
			абзац = append(абзац, строки[i])
		}
		fmt.Fprintf(&out, "<p>%s</p>\n", строчный(strings.Join(абзац, " ")))
	}
	закрытьСписок()
	закрытьТаблицу()
	return заголовокСтраницы, out.String()
}

// разметка разбирает то, что живёт внутри строки: код, жирный, ссылки.
// Порядок важен: сперва экранирование, потом код — иначе разметка
// внутри кода будет разобрана как разметка.
func разметка(текст, вверх string) string {
	экранированный := html.EscapeString(текст)
	экранированный = код.ReplaceAllString(экранированный, "<code>$1</code>")
	экранированный = жирный.ReplaceAllString(экранированный, "<strong>$1</strong>")
	экранированный = ссылка.ReplaceAllStringFunc(экранированный, func(m string) string {
		части := ссылка.FindStringSubmatch(m)
		цель := части[2]
		// Внутренние ссылки ведут на соседнюю страницу, а не на исходник.
		//
		// Каталогов в сборке два — корень и `ru/`, — а в исходниках три
		// уровня: корень репозитория, `docs/` и `docs/ru/`. Поэтому
		// «наверх» считается не по числу `../`, а по смыслу: всякий
		// выход из своего каталога ведёт в корень сборки, и сколько
		// там было точек, значения не имеет. Прежде срезалась ровно
		// одна пара — и «Read in English» с русской страницы вела
		// на `ru/overview.html`, которого нет.
		// Якорь отделяется до замены: `install.md#раздел` прежде
		// оставался как есть и вёл в собранной документации на файл,
		// которого там нет (найдено 26.09.2026 на ссылках «Что нового»).
		якорь := ""
		if i := strings.Index(цель, "#"); i > 0 && !strings.Contains(цель[:i], "://") {
			цель, якорь = цель[:i], цель[i:]
		}
		if strings.HasSuffix(цель, ".md") {
			// Файлы корня репозитория (CHANGELOG, REQUIREMENTS) ссылаются
			// на документацию через `docs/`, а в сборке она лежит в том же
			// каталоге, что и они. Сами страницы `docs/` так не ссылаются
			// никогда, поэтому приставка просто срезается.
			цель = strings.TrimPrefix(цель, "docs/")
			цель = strings.TrimSuffix(цель, ".md") + ".html"
			наружу := strings.HasPrefix(цель, "../")
			for strings.HasPrefix(цель, "../") {
				цель = strings.TrimPrefix(цель, "../")
			}
			if наружу {
				цель = вверх + цель
			}
		}
		цель += якорь
		return fmt.Sprintf(`<a href="%s">%s</a>`, цель, части[1])
	})
	return экранированный
}

func обычныйТекст(текст string) string {
	текст = код.ReplaceAllString(текст, "$1")
	return жирный.ReplaceAllString(текст, "$1")
}
