package httpapi

import "net/http"

// Заголовки безопасности на каждом ответе.
//
// Их отсутствие — первая строка любого отчёта о проверке ИБ, и это
// не придирка: без `nosniff` браузер угадывает тип по содержимому,
// без `frame-ancestors` страницу вставляют в чужую рамку и снимают
// нажатия, без политики содержимого внедрённый скрипт исполняется
// наравне со своим. Ставит их приложение, а не прокси: прокси у каждого
// заказчика свой, и обещание, которое держится настройкой на чужой
// стороне, — не обещание.
//
// Сюда же — а не в клиент через <meta>: заголовок накрывает и API,
// и ошибки, и статику, а разметка — только ту страницу, которая
// догрузилась.
const политика = "default-src 'self'; " +
	// Скрипты только свои: сборка Vite кладёт их файлами с отпечатком
	// в имени, ни одной строки в самой странице. Проверено тем, что
	// клиент вообще работает: при нарушении экран остаётся пустым.
	"script-src 'self'; " +
	// 'unsafe-inline' у стилей — вынужденно и названо вслух: четыре
	// места в клиенте задают стиль атрибутом (доля заполнения полосы,
	// сдвиг перетаскиваемой карточки), а атрибут стиля запрещается
	// той же директивой, что и <style>. Сузить это можно, только
	// переведя их на переменные CSS; пока не переведены — пусть будет
	// написано, а не умолчано.
	"style-src 'self' 'unsafe-inline'; " +
	"img-src 'self' data:; " +
	"font-src 'self'; " +
	// Поток изменений — тот же адрес, что и всё остальное.
	"connect-src 'self'; " +
	"form-action 'self'; " +
	"frame-ancestors 'none'; " +
	"base-uri 'none'; " +
	"object-src 'none'"

// secureHeaders — обёртка. Признак защищённости берётся оттуда же,
// откуда его берёт cookie: из схемы BASE_URL. Иначе установка по http
// получала бы HSTS и переставала открываться вовсе — на год.
func secureHeaders(secure bool, next http.Handler) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		h := w.Header()
		// Set, а не Add, и до обработчика: страница описания контракта
		// ставит свою политику, более строгую, и обязана её перебить.
		h.Set("Content-Security-Policy", политика)
		h.Set("X-Content-Type-Options", "nosniff")
		// Тот же смысл, что и frame-ancestors, для тех, кто читает
		// отчёт сканера, а не спецификацию: старый заголовок ищут
		// глазами, и его отсутствие объяснять дороже, чем поставить.
		h.Set("X-Frame-Options", "DENY")
		// Адрес карточки не должен уезжать на чужой сайт по ссылке
		// из обсуждения: в пути стоит идентификатор доски.
		h.Set("Referrer-Policy", "same-origin")
		h.Set("Permissions-Policy", "camera=(), microphone=(), geolocation=()")
		if secure {
			// Год — обычный срок. Без includeSubDomains и без preload
			// намеренно: и то и другое распространяется на соседние
			// имена заказчика, о которых мы ничего не знаем, и снять
			// это обратно нельзя быстрее, чем через срок.
			h.Set("Strict-Transport-Security", "max-age=31536000")
		}
		next.ServeHTTP(w, r)
	})
}
