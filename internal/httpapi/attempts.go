package httpapi

import (
	"net/http"
	"strconv"
	"strings"
)

// Перебор пароля.
//
// Предел частоты из контракта здесь не помогает вовсе: он считает только
// запросы с ключом, а у входа ключа нет. Да и повод другой — тот предел
// бережёт сервер от частых запросов, а перебор частым не выглядит:
// десять попыток в минуту не нагружают ничего и за сутки перебирают
// четырнадцать тысяч паролей.
//
// Считаем по адресу почты, а не по источнику запроса. Источника мы
// не знаем: приложение живёт за прокси, RemoteAddr у всех запросов один
// и тот же, и ведро по нему заперло бы вход всей организации из-за
// одного подбиральщика. Заголовок X-Forwarded-For годится ещё меньше:
// без настроенного доверенного прокси его пишет кто угодно, и ведро
// обходится сменой строки. Поэтому считается то, что перебирают, —
// адрес.
//
// Чего это не ловит: один пароль, разосланный по многим адресам. Такой
// перебор режется только источником, а источника у нас нет; записано
// в плане отдельно, вместе с ценой — настройкой доверенного прокси.
//
// Считаются неудачи, а не попытки, и успешный вход счёт обнуляет:
// человек, вспомнивший пароль с четвёртого раза, ждать не должен.
const (
	// Десять неудач подряд — с запасом для того, кто путает пароли,
	// и конец для перебора: дальше одна попытка в минуту.
	loginBurst  = 10.0
	loginPerSec = 1.0 / 60
)

// loginKey — ведро попыток для этого адреса. Приведение к нижнему
// регистру то же, что и при поиске пользователя: иначе счёт обходится
// заглавной буквой.
func loginKey(email string) string {
	return "вход:" + strings.ToLower(strings.TrimSpace(email))
}

// tooManyAttempts отвечает отказом, называя, когда повторять.
//
// Свой код, а не общий too_many_requests: клиент показывает это
// не как «сервер занят», а как «слишком много попыток», и разбирать
// разницу по тексту сообщения — способ сломать экран при первой правке
// формулировки.
func tooManyAttempts(w http.ResponseWriter, seconds int) {
	w.Header().Set("Retry-After", strconv.Itoa(seconds))
	writeCoded(w, http.StatusTooManyRequests, "too_many_attempts",
		"слишком много неудачных попыток входа — попробуйте через "+minutes(seconds))
}

// minutes — «через сколько» словами. Секунды человеку ни о чём
// не говорят, а «через минуту» говорит.
func minutes(seconds int) string {
	if seconds <= 60 {
		return "минуту"
	}
	return strconv.Itoa((seconds+59)/60) + " мин"
}
