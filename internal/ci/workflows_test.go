// Рабочие процессы GitHub проверяются на то, из-за чего они молчат.
//
// Молчащая проверка хуже упавшей: упавшая красная и её видно, а
// молчащая выглядит как «замечаний нет». Оба случая, которые здесь
// закреплены, случились на самом деле и оба выглядели именно так.
//
// Первый: у работы был русский идентификатор (`jobs.проверка`). GitHub
// принимает в идентификаторах только латиницу, цифру, дефис и
// подчёркивание; на кириллице он объявляет негодным весь файл и не
// запускает из него ничего — одной строкой «workflow file issue»
// и без единого шага. Выпуск по тегу так не собрался бы вовсе.
//
// Второй: у проверки безопасности стоял отбор по путям, и правка,
// до этих путей не достающая, ехала без разбора. Хуже того, проверку,
// промолчавшую по отбору, нельзя сделать обязательной: в списке
// предложения она не появляется вовсе и вечно «ожидается».

// Идентификаторы работ и входов: то, что позволяет GitHub. Латиница
// намеренно: русские имена живут в `name`, и там они законны.
var идентификатор = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_-]*$`)

// Проверки, которые обязаны просыпаться на каждое предложение правок.
// Список явный: новый файл рабочего процесса не всегда обязан быть
// проверкой предложения — выпуск, например, идёт по тегу.
var обязательные = map[string]string{
	"check.yml":    "обязательная проверка",
	"e2e.yml":      "сквозные сценарии",
	"security.yml": "безопасность",
}

func каталог(t *testing.T) string {
	t.Helper()
	_, файл, _, ok := runtime.Caller(0)
	if !ok {
		t.Fatal("не найти собственный путь")
	}
	return filepath.Join(filepath.Dir(файл), "..", "..", ".github", "workflows")
}

func процессы(t *testing.T) map[string]map[string]any {
	t.Helper()
	пути, err := filepath.Glob(filepath.Join(каталог(t), "*.yml"))
	if err != nil {
		t.Fatal(err)
	}
	if len(пути) == 0 {
		t.Fatal("в .github/workflows не нашлось ни одного файла — " +
			"проверка бы молча ничего не проверяла")
	}
	разобранные := make(map[string]map[string]any, len(пути))
	for _, путь := range пути {
		raw, err := os.ReadFile(путь)
		if err != nil {
			t.Fatal(err)
		}
		var дерево map[string]any
		if err := yaml.Unmarshal(raw, &дерево); err != nil {
			t.Fatalf("%s: не разбирается как YAML: %v", filepath.Base(путь), err)
		}
		разобранные[filepath.Base(путь)] = дерево
	}
	return разобранные
}

// событие достаёт раздел `on`.
//
// Отдельной функцией — из-за ключа: в YAML 1.1 голое `on` означает
// `true`, и разбор положил бы раздел под ключ «true», а проверка
// смотрела бы в пустоту и радовалась. Здешний разборщик держится
// схемы YAML 1.2, где `on` — обычная строка; это проверено, а не
// принято на веру, и на случай смены разборщика проверка ниже
// не молчит, а падает: раздела `on` у рабочего процесса не бывает.
func событие(дерево map[string]any, имя string) (any, bool) {
	раздел, есть := дерево["on"]
	if !есть {
		return nil, false
	}
	карта, ok := раздел.(map[string]any)
	if !ok {
		return nil, false
	}
	что, есть := карта[имя]
	return что, есть
}

func TestИдентификаторыРаботГодныДляGitHub(t *testing.T) {
	for файл, дерево := range процессы(t) {
		работы, ok := дерево["jobs"].(map[string]any)
		if !ok || len(работы) == 0 {
			t.Errorf("%s: ни одной работы — файл ничего не делает", файл)
			continue
		}
		for имя := range работы {
			if !идентификатор.MatchString(имя) {
				t.Errorf("%s: идентификатор работы %q GitHub не примет "+
					"и откажется от всего файла: только латиница, цифра, "+
					"дефис и подчёркивание. Русское имя — в `name`",
					файл, имя)
			}
		}
	}
}

func TestИдентификаторыВходовГодныДляGitHub(t *testing.T) {
	for файл, дерево := range процессы(t) {
		вручную, есть := событие(дерево, "workflow_dispatch")
		if !есть || вручную == nil {
			continue
		}
		карта, ok := вручную.(map[string]any)
		if !ok {
			continue
		}
		входы, ok := карта["inputs"].(map[string]any)
		if !ok {
			continue
		}
		for имя := range входы {
			if !идентификатор.MatchString(имя) {
				t.Errorf("%s: идентификатор входа %q GitHub не примет "+
					"и откажется от всего файла. Русское имя — "+
					"в `description`", файл, имя)
			}
		}
	}
}

func TestРаботаСсылаетсяНаСуществующую(t *testing.T) {
	for файл, дерево := range процессы(t) {
		работы, ok := дерево["jobs"].(map[string]any)
		if !ok {
			continue
		}
		for имя, тело := range работы {
			карта, ok := тело.(map[string]any)
			if !ok {
				continue
			}
			for _, нужна := range зависимости(карта["needs"]) {
				if _, есть := работы[нужна]; !есть {
					t.Errorf("%s: работа %s ждёт %q, которой нет — "+
						"GitHub откажется от файла целиком", файл, имя, нужна)
				}
			}
		}
	}
}

func зависимости(что any) []string {
	switch v := что.(type) {
	case string:
		return []string{v}
	case []any:
		имена := make([]string, 0, len(v))
		for _, э := range v {
			if строкой, ok := э.(string); ok {
				имена = append(имена, строкой)
			}
		}
		return имена
	}
	return nil
}

func TestОбязательныеПроверкиИдутНаКаждоеПредложение(t *testing.T) {
	разобранные := процессы(t)
	for файл, зачем := range обязательные {
		дерево, есть := разобранные[файл]
		if !есть {
			t.Errorf("%s (%s) пропал — проверка предложений стала меньше "+
				"на целый файл, и заметить это иначе нечем", файл, зачем)
			continue
		}
		отбор, есть := событие(дерево, "pull_request")
		if !есть {
			t.Errorf("%s (%s) не просыпается на pull_request: правку "+
				"никто не проверит", файл, зачем)
			continue
		}
		карта, ok := отбор.(map[string]any)
		if !ok {
			continue
		}
		for _, ключ := range []string{"paths", "paths-ignore"} {
			if _, есть := карта[ключ]; есть {
				t.Errorf("%s (%s): отбор по %s. Правка мимо этих путей "+
					"поедет без разбора, а сама проверка в списке "+
					"предложения не появится — обязательной её "+
					"не сделать", файл, зачем, ключ)
			}
		}
	}
}

// Кириллица в именах переменных: третий способ сломать рабочий процесс
// молча, и он ломает уже не разбор файла, а сам прогон.
//
// Правило проекта — код и комментарии по-русски, и в Go оно работает:
// язык принимает любые буквы Unicode. Оболочка и awk — не принимают.
// `набор=""` для оболочки не присваивание, а команда, которой нет;
// awk на `-v тег=` падает с «is not a legal variable name».
//
// Второе и поймало: `release.yml` доставал описание выпуска
// из CHANGELOG.md вызовом `awk -v тег=`, и это убило бы каждый выпуск.
// Заметить это раньше было нечем — файл был негоден целиком, и до awk
// дело не доходило ни разу.
//
// Проверяются два самых частых вида, а не всякое возможное имя:
// присваивание в начале строки и `-v имя=` у awk. Правило грубое,
// зато не притворяется полным.
var (
	присваивание    = regexp.MustCompile(`(?m)^\s*(?:export\s+)?([^\x00-\x7F][^\s=]*)=`)
	переменнаяAwk   = regexp.MustCompile(`-v\s+([^\x00-\x7F][^\s=]*)=`)
	переменнаяЦикла = regexp.MustCompile(`\bfor\s+([^\x00-\x7F][^\s]*)\s+in\b`)
)

// проверитьКоманду — одно место на все три вида имён. Команды приходят
// и из рабочих процессов, и из Makefile: оболочка у них общая, значит
// и запрет общий.
func проверитьКоманду(t *testing.T, откуда, команда string) {
	t.Helper()
	for _, m := range присваивание.FindAllStringSubmatch(команда, -1) {
		t.Errorf("%s: `%s=` — оболочка кириллицу в именах не принимает "+
			"и увидит здесь несуществующую команду. Имя латиницей, "+
			"объяснение — комментарием", откуда, m[1])
	}
	for _, m := range переменнаяЦикла.FindAllStringSubmatch(команда, -1) {
		t.Errorf("%s: `for %s in` — то же самое: «%s: это недопустимый "+
			"идентификатор»", откуда, m[1], m[1])
	}
	for _, m := range переменнаяAwk.FindAllStringSubmatch(команда, -1) {
		t.Errorf("%s: `awk -v %s=` — awk откажется: "+
			"«is not a legal variable name»", откуда, m[1])
	}
}

func TestИменаПеременныхВКомандахГодныДляОболочки(t *testing.T) {
	for файл, дерево := range процессы(t) {
		работы, ok := дерево["jobs"].(map[string]any)
		if !ok {
			continue
		}
		for имя, тело := range работы {
			карта, ok := тело.(map[string]any)
			if !ok {
				continue
			}
			шаги, ok := карта["steps"].([]any)
			if !ok {
				continue
			}
			for _, ш := range шаги {
				шаг, ok := ш.(map[string]any)
				if !ok {
					continue
				}
				команда, ok := шаг["run"].(string)
				if !ok {
					continue
				}
				проверитьКоманду(t, fmt.Sprintf("%s, работа %s", файл, имя), команда)
			}
		}
	}
}

// Makefile проверяется тем же правилом: рецепты — те же команды
// оболочки, и ломаются они так же. Поймано на `for б in $(BASES)`
// в цели, собирающей образы: «б: это недопустимый идентификатор».
// Проверка тогда смотрела только рабочие процессы — и промолчала.
func TestИменаПеременныхВMakefileГодныДляОболочки(t *testing.T) {
	raw, err := os.ReadFile(filepath.Join(каталог(t), "..", "..", "Makefile"))
	if err != nil {
		t.Fatal(err)
	}
	// Только строки рецептов: объявления make кириллицу принимают,
	// и запрещать её там значило бы запрещать язык проекта.
	for н, строка := range strings.Split(string(raw), "\n") {
		if !strings.HasPrefix(строка, "\t") {
			continue
		}
		проверитьКоманду(t, fmt.Sprintf("Makefile:%d", н+1), строка)
	}
}

// Секрет в условии делает файл негодным целиком.
//
// Контекст `secrets` в `if` недоступен — ни у шага, ни у работы; это
// сделано нарочно, чтобы по ветвлению нельзя было угадывать значение
// секрета. GitHub при этом не жалуется на конкретную строку,
// а отвечает тем же «workflow file issue» и не запускает ни шага —
// то есть ошибка выглядит ровно как от кириллицы в идентификаторе.
//
// Поймано на `if: ${{ secrets.DOCKERHUB_TOKEN != ” }}`: вход
// в Docker Hub хотелось пропускать там, где секрета нет. Проверять
// секрет надо внутри команды, а не в условии.
var секретВУсловии = regexp.MustCompile(`secrets\.[A-Za-z_]`)

func TestУсловияНеСмотрятНаСекреты(t *testing.T) {
	for файл, дерево := range процессы(t) {
		работы, ok := дерево["jobs"].(map[string]any)
		if !ok {
			continue
		}
		for имя, тело := range работы {
			карта, ok := тело.(map[string]any)
			if !ok {
				continue
			}
			условия := map[string]any{"работа " + имя: карта["if"]}
			if шаги, ok := карта["steps"].([]any); ok {
				for н, ш := range шаги {
					шаг, ok := ш.(map[string]any)
					if !ok {
						continue
					}
					где := fmt.Sprintf("работа %s, шаг %d", имя, н+1)
					if подпись, ok := шаг["name"].(string); ok {
						где = fmt.Sprintf("работа %s, шаг «%s»", имя, подпись)
					}
					условия[где] = шаг["if"]
				}
			}
			for где, что := range условия {
				строкой, ok := что.(string)
				if !ok || !секретВУсловии.MatchString(строкой) {
					continue
				}
				t.Errorf("%s, %s: условие смотрит на секрет — контекст "+
					"`secrets` в `if` недоступен, и GitHub объявит негодным "+
					"весь файл. Секрет проверяют внутри команды: положить "+
					"его в env и сравнить в оболочке", файл, где)
			}
		}
	}
}
