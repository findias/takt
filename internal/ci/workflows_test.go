package ci_test

import (
	"os"
	"path/filepath"
	"regexp"
	"runtime"
	"testing"

	"go.yaml.in/yaml/v4"
)

// Рабочие процессы GitHub проверяются на то, из-за чего они молчат.
//
// Молчащая проверка хуже упавшей: упавшая красная и её видно, а
// молчащая выглядит как «замечаний нет». Оба случая, которые здесь
// закреплены, случились на самом деле и оба выглядели именно так.
//
// Первый: у работы был русский идентификатор (`jobs.проверка`). GitHub
// принимает в идентификаторах только латиницу, цифру, дефис и
// подчёркивание; на кириллице он объявляет негодным весь файл и не
// запускает из него ничего — одной строкой «workflow file issue»
// и без единого шага. Выпуск по тегу так не собрался бы вовсе.
//
// Второй: у проверки безопасности стоял отбор по путям, и правка,
// до этих путей не достающая, ехала без разбора. Хуже того, проверку,
// промолчавшую по отбору, нельзя сделать обязательной: в списке
// предложения она не появляется вовсе и вечно «ожидается».

// Идентификаторы работ и входов: то, что позволяет GitHub. Латиница
// намеренно: русские имена живут в `name`, и там они законны.
var идентификатор = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_-]*$`)

// Проверки, которые обязаны просыпаться на каждое предложение правок.
// Список явный: новый файл рабочего процесса не всегда обязан быть
// проверкой предложения — выпуск, например, идёт по тегу.
var обязательные = map[string]string{
	"check.yml":    "обязательная проверка",
	"e2e.yml":      "сквозные сценарии",
	"security.yml": "безопасность",
}

func каталог(t *testing.T) string {
	t.Helper()
	_, файл, _, ok := runtime.Caller(0)
	if !ok {
		t.Fatal("не найти собственный путь")
	}
	return filepath.Join(filepath.Dir(файл), "..", "..", ".github", "workflows")
}

func процессы(t *testing.T) map[string]map[string]any {
	t.Helper()
	пути, err := filepath.Glob(filepath.Join(каталог(t), "*.yml"))
	if err != nil {
		t.Fatal(err)
	}
	if len(пути) == 0 {
		t.Fatal("в .github/workflows не нашлось ни одного файла — " +
			"проверка бы молча ничего не проверяла")
	}
	разобранные := make(map[string]map[string]any, len(пути))
	for _, путь := range пути {
		raw, err := os.ReadFile(путь)
		if err != nil {
			t.Fatal(err)
		}
		var дерево map[string]any
		if err := yaml.Unmarshal(raw, &дерево); err != nil {
			t.Fatalf("%s: не разбирается как YAML: %v", filepath.Base(путь), err)
		}
		разобранные[filepath.Base(путь)] = дерево
	}
	return разобранные
}

// событие достаёт раздел `on`.
//
// Отдельной функцией — из-за ключа: в YAML 1.1 голое `on` означает
// `true`, и разбор положил бы раздел под ключ «true», а проверка
// смотрела бы в пустоту и радовалась. Здешний разборщик держится
// схемы YAML 1.2, где `on` — обычная строка; это проверено, а не
// принято на веру, и на случай смены разборщика проверка ниже
// не молчит, а падает: раздела `on` у рабочего процесса не бывает.
func событие(дерево map[string]any, имя string) (any, bool) {
	раздел, есть := дерево["on"]
	if !есть {
		return nil, false
	}
	карта, ok := раздел.(map[string]any)
	if !ok {
		return nil, false
	}
	что, есть := карта[имя]
	return что, есть
}

func TestИдентификаторыРаботГодныДляGitHub(t *testing.T) {
	for файл, дерево := range процессы(t) {
		работы, ok := дерево["jobs"].(map[string]any)
		if !ok || len(работы) == 0 {
			t.Errorf("%s: ни одной работы — файл ничего не делает", файл)
			continue
		}
		for имя := range работы {
			if !идентификатор.MatchString(имя) {
				t.Errorf("%s: идентификатор работы %q GitHub не примет "+
					"и откажется от всего файла: только латиница, цифра, "+
					"дефис и подчёркивание. Русское имя — в `name`",
					файл, имя)
			}
		}
	}
}

func TestИдентификаторыВходовГодныДляGitHub(t *testing.T) {
	for файл, дерево := range процессы(t) {
		вручную, есть := событие(дерево, "workflow_dispatch")
		if !есть || вручную == nil {
			continue
		}
		карта, ok := вручную.(map[string]any)
		if !ok {
			continue
		}
		входы, ok := карта["inputs"].(map[string]any)
		if !ok {
			continue
		}
		for имя := range входы {
			if !идентификатор.MatchString(имя) {
				t.Errorf("%s: идентификатор входа %q GitHub не примет "+
					"и откажется от всего файла. Русское имя — "+
					"в `description`", файл, имя)
			}
		}
	}
}

func TestРаботаСсылаетсяНаСуществующую(t *testing.T) {
	for файл, дерево := range процессы(t) {
		работы, ok := дерево["jobs"].(map[string]any)
		if !ok {
			continue
		}
		for имя, тело := range работы {
			карта, ok := тело.(map[string]any)
			if !ok {
				continue
			}
			for _, нужна := range зависимости(карта["needs"]) {
				if _, есть := работы[нужна]; !есть {
					t.Errorf("%s: работа %s ждёт %q, которой нет — "+
						"GitHub откажется от файла целиком", файл, имя, нужна)
				}
			}
		}
	}
}

func зависимости(что any) []string {
	switch v := что.(type) {
	case string:
		return []string{v}
	case []any:
		имена := make([]string, 0, len(v))
		for _, э := range v {
			if строкой, ok := э.(string); ok {
				имена = append(имена, строкой)
			}
		}
		return имена
	}
	return nil
}

func TestОбязательныеПроверкиИдутНаКаждоеПредложение(t *testing.T) {
	разобранные := процессы(t)
	for файл, зачем := range обязательные {
		дерево, есть := разобранные[файл]
		if !есть {
			t.Errorf("%s (%s) пропал — проверка предложений стала меньше "+
				"на целый файл, и заметить это иначе нечем", файл, зачем)
			continue
		}
		отбор, есть := событие(дерево, "pull_request")
		if !есть {
			t.Errorf("%s (%s) не просыпается на pull_request: правку "+
				"никто не проверит", файл, зачем)
			continue
		}
		карта, ok := отбор.(map[string]any)
		if !ok {
			continue
		}
		for _, ключ := range []string{"paths", "paths-ignore"} {
			if _, есть := карта[ключ]; есть {
				t.Errorf("%s (%s): отбор по %s. Правка мимо этих путей "+
					"поедет без разбора, а сама проверка в списке "+
					"предложения не появится — обязательной её "+
					"не сделать", файл, зачем, ключ)
			}
		}
	}
}
