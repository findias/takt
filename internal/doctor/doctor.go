// Package doctor отвечает на вопрос «поставлено ли правильно».
//
// Живость и готовность отвечают на другой: «процесс жив» и «база
// отвечает». Между ними и работающей установкой лежит всё, что
// выясняется у заказчика в первые сутки и выглядит для него как «у вас
// не работает»: схема осталась от прежней версии, роль подключения
// обходит политики, BASE_URL не тот — и потому не доходит cookie,
// провайдер входа настроен, но недостижим.
//
// Проверка отвечает не «да/нет», а списком: что смотрели, чем кончилось
// и — у неудачи — что делать. Установка ломается редко целиком; обычно
// не работает одна вещь, и человеку нужно имя этой вещи, а не слово
// «ошибка».
package doctor

import (
	"context"
	"fmt"
	"io/fs"
	"net/http"
	"net/url"
	"sort"
	"time"

	"github.com/findias/takt/internal/config"
	"github.com/findias/takt/internal/realtime"
	"github.com/findias/takt/internal/store"
	"github.com/findias/takt/migrations"
)

// Итог одной проверки.
//
// Совет заполняется у неудачи — «нельзя» без того, что делать,
// отправляет человека искать поломку наугад, — и у того, что поломкой
// не является, но названо: связь с базой открытым текстом, открытая
// регистрация. Разница видна в выводе: у неудачи это «что делать»,
// у остального — «стоит знать».
type Итог struct {
	Что   string
	Ладно bool
	Ответ string
	Совет string
}

// Осмотр — все проверки разом. Порядок важен: сперва то, без чего
// остальное не имеет смысла.
func Осмотр(ctx context.Context, cfg config.Config, db *store.Store) []Итог {
	return []Итог{
		схемаПрименена(ctx, db),
		изоляцияДействует(ctx, db),
		адресНастроен(cfg),
		связьСБазой(cfg),
		ктоЗаводитОрганизации(cfg),
		провайдерДостижим(ctx, cfg),
		оповещенияДоходят(ctx, db),
	}
}

// Всё ли в порядке: по этому ответу выходит код возврата, а по нему —
// решение выкладки, продолжать или звать человека.
func Ладно(итоги []Итог) bool {
	for _, и := range итоги {
		if !и.Ладно {
			return false
		}
	}
	return true
}

// Схема должна быть той, которую ждёт этот бинарник. Проверка при старте
// смотрит только, что таблицы вообще есть; установка, где миграции
// применены наполовину или не применены после смены образа, проходит её
// и падает потом — на первом запросе, которому нужна новая колонка.
func схемаПрименена(ctx context.Context, db *store.Store) Итог {
	итог := Итог{Что: "схема базы"}
	вшито, err := именаМиграций()
	if err != nil {
		итог.Ответ = err.Error()
		return итог
	}
	rows, err := db.Pool.Query(ctx, `select name from schema_migrations`)
	if err != nil {
		итог.Ответ = fmt.Sprintf("не прочитать schema_migrations: %v", err)
		итог.Совет = "если таблицы нет вовсе — миграции не запускались: `takt migrate`"
		return итог
	}
	defer rows.Close()
	есть := map[string]bool{}
	for rows.Next() {
		var имя string
		if err := rows.Scan(&имя); err != nil {
			итог.Ответ = err.Error()
			return итог
		}
		есть[имя] = true
	}
	if err := rows.Err(); err != nil {
		итог.Ответ = err.Error()
		return итог
	}

	не := []string{}
	for _, имя := range вшито {
		if !есть[имя] {
			не = append(не, имя)
		}
	}
	// Лишние отмечаем, но поломкой не считаем: так выглядит откат
	// на прежний образ, и он законен ровно потому, что миграции пишутся
	// совместимыми с предыдущей версией.
	лишние := 0
	for имя := range есть {
		if !содержит(вшито, имя) {
			лишние++
		}
	}
	switch {
	case len(не) > 0:
		итог.Ответ = fmt.Sprintf("не применено %d из %d, первая — %s", len(не), len(вшито), не[0])
		итог.Совет = "запустите `takt migrate` (в Kubernetes это задача takt-migrate)"
	case лишние > 0:
		итог.Ладно = true
		итог.Ответ = fmt.Sprintf(
			"применены все %d, и ещё %d от более новой версии — похоже на откат", len(вшито), лишние)
	default:
		итог.Ладно = true
		итог.Ответ = fmt.Sprintf("применены все %d", len(вшито))
	}
	return итог
}

// Изоляция организаций держится политиками базы, а для суперпользователя
// они не действуют вовсе. Приложение проверяет это при старте
// и отказывается запускаться; здесь — то же самое, но до запуска
// и с объяснением, что чинить.
func изоляцияДействует(ctx context.Context, db *store.Store) Итог {
	итог := Итог{Что: "изоляция организаций"}
	if err := db.EnsureTenantIsolation(ctx); err != nil {
		итог.Ответ = err.Error()
		итог.Совет = "роль подключения не должна быть суперпользователем и владельцем таблиц: " +
			"заведите отдельную роль (пример — deploy/postgres-init/10-app-role.sh)"
		return итог
	}
	итог.Ладно = true
	итог.Ответ = "политики действуют на роль подключения"
	return итог
}

// BASE_URL решает две вещи, ломающиеся по-разному: из него клиент строит
// адрес потока изменений, и по его схеме ставится признак защищённой
// cookie. Ошибка здесь выглядит не ошибкой, а «не работает вход»
// или «доска не обновляется».
func адресНастроен(cfg config.Config) Итог {
	итог := Итог{Что: "адрес (BASE_URL)"}
	u, err := url.Parse(cfg.BaseURL)
	if err != nil || u.Host == "" {
		итог.Ответ = fmt.Sprintf("%q не разбирается как адрес", cfg.BaseURL)
		итог.Совет = "BASE_URL — тот адрес, по которому доску открывают в браузере, без слэша на конце"
		return итог
	}
	итог.Ладно = true
	if u.Scheme == "https" {
		итог.Ответ = cfg.BaseURL + " — cookie будет защищённой (Secure)"
	} else {
		итог.Ответ = cfg.BaseURL + " — cookie без Secure: годится для стенда, не для боя"
	}
	return итог
}

// Связь с базой: защищена ли она, когда база не рядом.
//
// Это первый вопрос проверки ИБ у заказчика и первое, что расходится
// с примером из руководства: там стоит `sslmode=disable`, потому что
// там подключаются к локальному сокету, а переносят строку целиком
// и на базу в соседней стойке — вместе с паролем открытым текстом.
//
// Поломкой это не объявляется: сеть между приложением и базой бывает
// и доверенной, и решает это тот, кто ставил. Но названо должно быть,
// потому что молчание здесь читается как «всё в порядке».
//
// Пароль в ответе не показывается: осмотр печатают на экран, и адрес
// базы с паролем оттуда попадает в переписку.
func связьСБазой(cfg config.Config) Итог {
	итог := Итог{Что: "связь с базой", Ладно: true}
	u, err := url.Parse(cfg.DatabaseURL)
	if err != nil || u.Host == "" {
		// Строка могла быть и в формате ключ-значение — разбирать его
		// здесь незачем: приложение уже подключилось этой строкой,
		// раз осмотр дошёл до сюда.
		итог.Ответ = "строку подключения не разобрать по частям — проверьте sslmode глазами"
		return итог
	}
	режим := u.Query().Get("sslmode")
	if режим == "" {
		режим = "не задан"
	}
	if isLoopback(u.Hostname()) {
		итог.Ответ = fmt.Sprintf("база рядом (%s), sslmode=%s — трафик не выходит за машину",
			u.Hostname(), режим)
		return итог
	}
	switch режим {
	case "verify-full", "verify-ca":
		итог.Ответ = fmt.Sprintf("база по сети (%s), sslmode=%s", u.Hostname(), режим)
	case "require":
		итог.Ответ = fmt.Sprintf("база по сети (%s), sslmode=require: шифрование есть, "+
			"а имя узла не проверяется", u.Hostname())
		итог.Совет = "verify-full проверяет и имя: без него подставленная база выглядит своей"
	default:
		итог.Ответ = fmt.Sprintf("база по сети (%s), sslmode=%s: пароль и данные идут открыто",
			u.Hostname(), режим)
		итог.Совет = "поставьте sslmode=verify-full и корневой сертификат базы (sslrootcert)"
	}
	return итог
}

// isLoopback — та же местность, что и у настройки: адрес, дальше
// которого трафик не уходит.
func isLoopback(host string) bool {
	switch host {
	case "localhost", "127.0.0.1", "::1", "":
		return true
	}
	return false
}

// Кто заводит организации. Спрашивают об этом в двух случаях: при
// проверке ИБ («кто может создать себе организацию на вашем адресе?»)
// и через месяц после установки, когда организаций стало две.
func ктоЗаводитОрганизации(cfg config.Config) Итог {
	итог := Итог{Что: "кто заводит организации", Ладно: true}
	switch cfg.Signup {
	case config.SignupOpen:
		итог.Ответ = "SIGNUP=open — организацию заведёт всякий, кто откроет адрес"
		итог.Совет = "для установки в контуре обычно нужен SIGNUP=first (первый пришедший, " +
			"дальше по приглашению) или closed (никто)"
	case config.SignupClosed:
		итог.Ответ = "SIGNUP=closed — организации заводятся заранее, людей приводит каталог"
	default:
		итог.Ответ = "SIGNUP=first — организацию заводит первый пришедший, дальше по приглашению"
	}
	return итог
}

// Провайдер входа: настроен — значит должен быть достижим. Иначе кнопка
// на экране входа есть, а за ней отказ, и выясняется это на первом
// человеке, который ею воспользуется.
func провайдерДостижим(ctx context.Context, cfg config.Config) Итог {
	итог := Итог{Что: "корпоративный вход"}
	if !cfg.OIDC.Enabled() {
		итог.Ладно = true
		итог.Ответ = "не настроен (вход по паролю)"
		return итог
	}
	адрес := cfg.OIDC.Issuer + "/.well-known/openid-configuration"
	ctx, cancel := context.WithTimeout(ctx, 10*time.Second)
	defer cancel()
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, адрес, nil)
	if err != nil {
		итог.Ответ = err.Error()
		return итог
	}
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		итог.Ответ = fmt.Sprintf("%s недостижим: %v", адрес, err)
		итог.Совет = "проверьте сеть до провайдера из этого пода и OIDC_ISSUER"
		return итог
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		итог.Ответ = fmt.Sprintf("%s отвечает %d", адрес, resp.StatusCode)
		итог.Совет = "OIDC_ISSUER указывает не на того, кто раздаёт настройки провайдера"
		return итог
	}
	итог.Ладно = true
	итог.Ответ = cfg.OIDC.Issuer + " отвечает"
	return итог
}

// Изменения расходятся по репликам оповещениями базы: одна вкладка
// двигает карточку, остальные узнают об этом через LISTEN/NOTIFY.
// Проверка не выдуманная: пул соединений перед базой, поставленный
// в режим транзакций, оповещения теряет молча — соединение под
// подписчиком меняется, и `listen` остаётся на чужом. Приложение
// при этом работает, а доска «не обновляется сама», и ищут это
// в приложении.
func оповещенияДоходят(ctx context.Context, db *store.Store) Итог {
	итог := Итог{Что: "поток изменений"}
	ctx, cancel := context.WithTimeout(ctx, 5*time.Second)
	defer cancel()

	// Своё соединение, а не из пула: подписка живёт на соединении,
	// и проверять её через пул значит проверять пул.
	conn, err := db.Pool.Acquire(ctx)
	if err != nil {
		итог.Ответ = fmt.Sprintf("нет соединения: %v", err)
		return итог
	}
	defer conn.Release()

	if _, err := conn.Exec(ctx, "listen "+realtime.Channel); err != nil {
		итог.Ответ = fmt.Sprintf("не подписаться на %s: %v", realtime.Channel, err)
		итог.Совет = "роли подключения нужно право listen; проверьте, что перед базой не стоит " +
			"пул соединений в режиме транзакций"
		return итог
	}
	if _, err := conn.Exec(ctx, `select pg_notify($1, $2)`, realtime.Channel, "doctor"); err != nil {
		итог.Ответ = fmt.Sprintf("не отправить оповещение: %v", err)
		return итог
	}
	if _, err := conn.Conn().WaitForNotification(ctx); err != nil {
		итог.Ответ = "оповещение не вернулось за пять секунд"
		итог.Совет = "так ведёт себя пул соединений в режиме транзакций (pgbouncer transaction): " +
			"он теряет подписки, и доска перестаёт обновляться сама. Нужен режим сессий " +
			"или прямое подключение к базе"
		return итог
	}
	итог.Ладно = true
	итог.Ответ = "оповещения доходят: доска будет обновляться у всех сразу"
	return итог
}

func именаМиграций() ([]string, error) {
	entries, err := fs.ReadDir(migrations.FS, ".")
	if err != nil {
		return nil, fmt.Errorf("чтение каталога миграций: %w", err)
	}
	out := make([]string, 0, len(entries))
	for _, e := range entries {
		if !e.IsDir() {
			out = append(out, e.Name())
		}
	}
	sort.Strings(out)
	return out, nil
}

func содержит(список []string, что string) bool {
	for _, э := range список {
		if э == что {
			return true
		}
	}
	return false
}
