package help

import (
	"regexp"
	"strings"
	"testing"
)

// «Что нового» начинается с перечня главного простыми словами, и каждый
// пункт ведёт в тот раздел справки, где это описано (задание владельца
// 26.09.2026, этап 35.3). Ссылка, ведущая мимо — на исчезнувший раздел
// или на страницу, которой нет в справке, — обещает объяснение и не даёт
// его; здесь каждая проверяется по настоящей собранной странице.
func TestWhatsNewShortListLeadsIntoHelp(t *testing.T) {
	ссылка := regexp.MustCompile(`href="/help/(ru|en)/([a-z-]+)(#[a-z0-9-]+)?"`)
	for _, язык := range []string{"ru", "en"} {
		страница, ok, err := СобратьНовое(язык, "v0.3.0")
		if err != nil || !ok {
			t.Fatalf("%s: %v", язык, err)
		}
		// Перечень — до заголовка «Подробно».
		w := словаНового[язык]
		граница := strings.Index(страница, ">"+w.подробно+"</h2>")
		if граница < 0 {
			t.Fatalf("%s: нет заголовка %q — перечня «Коротко» в списке изменений нет", язык, w.подробно)
		}
		начало := strings.Index(страница, "<main")
		if начало < 0 || начало > граница {
			t.Fatalf("%s: не найдено начало страницы", язык)
		}
		перечень := страница[начало:граница]
		найдено := ссылка.FindAllStringSubmatch(перечень, -1)
		if len(найдено) < 10 {
			t.Fatalf("%s: в перечне %d ссылок в справку — ждали не меньше десяти", язык, len(найдено))
		}
		for _, н := range найдено {
			цель, адрес, якорь := н[1], н[2], strings.TrimPrefix(н[3], "#")
			if цель != язык {
				t.Errorf("%s: ссылка ведёт на справку другого языка: %s", язык, н[0])
				continue
			}
			раздел, ok, err := Собрать(цель, адрес, "v0.3.0")
			if err != nil || !ok {
				t.Errorf("%s: %s — такой страницы справки нет", язык, н[0])
				continue
			}
			if якорь != "" && !strings.Contains(раздел, `id="`+якорь+`"`) {
				t.Errorf("%s: %s — на странице нет раздела #%s", язык, н[0], якорь)
			}
		}
	}
}

// Любая страница справки называет свою версию и ведёт в «Что нового»
// этой версии и в репозиторий: первое, что о справке спрашивают, —
// к какой она версии (задание владельца 26.09.2026, этап 35.3).
func TestHelpNamesItsVersionAndWhatIsNew(t *testing.T) {
	for язык, версия := range map[string]string{"ru": "Версия v0.3.0", "en": "Version v0.3.0"} {
		страница, ok, err := Собрать(язык, "howto", "v0.3.0")
		if err != nil || !ok {
			t.Fatalf("%s: %v", язык, err)
		}
		for _, нужно := range []string{версия, `href="/help/` + язык + `/whats-new"`, `href="https://github.com/findias/takt"`} {
			if !strings.Contains(страница, нужно) {
				t.Errorf("%s: на странице справки нет %q", язык, нужно)
			}
		}
	}
}
