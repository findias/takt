package security_test

import (
	"os/exec"
	"path/filepath"
	"runtime"
	"strings"
	"testing"
)

// Инструменты сборки не должны оказаться в поставке.
//
// Проверка заведена под конкретное исключение: cmd/docs выведен
// из-под gosec, и единственный довод в пользу этого — что заказчику
// он не едет. Довод, записанный в комментарии, живёт ровно до первой
// правки импортов: достаточно позвать оттуда одну функцию, и
// невыполняемое обещание станет невыполненным молча.
//
// Отсюда проверка обратной стороны: пусть исключение держится не
// на слове, а на том, что можно перепроверить машиной.
func TestИнструментыСборкиНеЕдутВПоставку(t *testing.T) {
	_, файл, _, ok := runtime.Caller(0)
	if !ok {
		t.Fatal("не найти собственный путь")
	}
	корень := filepath.Join(filepath.Dir(файл), "..", "..")

	cmd := exec.Command("go", "list", "-deps", "./cmd/takt")
	cmd.Dir = корень
	out, err := cmd.Output()
	if err != nil {
		t.Fatalf("go list: %v", err)
	}

	пакеты := strings.Fields(string(out))
	if len(пакеты) == 0 {
		t.Fatal("go list не вернул ни одного пакета — проверка ничего не проверила")
	}
	for _, пакет := range пакеты {
		if strings.HasSuffix(пакет, "/cmd/docs") {
			t.Errorf("cmd/docs вкомпилирован в cmd/takt, а он выведен из-под gosec "+
				"именно потому, что не едет заказчику: снимите исключение в Makefile "+
				"или уберите зависимость (%s)", пакет)
		}
	}
}
