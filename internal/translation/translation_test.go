package translation_test

import (
	"crypto/sha256"
	"encoding/hex"
	"os"
	"path/filepath"
	"regexp"
	"runtime"
	"testing"
)

// Перевод не должен молча отстать от оригинала.
//
// Возражение против второго набора текстов было записано в коде сборки
// документации и звучало так: у перевода нет прогона, который упадёт,
// когда оригинал поправят. Возражение верное, и снимается оно ровно
// тем, чего не хватало, — прогоном.
//
// Каждая английская страница помечена именем русского исходника и
// отпечатком его состояния на момент перевода. Правка русской страницы
// меняет отпечаток, проверка падает и называет, что переводить заново.
// Отпечаток при этом не подписывает смысл — он подписывает лишь то,
// что человек видел исходник в этом виде; ничего большего машинная
// проверка о переводе сказать не может, и притворяться иначе было бы
// хуже, чем не проверять вовсе.
//
// Вторая половина проверки — что пара вообще есть. Новая английская
// страница без русской не должна проезжать молча: тогда «есть
// документация на двух языках» превращается в «была когда-то».
//
// Направление у пар английское: оригинал пишется по-английски,
// русский идёт переводом и помечается отпечатком английского.
// Прежде было наоборот, и разворот — не косметика: отпечаток
// подписывает исходник, и сторона, на которой он стоит, и есть
// та, что считается переводом.

// Пары: английский исходник — русский перевод. Список явный, потому
// что имена страниц не переводятся механически (`howto.md` — `как.md`),
// а угадывание здесь дало бы проверку, которая молчит на опечатке.
var пары = map[string]string{
	"docs/overview.md":        "docs/ru/индекс.md",
	"docs/quickstart.md":      "docs/ru/старт.md",
	"docs/howto.md":           "docs/ru/как.md",
	"docs/reference.md":       "docs/ru/справочник.md",
	"docs/cheatsheet.md":      "docs/ru/памятка.md",
	"docs/architecture.md":    "docs/ru/устройство.md",
	"docs/install.md":         "docs/ru/установка.md",
	"docs/security-review.md": "docs/ru/проверка-иб.md",
	"README.md":               "README.ru.md",
}

var метка = regexp.MustCompile(`<!-- перевод: (\S+) sha256:([0-9a-f]{12}) -->`)

func корень(t *testing.T) string {
	t.Helper()
	_, файл, _, ok := runtime.Caller(0)
	if !ok {
		t.Fatal("не найти собственный путь")
	}
	return filepath.Join(filepath.Dir(файл), "..", "..")
}

func отпечаток(t *testing.T, путь string) string {
	t.Helper()
	raw, err := os.ReadFile(filepath.Join(корень(t), путь))
	if err != nil {
		t.Fatalf("%s: %v", путь, err)
	}
	сумма := sha256.Sum256(raw)
	return hex.EncodeToString(сумма[:])[:12]
}

func TestУКаждойРусскойСтраницыЕстьАнглийская(t *testing.T) {
	for русская, английская := range пары {
		if _, err := os.Stat(filepath.Join(корень(t), русская)); err != nil {
			t.Errorf("%s назван парой, а его нет: %v", русская, err)
			continue
		}
		if _, err := os.Stat(filepath.Join(корень(t), английская)); err != nil {
			t.Errorf("у %s нет английской пары %s: %v", русская, английская, err)
		}
	}

	// Русская страница, не попавшая в пары, — это страница, которую
	// забыли перевести и забыли объявить непереводимой.
	каталог := filepath.Join(корень(t), "docs")
	файлы, err := filepath.Glob(filepath.Join(каталог, "*.md"))
	if err != nil {
		t.Fatalf("не прочесть docs/: %v", err)
	}
	if len(файлы) == 0 {
		t.Fatal("в docs/ нет ни одной страницы — проверка ничего не проверила")
	}
	for _, файл := range файлы {
		отн := "docs/" + filepath.Base(файл)
		if _, есть := пары[отн]; !есть {
			t.Errorf("%s не назван ни в одной паре: переведите его "+
				"или впишите сюда, почему он остаётся только по-русски", отн)
		}
	}
}

func TestПереводНеОтсталОтОригинала(t *testing.T) {
	for русская, английская := range пары {
		raw, err := os.ReadFile(filepath.Join(корень(t), английская))
		if err != nil {
			t.Errorf("%s: %v", английская, err)
			continue
		}
		m := метка.FindSubmatch(raw)
		if m == nil {
			t.Errorf("%s не помечен: последней строкой должно стоять\n"+
				"    <!-- перевод: %s sha256:%s -->",
				английская, русская, отпечаток(t, русская))
			continue
		}
		if string(m[1]) != русская {
			t.Errorf("%s помечен переводом %s, а парой ему назван %s",
				английская, m[1], русская)
			continue
		}
		if ждём := отпечаток(t, русская); string(m[2]) != ждём {
			t.Errorf("%s поправили, а %s — нет.\n"+
				"Перечитайте правку, перенесите её в перевод и поставьте метку\n"+
				"    <!-- перевод: %s sha256:%s -->\n"+
				"Метка подписывает только то, что исходник видели в этом виде: "+
				"переставить её, не читая, — значит соврать себе же.",
				русская, английская, русская, ждём)
		}
	}
}

// Переключение языка обязано вести на пару, а не на себя.
//
// «По-русски», ведущее на ту же английскую страницу, выглядит рабочей
// ссылкой и ею не является: страница перезагружается тем же текстом,
// и читающий решает, что перевода нет вовсе. Так и было на титульной
// странице — ссылка стояла, перевод лежал рядом, и никто из двоих
// об этом не знал.
//
// Проверяются ссылки, подписанные названием языка: только они
// обещают переключение. Ссылка «Overview» в русской таблице —
// это отсылка к разделу, а не рычаг языка, и её здесь нет.
var переключатель = regexp.MustCompile(`\[(По-русски|Русский|In English|English)\]\(([^)#]+)\)`)

func TestПереключениеЯзыкаВедётНаПару(t *testing.T) {
	for оригинал, перевод := range пары {
		переключаетНа(t, оригинал, перевод)
		переключаетНа(t, перевод, оригинал)
	}
}

// переключаетНа: если на странице есть рычаг языка, он ведёт на пару.
// Отсутствие рычага здесь не ошибка — не всякая страница им снабжена,
// а обещание, которое не выполняется, есть только там, где рычаг стоит.
func переключаетНа(t *testing.T, страница, пара string) {
	t.Helper()
	raw, err := os.ReadFile(filepath.Join(корень(t), страница))
	if err != nil {
		t.Errorf("%s: %v", страница, err)
		return
	}
	for _, m := range переключатель.FindAllStringSubmatch(string(raw), -1) {
		подпись, цель := m[1], m[2]
		куда := filepath.ToSlash(filepath.Join(filepath.Dir(страница), цель))
		if куда == filepath.ToSlash(страница) {
			t.Errorf("%s: «%s» ведёт на саму же %s — переключение языка "+
				"ничего не переключает", страница, подпись, страница)
			continue
		}
		if куда != пара {
			t.Errorf("%s: «%s» ведёт на %s, а пара ему — %s",
				страница, подпись, куда, пара)
		}
	}
}
