// Package version — чем эта сборка отвечает на вопрос «какая у меня
// версия».
//
// До сих пор ответа не было ни у кого: тегов в репозитории нет,
// `BUNDLE_VERSION` собирался из хеша с суффиксом `-dirty`, чарт
// с рождения стоял на 0.1.0, а в самом бинарнике не было ничего.
// Заказчику нечем ответить на «какая у меня версия», нам — на «на какой
// воспроизвели», и что изменилось между двумя установками, не было
// перечислено нигде.
//
// Значение вшивается при сборке (`-ldflags -X`), а не читается
// из файла: файл в образе можно подменить, а версия должна быть тем же
// артефактом, что и код.
package version

// Value заполняется линковщиком. Пустое значение — сборка, собранная
// мимо `make`: `go run` при разработке, `go build` без флагов.
var Value string

// Строка — версия для человека. Пустую подменяем словами, а не пустотой:
// «версия: » в выводе выглядит поломкой вывода, а не отсутствием версии.
func Строка() string {
	if Value == "" {
		return "не задана (сборка мимо make)"
	}
	return Value
}

// Задана ли версия. Установка без версии работает, но ответить
// на «что у вас стоит» нечем — и это стоит сказать вслух.
func Задана() bool { return Value != "" }
