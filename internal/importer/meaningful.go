package importer

import "unicode"

// Meaningful — несёт ли запись истории хоть что-то: букву или цифру.
//
// Системные сообщения YouGile пришли при первом настоящем переносе
// (26.09.2026) с текстом «.»: карточка показала «До переноса» столбиком
// из пятнадцати точек с датами, и выглядело это поломкой, а не историей.
// Запись без единой буквы и цифры рассказать ничего не может — её не
// пишут и не показывают. Реплик людей это не касается: человек вправе
// ответить «+» или «.», и это ответ.
func Meaningful(text string) bool {
	for _, r := range text {
		if unicode.IsLetter(r) || unicode.IsDigit(r) {
			return true
		}
	}
	return false
}
