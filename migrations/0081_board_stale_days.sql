-- «Без движения» у доски (ROADMAP 42.3, срез 5): сколько дней карточка
-- в работе может стоять в одной колонке, прежде чем попасть в сводку
-- «Требует внимания» на «Отчётах». Пусто — семь дней. У каждой доски
-- своё: у поддержки сутки без движения — тревога, у исследований неделя
-- — норма.
--
-- Колонка без умолчания и допускает пусто: старая версия её не читает
-- и на новой схеме работает как прежде.

alter table boards
    add column stale_days integer
        constraint boards_stale_days_range check (stale_days is null or stale_days between 1 and 365);
