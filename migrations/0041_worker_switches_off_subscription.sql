-- Работнику нечем было отключить подписку, и об этом никто не узнавал.
--
-- Задумано так: восемь попыток с удвоением — около двух часов, — и если
-- получатель не ожил, работник сдаётся, отключает подписку и пишет
-- в неё причину. Список подписок показывает отметку «Отключена:
-- получатель не отвечал», потому что молчащая подписка — это соседняя
-- система, которая в этот момент считает, что у нас ничего не
-- происходит.
--
-- Ничего этого не происходило. Работник ходит по очереди без арендатора
-- (очередь общая, и выбирать из неё по одной организации значило бы
-- обходить их по кругу), а на webhooks для него была заведена только
-- политика чтения. Изменение подчинялось manage — «владелец
-- организации», — и без арендатора она не пропускает никого. Строка
-- `update webhooks set disabled_at = now()` обновляла ноль строк
-- и не жаловалась: тот же молчаливый отказ, каким уже дважды ломались
-- правки данных внутри миграций.
--
-- Видно это не было ниоткуда: отметка просто никогда не появлялась,
-- а недоставленное продолжало копиться — ровно то, что решили не делать.
--
-- Разрешение даётся тем же способом, что и на очередь: арендатор
-- не выставлен — значит, это работник, а не запрос человека (у запроса
-- арендатор выставлен всегда). Строк, а не столбцов: политика умеет
-- только строки. Поэтому в with check стоит условие «подписка остаётся
-- отключённой» — единственное, ради чего разрешение и заводится.
-- Включает подписку обратно владелец, у него своя политика.
create policy worker_switches_off on webhooks for update
    using ((select app_current_org()) is null)
    with check ((select app_current_org()) is null and disabled_at is not null);
