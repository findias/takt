-- Архивная карточка больше не занимает ключ порядка навсегда.
--
-- Дефект был заложен в первой миграции: уникальный индекс на
-- (column_id, position) не был частичным, а архивация оставляет карточке
-- и колонку, и позицию — намеренно, чтобы журнал продолжал ссылаться
-- на осмысленное место.
--
-- Поиск соседей при вычислении новой позиции смотрит только на живые
-- карточки. Значит вычисленный ключ мог в точности совпасть с ключом
-- давно убранной карточки, и совершенно обычное действие — заархивировать
-- карточку, потом добавить новую — падало нарушением уникальности.
-- Пользователь при этом видел внутреннюю ошибку, а не конфликт, то есть
-- даже не получал актуальный порядок колонки, чтобы пересобраться.
--
-- Воспроизводится тестом TestArchivedCardDoesNotHoldItsOrderKeyForever.
--
-- Индекс остаётся уникальным: страховка от коллизии ключей нужна ровно
-- там, где карточки живые. Он же по-прежнему тот индекс, по которому
-- колонка читается уже отсортированной.

drop index cards_order_key;
create unique index cards_order_key on cards (column_id, position)
    where archived_at is null;

-- Та же ловушка ждала колонки: у них есть archived_at, а индекс порядка
-- был общим. Операции архивирования колонки пока нет, но появится —
-- и наступила бы на те же грабли.
drop index board_columns_order_key;
create unique index board_columns_order_key on board_columns (board_id, position)
    where archived_at is null;
