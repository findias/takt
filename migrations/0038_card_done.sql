-- Отметка «сделано» — готовность, не зависящая от колонки.
--
-- Готовность на доске означает колонку финиша, и это остаётся
-- единственной мерой потока: цикл, пропускная способность и отчёт
-- по итерации считаются по finished_at и outcome, и отметка отсюда
-- в них не входит. Иначе появилась бы вторая пропускная способность,
-- которую никто не мерил секундомером, и прогнозы поехали бы за ней.
--
-- Но у подзадачи готовность часто не переезд по доске. Разбиение
-- заводят пунктами вида «написать текст письма», «согласовать с
-- юристами» — их не гоняют по колонкам, и требовать переезда значит
-- требовать обряда ради счётчика. Спрашивают о них ровно одно: эта
-- часть уже сделана или ещё нет. Отметка отвечает на этот вопрос
-- и больше ни на какой: она входит в прогресс родителя и меняет вид
-- строки, а поток о ней не знает.
--
-- Момент, а не булево. «Когда её отметили» спрашивают так же, как
-- «когда заблокировали», и восстановить это из флага неоткуда;
-- журнал событий на вопрос «сколько эта часть числится сделанной»
-- отвечает обходом, а поле — чтением.
--
-- Кто отметил, поля нет: это событие, и оно уже пишется в журнал
-- карточки вместе с автором. Вторая копия автора обязана была бы
-- не разъезжаться с первой, не будучи обязанной совпасть.

