-- Вес карточки.
--
-- Прогресс сегодня считается по числу подзадач: три из пяти. В любой
-- команде, где задачи разного размера, это ложь — причём ложь, которая
-- выглядит как факт. Три мелкие правки из пяти задач не означают, что
-- работа сделана на шестьдесят процентов.
--
-- Оценка нужна и для прогресса, и для прогноза по бэклогу, и вот почему
-- она в этапе «необратимое»: оценку ставят до работы или в её начале.
-- Задним числом её не восстановить — никто не проставит ретроспективно
-- то, что и тогда-то было догадкой. Пропущенный период просто останется
-- без оценок навсегда.
--
-- Единица измерения — свойство организации, а не карточки. Смешивать
-- в одной организации часы и очки бессмысленно: складывать их нельзя,
-- а прогресс — это сложение. Менять единицу можно когда угодно, она
-- влияет только на подпись; поэтому здесь она обратима, а сами числа —
-- нет.

alter table orgs
    add column estimate_unit text not null default 'points'
        constraint orgs_estimate_unit_valid
        check (estimate_unit in ('points', 'hours', 'days'));

alter table cards
    -- Дробные оценки существуют: полдня, полтора часа. Два знака хватает
    -- любой шкале, а numeric вместо double — потому что складывать деньги
    -- и часы в плавающей точке всегда заканчивается одинаково.
    add column estimate numeric(10, 2)
        constraint cards_estimate_positive
        check (estimate is null or estimate > 0);

