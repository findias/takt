-- Перенос своей области не выводит её из-под надзора.
--
-- Политика `manage on teams` спрашивает одно: остался ли узел внутри моей
-- области, — и сравнивает `ancestor_ids` с корнями администратора до
-- и после правки. Для узла, который сам и есть корень области, ответ
-- «да» при любом родителе: собственный идентификатор из пути никуда
-- не девается. Поэтому администратор поддерева мог увести свою область
-- в корень дерева, и политика это пропускала.
--
-- Прогон 22 августа 2026: наблюдатель, которому владелец выдал надзор
-- за «Компанией», видел «Компания, Разработка, Платформа»; после того
-- как администратор «Разработки» перенёс её в корень, — только
-- «Компанию». Администратором он при этом остался. То есть подотчётный
-- в одно действие переставал быть подотчётным, вместе со всем своим
-- поддеревом и всеми его досками.
--
-- Правило, которое здесь дописывается, проект уже сформулировал для
-- заведения: «корень заводит только владелец: у нового корня нет предка,
-- а значит нет и того, кто мог бы за него отвечать». Перенос в корень
-- давал ровно такой узел через другую дверь.
--
-- Проверять это политикой нельзя: `with check` видит только новую строку,
-- а вопрос стоит о перемене — сменился ли родитель. Условие «родитель
-- внутри моей области», наложенное на всякую правку, запретило бы
-- администратору переименовать собственный корень: у того родитель
-- снаружи по определению. Значит, нужен триггер, который видит обе
-- стороны.
--
-- Внутри своей области администратор по-прежнему волен переставлять
-- что угодно: запрещён только перенос, меняющий того, кому область
-- подотчётна.

create function teams_move_keeps_oversight() returns trigger
language plpgsql
as $$
begin
    if new.parent_id is not distinct from old.parent_id then
        return new;
    end if;
    if (select app_is_owner()) then
        return new;
    end if;

    -- Корень — отдельным случаем: сказать про него «родитель не в вашей
    -- области» значит промолчать о главном, а человеку надо понять,
    -- почему нельзя то, что рядом можно.
    if new.parent_id is null then
        raise exception
            'вывести подразделение в корень может только владелец организации: '
            'у корневого подразделения нет старшего, и надзор за ним прекращается'
            using errcode = 'check_violation';
    end if;

    if not (new.parent_id = any (app_admin_teams())) then
        raise exception
            'перенести подразделение можно только внутрь своей области: '
            'перенос наружу меняет, кто видит поддерево, и это решает '
            'владелец организации'
            using errcode = 'check_violation';
    end if;

    return new;
end;
$$;

-- После teams_path: тот проверяет циклы и глубину, и о переносе,
-- уводящем поддерево слишком глубоко, человеку полезнее узнать раньше,
-- чем о правах. Порядок триггеров одного момента — по имени.
create trigger teams_path_oversight
    before update of parent_id on teams
    for each row execute function teams_move_keeps_oversight();
