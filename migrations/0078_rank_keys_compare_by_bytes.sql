-- Ключи порядка сравниваются побайтово.
--
-- Позиция карточки и колонки — ключ из internal/rank: алфавит
-- 0-9A-Za-z, порядок символов совпадает с порядком их байтов, и код
-- рассчитывает на то, что `order by position` и `position > $1` в базе
-- сравнивают так же. Но столбцы были заведены без правила сравнения
-- и сравнивались по локали базы. На musl (наша разработка, alpine)
-- локаль сравнивает побайтово, и расхождения не было видно. На базе
-- с настоящей локалью — ru_RU, en_US на glibc или ICU — регистр почти
-- не различается: побайтово «aZ» < «aa», по локали «aZ» > «aa».
--
-- Пока ключи из одних цифр, порядки совпадают. Перенос сотни карточек
-- выдаёт ключи с буквами обоих регистров, и после него «последней
-- карточкой колонки» база называла не последнюю: ключ «после неё»
-- совпадал с занятым, и заведение и перенос карточки на такой доске
-- падали на cards_order_key (прод 06.10.2026, v0.3.1, после переноса
-- доски). Заодно порядок карточек на экране расходился с задуманным.
--
-- Правило «C» — побайтовое. Равенство ключей от него не меняется (оба
-- правила детерминированные), поэтому новых повторов не появится;
-- меняется только порядок — на тот, по которому ключи и строились.
-- Индекс cards_order_key база перестроит сама. Таблица не
-- переписывается: тип тот же.
--
-- Совместимость со старой версией: она работает на новой схеме и
-- работает правильно — её запросы те же, сравнение становится тем,
-- на которое они рассчитаны. Повторный запуск безвреден: правило уже
-- то же.
alter table cards         alter column position type text collate "C";
alter table board_columns alter column position type text collate "C";
