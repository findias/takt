-- Владелец подразделения приглашает людей в своё подразделение.
--
-- Этап 31, решение владельца 26.09.2026: администратор области и есть
-- владелец подразделения, одно назначение, а не два. Половину его прав
-- дала 0018 — состав узлов, вложенные узлы, доски поддерева. Людей
-- в организацию приводил только владелец организации, и в дереве
-- из пяти уровней весь приток людей шёл через одного человека.
--
-- Приглашение получает узел: человек входит в организацию и сразу
-- в этот узел. Владелец организации по-прежнему приглашает куда угодно
-- или никуда; владелец подразделения — только в своё поддерево
-- и только участником или наблюдателем. Роль в организации общая
-- на все ветки, и владельца организации из ветки не выдают.
--
-- Совместимость со старой версией: колонка необязательная и без
-- умолчания, старый код её не пишет и не читает; его приглашения
-- делает владелец организации, а ему новая политика не мешает.

alter table invites
    add column team_id uuid references teams (id) on delete set null;

-- Прежде право приглашать держал только обработчик (`s.owner`),
-- а политика у приглашений была одна — по арендатору: любой вошедший
-- мог бы вставить строку мимо обработчика. Теперь право — в базе,
-- и обработчику решать нечего.
--
-- Политика ограничивающая, поэтому пропускает всех, кто обращается
-- к приглашениям законно: принимающий по токену (Accept пишет
-- «принято», уже назвав себя), уборщик без личности, владелец
-- организации, владелец подразделения — в пределах поддерева.
create policy managed on invites as restrictive for all
    using (
           token_hash = (select nullif(current_setting('app.invite_token', true), ''))
        or (select app_no_actor())
        or (select app_is_owner())
        or team_id = any (array(select unnest(app_admin_teams())))
    )
    with check (
           token_hash = (select nullif(current_setting('app.invite_token', true), ''))
        or (select app_is_owner())
        or (role in ('member', 'viewer')
            and team_id = any (array(select unnest(app_admin_teams()))))
    );

-- Принявший вписывает себя в узел приглашения сам: вписывать людей
-- в узлы вправе владелец и владелец подразделения, а в момент
-- принятия действует приглашённый. Разрешение узкое — только себя
-- и только в узел того приглашения, которое открыл его токен.
create policy joins_by_invite on team_members for insert
    with check (
        user_id = (select app_current_user())
        and exists (
            select 1 from invites i
             where i.team_id = team_members.team_id
               and i.token_hash = (select nullif(current_setting('app.invite_token', true), ''))
        )
    );
