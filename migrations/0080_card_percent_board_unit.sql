-- Процент выполнения карточки и единица оценки доски (ROADMAP 38).
--
-- Процент — ручной: пусто значит «считать само» — из частей, если они
-- есть, и из отметки «сделано». Прежде здесь стояло решение процент
-- руками не хранить («поле, которое никто не обновляет»); владелец
-- решил иначе: доля работы внутри задачи без частей видна только тому,
-- кто её делает, и сказать её можно только руками. Счёт родителя
-- теперь учитывает и ручной процент части — часть на 40% даёт ему 0,4,
-- а не ноль.
--
-- Единица оценки — у доски, пусто — как у организации. Команды
-- оценивают по-разному: одна очками, другая часами, и общая единица
-- заставляла одну из них врать в подписи.
--
-- Обе колонки без умолчания и допускают пусто: старая версия их
-- не читает и на новой схеме работает как прежде.

alter table cards
    add column percent smallint
        constraint cards_percent_range check (percent between 0 and 100);

alter table boards
    add column estimate_unit text
        constraint boards_estimate_unit_valid check (estimate_unit in ('points', 'hours', 'days'));
