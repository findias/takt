-- Блокировка со ссылкой на работу, которая держит.
--
-- Причину блокировки писали словами, и для большинства случаев это
-- верно: «нет доступа к стенду», «ждём ответа юристов» — список готовых
-- формулировок отвечал бы не на тот вопрос. Но один случай словами
-- описывается плохо, и он самый частый: держит другая карточка, чаще
-- всего собственная часть этой же работы. Написанное про неё словами
-- нельзя ни открыть, ни сверить с тем, что с ней стало, — а спрашивают
-- именно это: «что там у того, кого мы ждём».
--
-- Поэтому ссылка, а не текст с названием. Название переименуют, и текст
-- начнёт врать задним числом — журнал блокировок при этом обязан
-- оставаться правдой о прошлом. Ссылка же показывает нынешнее имя
-- и нынешнее состояние: часть могли уже сделать, и тогда блокировку
-- пора снимать — интерфейс скажет об этом сам.
--
-- Причина словами остаётся и остаётся обязательной: ссылка говорит,
-- кого ждём, но не говорит, чего именно от него ждут. «Ждём ПОСТ-9»
-- без слов — это половина ответа, и вторую половину пришлось бы искать
-- в переписке.
--
-- Автоматической такая блокировка не становится. Блокировка — интервал,
-- из которого считается время в блоке, и наполнять его выведенными
-- интервалами («часть не сделана — значит родитель стоит») значит
-- испортить единственную честную меру: работа над родителем часто идёт
-- и при незакрытой части. Ставит её человек, снимает тоже человек.
--
-- on delete set null, а не cascade: карточку могут удалить насовсем,
-- а блокировка — запись о прошлом, из которой считается время
-- разрешения блокировок. Пропасть ей нельзя, а ссылке — можно.

alter table card_blocks
    add column blocking_card uuid references cards (id) on delete set null;

