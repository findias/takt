-- Связь «подзадача» видна и со стороны самой подзадачи (этап 32.2).
--
-- До сих пор связь читалась по видимости карточки-источника (0006):
-- родитель виден — видна и связь. Подзадача, чей родитель лежит
-- на закрытой доске, не знала, что у неё родитель есть вовсе: путь
-- «Эпик › Фича» в панели карточки обрывался молча, и работа выглядела
-- самостоятельной, хотя её делают ради чужого эпика.
--
-- Видна строка связи, а не родитель: его название и доску по-прежнему
-- закрывает политика карточек, и на экране звено называется
-- «недоступная карточка». Существование связи скрывать незачем —
-- то же правило записано у снимка доски (Snapshot.Linked), — а содержимое
-- недоступной доски раскрывать нельзя, и оно не раскрывается.
--
-- Только чтение и только подзадачи: «блокирует» и «связана» по-прежнему
-- видны со стороны источника, а менять связь может лишь тот, кто видит
-- родителя (политика writable не тронута).
--
-- Политика только добавляется: старая версия приложения на новой схеме
-- видит на одну строку больше и уже умеет её показать — клиент называет
-- карточку, которой нет в снимке, «недоступной» (resolve в
-- web/src/entities/card/model.ts).

create policy visible_from_child on card_links for select
    using (kind = 'subtask' and to_card in (select id from cards));
