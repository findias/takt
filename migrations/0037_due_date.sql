-- Дата обязательства: то, что обещано наружу.
--
-- Поля срока в системе не было намеренно, и довод остаётся верным:
-- канбан обещает распределение, а не дату, и главная пометка на
-- карточке — «идёт дольше, чем доска обещала», а не «просрочена».
-- Срок, поставленный всем подряд, превращается в ритуал переноса дат,
-- за которым перестают следить в первую же неделю.
--
-- Но у части работы дата есть на самом деле, и она не наша: релиз,
-- демонстрация, договор, регламент со сроком ответа. Про такую работу
-- вопрос «успеваем ли к четвергу» задают вслух, а система на него
-- ответить не могла — и его считали в уме. Это и записано в разборе
-- глазами тимлида: «дату не надо ставить всем — надо, чтобы её можно
-- было поставить тем, у кого она есть».
--
-- Поэтому дата необязательна и пуста по умолчанию. Пусто — не «дата
-- неизвестна», а «обязательства нет»: это разные вещи, и вторая
-- не требует ни ответа, ни напоминания.
--
-- Тип date, а не timestamptz: обещают день, а не мгновение. Час
-- в такой дате был бы выдумкой, а часовой пояс — выдумкой вдвойне:
-- «к четвергу» одинаково звучит в Москве и Новосибирске.

alter table cards add column due_on date;

-- Спрашивают «что горит по срокам», то есть про ближайшие и просроченные.
-- Частичный индекс ровно под этот вопрос: у большинства карточек даты
-- нет, и полный индекс был бы наполовину из NULL.
create index cards_due_idx on cards (board_id, due_on)
    where due_on is not null and archived_at is null;
