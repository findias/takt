-- Идентификатор операции уникален внутри организации, а не во всей базе.
--
-- Обнаружено тестом, который дважды использовал один и тот же
-- идентификатор — в разных организациях. Ожидался обычный повтор
-- операции, пришла внутренняя ошибка.
--
-- Механика такая. Первичный ключ `operations.operation_id` глобален,
-- поэтому вставка натыкается на чужую строку и не срабатывает —
-- `on conflict do nothing`. Код читает это как «операция уже выполнялась»
-- и идёт за сохранённым результатом, а его не видно: строка принадлежит
-- другому арендатору, политика её скрывает. Запрос не находит ничего,
-- и наружу выходит пятисотка.
--
-- Ограничения целостности проверяются в обход политик — это сказано
-- в документации Postgres прямо, и там же названо ковровой дорожкой
-- для утечки: по отказу уникальности можно узнать о существовании
-- строки, которой не видно. Отсюда правило, которому мы до сих пор
-- следовали не везде: всякая уникальность, которой распоряжается клиент,
-- должна быть уникальностью внутри арендатора.
--
-- Практическая вероятность столкновения случайных uuid ничтожна. Дело
-- не в ней: пока ключ глобален, поведение одной организации зависит от
-- другой, а изоляция арендаторов — то свойство, которое либо есть, либо
-- его нет.

alter table operations drop constraint operations_pkey;
alter table operations add primary key (org_id, operation_id);

-- Чтение сохранённого результата идёт по обоим столбцам, и новый ключ
-- его же и обслуживает. Отдельный индекс не нужен.
