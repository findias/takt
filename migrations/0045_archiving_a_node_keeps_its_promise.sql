-- Убрать подразделение с досками или отделами нельзя — какой бы дверью
-- ни шли.
--
-- Правило записано давно и жило в одном месте: `team.Archive` считал
-- живых потомков и живые доски и отказывал. Дверей же оказалось две.
-- Каталог по SCIM убирает группу тем же архивированием, но своим
-- запросом — `update teams set archived_at = now()`, — и проверки
-- не делал.
--
-- Прогон 22 августа 2026: владелец получил на тот же узел
-- 409 «сначала перенесите вложенные команды и доски», а ключ каталога
-- следом получил 204. После этого в дереве остался живой отдел
-- «Платформа» с `parent_id` на архивированную «Разработку» — узел,
-- у которого есть старший, но старшего нет в дереве, — а доска
-- «Поставки» осталась приписанной к архивированному подразделению,
-- то есть перестала быть видной всем, кто видел её этим подразделением.
--
-- Это третий случай за день, когда одно правило охраняло одну дверь
-- из двух: так же было у наблюдения и прав администратора (списки
-- показывали убранное) и у переноса подразделения (политика стерегла
-- узел, но не его собственный корень). Поэтому правило переезжает
-- в базу: код может забыть, триггер стоит на самой строке.
--
-- Проверяется только уход в архив. Возврат не трогаем: у возвращаемого
-- узла потомки и доски и так на месте, а мешать возврату — значит
-- запирать в архиве то, что туда положили.

create function teams_archive_needs_empty() returns trigger
language plpgsql
as $$
begin
    if not (old.archived_at is null and new.archived_at is not null) then
        return new;
    end if;

    if exists (select 1 from teams
                where parent_id = new.id and archived_at is null)
       or exists (select 1 from boards
                   where team_id = new.id and archived_at is null) then
        raise exception 'сначала перенесите вложенные команды и доски'
            using errcode = 'check_violation';
    end if;

    return new;
end;
$$;

create trigger teams_archive_empty
    before update of archived_at on teams
    for each row execute function teams_archive_needs_empty();
