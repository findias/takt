-- Уровень доски: «команда» или «портфель» (этап 33).
--
-- Эпик — это карточка доски-портфеля, а не форма дерева. Правило этапа
-- 32.6 («карточка с внуками — эпик») не держалось: эпик с фичами без
-- задач ещё не был эпиком, а метрики менялись задним числом, когда
-- кто-то добавлял подзадачу. Рынок и методика (Azure DevOps, Kaiten,
-- Flight Levels) держат крупное на своём уровне со своим потоком;
-- у нас уровень задаёт доска, и типов карточек по-прежнему нет.
--
-- С умолчанием 'team': старая версия приложения колонку не замечает,
-- все существующие доски остаются досками команд.
alter table boards add column level text not null default 'team'
    constraint boards_level_valid check (level in ('team', 'portfolio'));
