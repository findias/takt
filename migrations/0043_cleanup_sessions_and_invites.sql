-- Уборка того, что растёт без предела: сессии и отработавшие приглашения.
--
-- СЕССИИ. Строка живёт тридцать суток и после этого не пускает — но
-- продолжает лежать. Каждый вход добавляет новую; выход удаляет свою,
-- но выходят не все, а сессии заводит ещё и каждый вход через провайдера.
-- Таблица под RLS не попадает (она из таблиц личности), поэтому уборщику
-- ничего разрешать не нужно — только начать удалять.
--
-- ПРИГЛАШЕНИЯ. Строка хранит почту приглашённого и остаётся навсегда:
-- принятая, отозванная, просроченная. Это не журнал, а рабочая таблица,
-- и после того, как приглашение перестало действовать, читать её незачем —
-- факт «звали такого-то» лежит в журнале действий и убирается сроком
-- организации. Хуже: обезличивание участника оставляло его почту здесь,
-- хотя обещало, что персональных данных не останется.
--
-- Уборщик ходит без арендатора, а изоляция у приглашений требует его
-- выставленным. Приводить её к «пусто — значит всё» здесь нельзя:
-- областью без арендатора ходят и обмен по ключу, и приём приглашения,
-- и работник вебхуков, — им приглашения открывать незачем. Поэтому
-- уборщику выдаётся отдельная пара политик, и видит он ровно то, что и так
-- обязан стереть.

-- Месяц после того, как приглашение перестало действовать. Не сутки:
-- «кого мы звали в прошлом месяце» — живой вопрос, и ответ на него
-- лучше брать из самой таблицы, пока он там есть. Тот же срок стоит
-- в internal/retention; разойтись им нельзя, иначе уборка молча
-- перестанет что-либо находить.
create policy cleanup on invites for delete
    using (
        (select app_current_org()) is null
        and coalesce(accepted_at, revoked_at, expires_at) < now() - interval '30 days'
    );

-- Одного разрешения на удаление мало: чтобы понять, какие строки удалять,
-- база их читает, и к delete подмешивается политика чтения. Без личности
-- обе прежние ложны — уборщик оказался бы невидим сам для себя.
create policy cleanup_reads on invites for select
    using (
        (select app_current_org()) is null
        and coalesce(accepted_at, revoked_at, expires_at) < now() - interval '30 days'
    );
