-- Владелец, которого считают, — это человек.
--
-- «Последнего владельца снять нельзя» — правило старое, записанное
-- в двух местах: `org.ensureOtherOwnerExists` и `scim.deactivate`.
-- Оба считали владельцев одинаково и одинаково неверно: `select count(*)
-- from memberships where role = 'owner' and user_id <> …`, без вопроса,
-- человек ли это.
--
-- А владельцем бывает не только человек. Ключ каталога получает роль
-- владельца организации — этого требуют политики базы, чтобы заводить
-- людей, — и его служебная личность стоит в составе рядом со всеми.
-- Значит, в любой организации, где заведён такой ключ, «другой
-- владелец» находится всегда.
--
-- Прогон 22 августа 2026: в организации двое — человек с ролью владельца
-- и служебная личность ключа каталога с той же ролью. Человек снял сам
-- себя, получил 204, и следующий же запрос ответил «нужно войти».
-- Организация осталась с владельцем, который не умеет входить: войти
-- паролем служебной личности нельзя (это записано как «цело» в разборе
-- входа), а больше владельцев нет. Чинится руками в базе — ровно то,
-- ради чего правило и писали.
--
-- Считать теперь одной функцией. Сторожа остаются каждый на своём
-- месте — они отвечают по-разному и разными словами, — но «кто
-- считается владельцем» определено один раз, и разойтись этим двум
-- ответам больше негде.

create function app_other_person_owners(org uuid, except_user uuid)
    returns integer
language sql stable
as $$
    select count(*)::integer
      from memberships m
      join users u on u.id = m.user_id
     where m.org_id = org
       and m.role = 'owner'
       and m.user_id <> except_user
       and u.kind = 'person'
$$;
