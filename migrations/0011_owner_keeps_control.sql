-- Владелец организации не может потерять управление доской.
--
-- Дефект обнаружен тестом, который просто попробовал вернуть доску
-- обратно организации после передачи её команде.
--
-- Список досок, доступных на запись, считался по членству: своя команда
-- или поимённая запись в доску. Владелец организации не попадает ни туда,
-- ни туда — он видит командные доски по должности, а не по участию.
-- Значит, отдав доску команде, в которой не состоит, он терял право её
-- изменить: ни вернуть организации, ни передать другой команде, ни
-- переименовать. Починить это можно было только руками в базе.
--
-- Ловушка того же рода, что и «закрыть доску вокруг чужих людей», и
-- лечится тем же принципом: необратимых состояний быть не должно. Разница
-- в том, что там необратимость оказалась осмысленной — закрытая доска
-- и должна закрываться только вокруг себя, — а здесь она бессмысленна:
-- владелец и так видит эту доску, отказ в изменении ничего не защищает.
--
-- Закрытые доски остаются исключением. Владелец их не видит — значит,
-- и не пишет. Это ровно то, ради чего слово «закрытая» существует,
-- и единственное исключение из «видит всё» мы уже объявили намеренным.
--
-- Наблюдателя это не касается: «видит всё» и «может всё» — разные
-- вопросы, и наблюдение не даёт права писать ни при какой должности.

create or replace function app_writable_boards() returns uuid[]
language sql stable parallel safe
as $$
    select coalesce(array_agg(b.id), '{}')
      from boards b
     where (select app_can_write())
       and b.archived_at is null
       and (b.visibility = 'org'
            or b.team_id = any (array(select unnest(app_member_teams())))
            or b.id = any (array(select bm.board_id from board_members bm
                                  where bm.user_id = (select app_current_user())))
            -- Владелец организации управляет всем, что видит.
            or (b.visibility <> 'private' and (select app_is_owner())))
$$;
