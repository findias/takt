-- «Работаем итерациями» — обратимый переключатель доски (этап 32.4).
--
-- Жёсткого режима «Скрам/Канбан» не заводим: режим, который прячет
-- возможности, запирает команду — начала канбаном, захотела итераций,
-- переделывай доску. Вместо него шаблон при создании (он нигде
-- не хранится) и эта одна настройка.
--
-- Выключенная прячет итерации с экрана доски, но ничего не удаляет:
-- включение возвращает всё как было, отчёты по закрытым итерациям
-- на месте.
--
-- С умолчанием true: старая версия приложения колонку не замечает,
-- а все существующие доски продолжают работать итерациями, как раньше.
alter table boards add column iterations_enabled boolean not null default true;
