-- Отпечаток тела у ключа повтора.
--
-- Ключ сверялся с методом и путём, но не с телом. Значит два разных
-- запроса, посланных с одним ключом по одному адресу, — «заведи доску
-- „Найм“» и «заведи доску „Продажи“» — выглядели для нас одним
-- и тем же: второй получал 201 с телом первой доски, своей доски
-- не заводил, и по ответу это было неотличимо от успеха. Ошибка
-- в клиенте (ключ, не сброшенный между вызовами) доставалась не тому,
-- у кого она есть, а данным — через неделю, когда кто-то заметит, что
-- доски нет.
--
-- Отпечаток — sha256 от тела запроса. Хранится хеш, а не тело: сверять
-- нужно совпадение, а не содержимое, и держать вторую копию присланного
-- незачем — тем более что в теле бывает и то, чего в базе быть
-- не должно.
--
-- Пусто значит «отпечатка не было»: записи живут сутки, и те, что
-- заведены до этой миграции, доживут свой срок без него. Сверка
-- пропускается, а не считает пустое отпечатком — иначе первый же
-- повтор старого ключа получил бы отказ на ровном месте.

alter table api_idempotency add column fingerprint text;
