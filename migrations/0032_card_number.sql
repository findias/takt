-- Уникальный номер задачи.
--
-- До сих пор у карточки был только UUID. Его нельзя назвать вслух,
-- нельзя написать в переписке, нельзя ввести в поиск — а ссылаться
-- на задачу извне доски приходится постоянно: в разговоре, в коммите,
-- в письме, в постановке работы соседней команде.
--
-- Пространство номеров — доска. Выбор между доской и организацией
-- решался один раз и не задним числом: сквозной номер по организации
-- (#1423) никогда не врёт, но и не говорит, чья это работа, а в разговоре
-- двух команд именно это и нужно. Номер вида ПРО-142 отвечает сразу
-- и «какая задача», и «чья».
--
-- Номер неизменен. Это главное свойство, ради которого он заводится:
-- ссылка, написанная в переписке год назад, обязана вести туда же.
-- Отсюда два следствия, и оба намеренные.
--
-- Первое: номер хранится целиком строкой, а не собирается на лету из
-- ключа доски и счётчика. Собираемый номер поехал бы при первом же
-- переименовании ключа и утащил бы за собой все ссылки.
--
-- Второе: ключ доски задаётся при создании и потом не меняется — в схеме
-- его менять никто не запрещает, но операции переименования ключа нет
-- и не будет. Иначе на одной доске оказались бы карточки с двумя разными
-- префиксами: старые с прежним, новые с новым.
--
-- Счётчик живёт на доске, а не считается как count(*) по карточкам:
-- посчитанный номер переиспользовался бы после архивации последней
-- карточки, и два разных дела получили бы одно имя.

alter table boards add column key text;
-- Счётчик выданных номеров. Выданное не возвращается: архивация
-- карточки счётчик не откатывает.
alter table boards add column card_seq bigint not null default 0;

alter table cards add column number text;

-- --- Перенос ---
--
-- Политики снимаются на время правки данных. Миграция идёт под ролью
-- приложения, а ей видно только строки своей организации — и «своей»
-- у неё сейчас нет ни одной. Без этого весь перенос ниже прошёл бы
-- вхолостую и молча: ключи не проставились бы, номера не выдались бы,
-- а not null в конце упал бы уже на пустом месте, не объяснив почему.
alter table boards no force row level security;
alter table cards  no force row level security;

-- Проверка сторожит условие, а не результат: считать «сколько строк
-- обновилось» бессмысленно, этот счёт идёт под теми же политиками
-- и вернёт тот же ноль, что и сам перенос.
do $$
begin
    if (select bool_or(relforcerowsecurity) from pg_class
         where relname in ('boards', 'cards')
           and relnamespace = 'public'::regnamespace) then
        raise exception 'перенос пошёл бы вхолостую: политики ещё действуют';
    end if;
end $$;

-- Ключ существующей доски выводится из названия: первые четыре буквы
-- без пробелов и знаков. Ровно то же правило записано в deriveKey —
-- оно потому и простое, что записано в двух местах, и сложное разъехалось
-- бы между ними. Совпадения разводятся номером по старшинству: у первой
-- заведённой доски ключ остаётся чистым.
--
-- Архивные доски участвуют наравне с живыми: их номера уже написаны
-- в чьей-то переписке, и отдавать их ключ другой доске нельзя.
with derived as (
    select id,
           case when length(regexp_replace(name, '[^[:alnum:]]', '', 'g')) < 2
                then 'ДОСКА'
                else upper(substring(
                     regexp_replace(name, '[^[:alnum:]]', '', 'g') from 1 for 4))
           end as base
      from boards
), ranked as (
    select id, base,
           row_number() over (partition by org_id, base
                              order by created_at, id) as n
      from derived join boards using (id)
)
update boards b
   set key = case when r.n = 1 then r.base else r.base || r.n end
  from ranked r
 where b.id = r.id;

-- Номера выдаются по старшинству карточек: порядок создания — то
-- единственное, что здесь можно восстановить честно.
--
-- Архивные карточки нумеруются тоже. Архив у нас обратим, и карточка,
-- вернувшаяся из него без номера, оказалась бы единственной безымянной.
with numbered as (
    select c.id,
           b.key || '-' || row_number() over (partition by c.board_id
                                              order by c.created_at, c.id) as number
      from cards c join boards b on b.id = c.board_id
)
update cards c set number = n.number from numbered n where c.id = n.id;

-- Счётчик доски встаёт на последний выданный номер.
update boards b
   set card_seq = coalesce((select count(*) from cards c where c.board_id = b.id), 0);

alter table boards force row level security;
alter table cards  force row level security;

-- --- Ограничения ---
--
-- Ставятся после переноса: до него все строки пусты и not null упал бы
-- на первой же.
alter table boards alter column key set not null;
alter table cards  alter column number set not null;

-- Ключ уникален в организации, номер — тоже. Архивные считаются: имя,
-- однажды выданное, второй раз не выдаётся.
-- Он же индекс, по которому идёт поиск по номеру: отдельный не нужен,
-- уникальный ищет не хуже.
create unique index boards_key_key on boards (org_id, key);
create unique index cards_number_key on cards (org_id, number);
