-- Исполнитель — только тот, кто видит доску.
--
-- Назначить можно было любого участника организации: на доске
-- подразделения — человека из соседней ветки, на закрытой — того, кого
-- в неё не звали. Такой исполнитель не находит свою карточку, а
-- известие о назначении ему не показывается: уведомление видно, только
-- пока видна доска (0057). Работа числится за человеком, который о ней
-- не знает.
--
-- «Видит ли доску он» — вопрос политики visible на boards, но политика
-- отвечает про текущего пользователя, а спрашивают про другого.
-- Переписать её условие здесь второй раз нельзя: две копии правила
-- разойдутся при первой правке видимости. А повторить его в коде
-- и не получится — состав закрытой доски под ролью приложения видит
-- только владелец организации (0006, board_members).
--
-- Поэтому функция спрашивает саму политику: на время одного запроса
-- текущим пользователем становится назначаемый, и возвращается прежний.
-- Настройка транзакционная (как её ставит store), наружу функции
-- подстановка не выходит.
--
-- Спрашивать можно только о доске, которую видит сам спрашивающий:
-- иначе функция отвечала бы о чужих закрытых досках, которых
-- спрашивающему не видно. Участникам закрытой доски она показывает, кто
-- ещё её видит, — это то же, что показывает список исполнителей, и без
-- этого назначить на такой доске было бы некого.
--
-- volatile, а не stable: функция меняет настройку сеанса.
--
-- Совместимость со старой версией: новая функция, ничего не меняется.
create function app_sees_board_as(u uuid, b uuid) returns boolean
language plpgsql volatile
as $fn$
declare
    me   text := current_setting('app.current_user', true);
    seen boolean;
begin
    if u is null or b is null or not exists (select 1 from boards where id = b) then
        return false;
    end if;
    perform set_config('app.current_user', u::text, true);
    seen := exists (select 1 from boards where id = b);
    perform set_config('app.current_user', coalesce(me, ''), true);
    return seen;
end $fn$;
