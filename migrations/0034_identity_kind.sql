-- Личность знает, человек она или ключ.
--
-- Служебные личности клиентов (0020) устроены нарочно так же, как люди:
-- строка в `users`, членство в организации, имя под работой. Это решение
-- себя оправдало — политики доступа обошлись без второй ветки, а журнал
-- действий получил автора вместо пустоты.
--
-- Но у решения оказалась цена, которую видно только на экране: в списке
-- людей организации ключ стоит человеком. Ему предлагают роль,
-- «Исключить» и «Удалить данные» — причём последнее отвечает отказом
-- «это служебная личность ключа», то есть система предлагает то, чего
-- сама не разрешает. Это нашёл сквозной проход (11.6).
--
-- Отличить одно от другого можно было и без новой колонки — по наличию
-- строки в `api_clients`. Так нельзя по двум причинам. Первая: список
-- ключей видит только владелец организации, а «это не человек» должно
-- читаться всем, кто видит имя, — оно попадается на карточках и
-- в журнале. Вторая: `api_clients` знает про ключ, а вопрос задаётся
-- о личности, и ответ на него принадлежит личности.
--
-- Значение по умолчанию — «человек»: людей на порядки больше, и всякая
-- личность, заведённая любым путём (регистрация, приглашение,
-- корпоративный вход, SCIM), человеком и является.

alter table users
    add column kind text not null default 'person'
        constraint users_kind_valid check (kind in ('person', 'service'));

-- Уже заведённые ключи. Политика арендатора на api_clients снимается
-- на время правки: миграция идёт под ролью приложения, арендатора у неё
-- нет, а select на api_clients открыт только владельцу организации либо
-- предъявителю токена — то есть подзапрос вернул бы ноль строк, и
-- обновление молча прошло бы вхолостую.
alter table api_clients no force row level security;

-- Проверяется условие, а не результат: счёт строк идёт под теми же
-- политиками и вернул бы тот же ноль, что и сама правка.
do $$
begin
    if (select relforcerowsecurity from pg_class
         where relname = 'api_clients' and relnamespace = 'public'::regnamespace) then
        raise exception 'правка пошла бы вхолостую: политики на api_clients ещё действуют';
    end if;
end $$;

update users set kind = 'service'
 where id in (select user_id from api_clients);

alter table api_clients force row level security;
