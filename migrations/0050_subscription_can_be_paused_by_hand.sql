-- Остановить, не удаляя.
--
-- Подписку можно было только завести и удалить. Получатель на плановых
-- работах — и выбор такой: терпеть два часа отказов, после которых
-- работник отключит подписку сам, или удалить её и завести заново,
-- потеряв ключ подписи (он показывается один раз) и весь журнал
-- доставок. То есть единственное вмешательство в идущую работу было
-- необратимым — при том, что правило продукта прямо обратное:
-- необратимое спрашивает, обратимое — нет.
--
-- Своя колонка, а не disabled_at: они значат разное и читаются человеку
-- разными словами. `disabled_at` — «мы сдались после восьми попыток,
-- получатель не отвечает»; `paused_at` — «остановлено человеком, ждём
-- его же». Свести их в одну значило бы отвечать «получатель
-- не отвечает» на паузу, которую человек поставил сам.
--
-- Пока пауза стоит, доставки не создаются вовсе — очередь не копится.
-- Иначе возобновление обернулось бы лавиной событий за все прошедшие
-- сутки, и получатель, ради которого паузу и ставили, лёг бы вторично.
alter table webhooks add column paused_at timestamptz;

-- Индекс живых подписок теперь считает живой ту, что и доставляет:
-- ни отключённую, ни приостановленную.
drop index webhooks_org_idx;
create index webhooks_org_idx on webhooks (org_id)
    where disabled_at is null and paused_at is null;
