-- Архивная доска остаётся доступной на запись, иначе её не вернуть.
--
-- Список досок, доступных на запись, исключал архивные. Выглядело
-- разумно — в архивную доску незачем писать, — но означало, что доска,
-- однажды убранная, не может быть возвращена ничем, кроме запроса
-- к базе: снятие отметки архива это тот же update.
--
-- Третья ловушка одного и того же рода. Первая: доску нельзя было закрыть
-- вокруг себя. Вторая: владелец, отдавший доску чужой команде, терял над
-- ней власть. Здесь то же самое — состояние, из которого нет выхода
-- обычными средствами. Разница только в том, что в первом случае
-- необратимость оказалась осмысленной, а в двух других — нет.
--
-- Что теряется: защита от записи в архивную доску на уровне базы. Она
-- остаётся на уровне приложения, и там она в одном месте — операция
-- начинается с блокировки строки доски условием `archived_at is null`,
-- и архивная доска отвечает «не найдена» на всё. Это проверяется тестом.
--
-- Обмен сознательный: одно проверяемое место в коде против состояния,
-- которое чинится только руками в базе.

create or replace function app_writable_boards() returns uuid[]
language sql stable parallel safe
as $$
    select coalesce(array_agg(b.id), '{}')
      from boards b
     where (select app_can_write())
       and (b.visibility = 'org'
            or b.team_id = any (array(select unnest(app_member_teams())))
            or b.id = any (array(select bm.board_id from board_members bm
                                  where bm.user_id = (select app_current_user())))
            or (b.visibility <> 'private' and (select app_is_owner())))
$$;
