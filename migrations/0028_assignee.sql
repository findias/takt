-- Исполнитель карточки.
--
-- Доска, которая не отвечает на вопрос «кто это делает», отвечает
-- на половину вопросов, ради которых её открывают. До сих пор такого
-- поля не было вовсе: ни в схеме, ни в API, ни на экране.
--
-- Один, а не список. Список исполнителей выглядит гибче ровно до первого
-- разбора: «делают трое» означает, что не делает никто конкретно, и на
-- стендапе спрашивать некого. Так же решено у Linear и в Jira по
-- умолчанию; Trello с его списком участников — про другое, там карточка
-- часто и есть обсуждение.
--
-- Ссылка на users, а не на memberships: человек может уйти из
-- организации, и его участие исчезнет, а карточки, которые он делал,
-- останутся — вместе с подписью, кто их делал. Проверку «состоит
-- в организации» делает операция назначения, а не внешний ключ:
-- ключу пришлось бы каскадно снимать исполнителя при исключении,
-- то есть переписывать историю.

alter table cards
    add column assignee_id uuid references users (id);

comment on column cards.assignee_id is
    'Кто делает карточку. Пусто — никто не назначен, и это нормальное состояние: работа сначала появляется, потом обретает исполнителя.';

-- «Что на мне» — главный вопрос к доске после «что происходит».
-- Индекс частичный: у большинства карточек в очереди исполнителя нет.
create index cards_assignee_idx
    on cards (org_id, assignee_id)
    where assignee_id is not null and archived_at is null;
