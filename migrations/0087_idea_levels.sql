-- Перенос идеи между уровнями (ROADMAP 45, решение владельца
-- 30.10.2026): идея живёт на уровне всей организации или подразделения
-- любой глубины, и уровень меняется — подали не туда, или подразделение
-- решило, что вопрос «выше нас».
--
-- Правка строки идеи и так открыта автору и владельцу организации
-- (`own`, 0083). Владелец подразделения решает идеи своего поддерева
-- (0084), а перенести их не мог. Здесь — может: внутрь своего поддерева
-- или на всю организацию. В чужое подразделение — нет: там решает
-- другой, и адресовать ему вопрос без его ведома — не перенос,
-- а подкидывание. Кто переносит и когда (автор — пока не решили,
-- решённую — никто) — словами в коде; политика держит границу области.
create policy retarget on ideas for update
    using (team_id is not null and team_id = any (array(select unnest(app_admin_teams()))))
    with check (team_id is null or team_id = any (array(select unnest(app_admin_teams()))));
