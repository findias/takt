-- Язык интерфейса хранится у человека (ROADMAP 30.6).
--
-- До этой миграции язык жил в браузере, и человек, выбравший English
-- на работе, дома снова видел русский экран — а переключатель искал
-- на языке, которого не читает. Выбор переезжает между устройствами,
-- только если хранится при учётной записи.
--
-- Пусто — человек не выбирал, язык решает браузер, как прежде. Старая
-- версия приложения колонку не читает и не пишет, так что в окне
-- выкладки ничего не меняется.
--
-- Тема и плотность сюда не едут намеренно: они часто разные на разных
-- устройствах — светлая на ноутбуке, тёмная на телефоне.
alter table users add column lang text
    constraint users_lang_known check (lang in ('ru', 'en'));
