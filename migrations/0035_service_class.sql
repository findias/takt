-- Класс обслуживания: по каким правилам эту работу тянут.
--
-- Приоритет в этой доске уже есть, и это порядок карточек в колонке:
-- тянут сверху. Поля «приоритет» нет намеренно — число рядом с ручным
-- порядком даёт два ответа на вопрос «что раньше», обязанных совпадать
-- и не обязанных совпасть. Тем же доводом из 4.2 удалена роль в команде.
--
-- Класс отвечает на другой вопрос — не «что раньше», а «по каким
-- правилам это обслуживают». Срочное пропускают вперёд и держат
-- отдельным лимитом, потому что оно ломает поток и должно быть
-- редким; фоновое берут, когда нечем занять паузу, и обещаний по нему
-- не дают. Внутри класса порядок остаётся ручным — второго ответа
-- не появляется.
--
-- Канон (Kanban Guide) классов не требует, и раньше мы их не заводили
-- ровно поэтому: «в схеме это ещё одно поле, по которому потом считают
-- отдельные метрики; заводить его без спроса незачем» — так записано
-- в research/agile-canon.html. Спрос появился.
--
-- Классов три, а не четыре. Канонический «с фиксированной датой» без
-- самой даты — пустое слово: поля срока в системе нет, и заводить класс
-- под данные, которых не существует, значит обещать то, чего нет.
-- Появится дата обязательства — появится и класс, значения расширяются
-- проверкой, а не переписыванием.
--
-- Умолчание — «обычное»: класс есть у всякой карточки, и «не решили»
-- от «обычного» ничем не отличается. Пустое значение завело бы четвёртое
-- состояние, которое нечем обслуживать.

alter table cards
    add column service_class text not null default 'standard'
        constraint cards_service_class_valid
        check (service_class in ('expedite', 'standard', 'filler'));

-- Срочных на доске единицы, и спрашивают о них отдельно: «сколько
-- срочного сейчас в работе». Частичный индекс — ровно под этот вопрос,
-- полный был бы индексом по колонке из одного повторяющегося значения.
create index cards_expedite_idx on cards (board_id)
    where service_class = 'expedite' and archived_at is null;
