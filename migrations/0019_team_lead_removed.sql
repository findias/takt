-- Роль в команде убрана: ведущий — это тот, кто за команду отвечает.
--
-- `team_members.role` со значениями lead и member существовала с шестой
-- миграции и не влияла ни на что. Половинчатое состояние хуже любого
-- из двух ответов, и ответов было ровно два.
--
-- Дать ведущему права на доски команды? Тогда полномочие над узлом
-- выражается двумя способами сразу — записью в team_admins и пометкой
-- в составе, — и на вопрос «кто здесь распоряжается» появляются два
-- ответа, которые обязаны совпадать, но не обязаны совпасть. Мы уже
-- отказались от этого, когда сделали наблюдение записью, а не признаком.
--
-- Оставить пометкой «кто ведёт»? Тогда в интерфейсе висит слово,
-- за которым ничего нет: ведущий без полномочий выглядит как недоделка,
-- и первый же вопрос к нему — «а почему он тогда ведущий».
--
-- Поэтому пометка убирается, а «ведущий» показывается тем, у кого есть
-- запись администратора именно на этом узле. Один механизм вместо двух,
-- и ответ на вопрос «кто здесь распоряжается» ровно один.
--
-- Что теряется: проставленные значения роли. В обмен исчезает состояние,
-- в котором два поля описывают одно и то же и могут разойтись.

alter table team_members drop column role;
