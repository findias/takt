-- Удаление насовсем.
--
-- До сих пор в системе не было ни одной операции удаления: всё
-- архивируется, и это правильное умолчание — почти всё, что «удаляют»,
-- на самом деле убирают с глаз. Но остаётся то, чего архив не решает:
-- ошибочно заведённая доска, дубль карточки, тестовые данные и человек,
-- потребовавший удалить свои данные.
--
-- Разбирать здесь надо не право, а следы: что остаётся, когда объекта
-- больше нет. Ответ разделён по журналам, и разделён не поровну.
--
--   ЖУРНАЛ ПОТОКА (card_events) отвечает на вопрос «как шла работа».
--   Работы больше нет — значит и ответа быть не должно: оставленные
--   события говорили бы о карточке, которую не открыть, и попадали бы
--   в ленту доски как след живой работы. Стирается.
--
--   ЖУРНАЛ ДЕЙСТВИЙ (audit_events) отвечает на вопрос «кто что сделал».
--   Удаление — тоже действие, у него есть автор и время, и оно
--   записывается ровно в тот момент, когда стирается всё остальное.
--   Не стирается никогда: ни внешних ключей на доски и карточки у него
--   нет, ни политики удаления — кроме уборщика по сроку хранения.
--
-- Отсюда и главное свойство: после удаления нельзя узнать, как шла
-- работа, но всегда можно узнать, кто её убрал и что именно.
--
-- Право одно на всё — владелец организации. Администратор подразделения
-- сюда не допущен намеренно: его полномочие про то, как идёт работа,
-- а не про то, чтобы стереть её следы, и цена ошибки у этих двух вещей
-- разная настолько, что одного слова «администратор» для обоих мало.

-- --- 1. Доска удаляется только из архива ---
--
-- Условие стоит в политике, а не в коде: доска уносит работу целой
-- команды, и правило «сперва в архив, потом насовсем» должно держаться
-- и тогда, когда до базы дошли не через приложение. Архивация при этом
-- обратима, так что цена лишнего шага — одно нажатие.
create policy removable on boards for delete
    using ((select app_is_owner()) and archived_at is not null);

-- --- 2. Карточка удаляется там, где лежит ---
--
-- Здесь правила «сперва в архив» нет, и это не непоследовательность.
-- Убранная карточка сегодня не показывается нигде, то есть требование
-- архива означало бы «удалить нельзя»; а цена ошибки — одна карточка,
-- названная в подтверждении, против работы целой команды.
--
-- Политика ограничительная: она добавляется к writable, а не заменяет
-- её. Писать в карточки может участник доски, удалять — только владелец,
-- и слабейшее из двух разрешений побеждает.
create policy removable_by_owner on cards as restrictive for delete
    using ((select app_is_owner()));

-- --- 3. Журнал потока стирается вместе с работой ---
--
-- Единственное разрешение на удаление у этой таблицы. Дописывать в неё
-- может всякий, кто пишет в доску; убирать — только владелец и только
-- вместе с самой работой.
create policy prunable on card_events for delete
    using ((select app_is_owner()));

-- --- 4. Что именно удалили ---
--
-- Триггер, а не запись из кода: удаление, сделанное в обход приложения,
-- обязано попадать в журнал так же, как сделанное через API. Ровно тот
-- же довод, по которому весь audit_events ведётся триггерами.
create function audit_card_delete() returns trigger
language plpgsql as $$
begin
    -- Карточка, уехавшая вместе с доской, отдельной записи не получает:
    -- доска уже записана целиком, а пятьсот строк «удалена карточка»
    -- под ней — это утопленная лента, а не след. Условие честное:
    -- к моменту каскада строки доски уже нет, и «сама по себе»
    -- отличается от «вместе с доской» без всяких признаков.
    if exists (select 1 from boards where id = old.board_id) then
        insert into audit_events (org_id, actor_id, action, subject, subject_id, payload)
        values (old.org_id, (select app_current_user()), 'delete', 'cards', old.id,
                jsonb_build_object('new', to_jsonb(old)));
    end if;
    return null;
end $$;

create trigger audit_delete after delete on cards
    for each row execute function audit_card_delete();

-- --- 5. Человека не удаляют, а обезличивают ---
--
-- Строку `users` удалить нельзя, и это не ограничение, а смысл: на неё
-- ссылаются подписи под работой — журнал действий, назначения,
-- комментарии, — и половина ссылок без каскада. Удаление, стирающее
-- историю чужой работы, хуже отсутствия удаления.
--
-- Поэтому требование «удалите мои данные» исполняется обезличиванием:
-- личность остаётся, персональных данных в ней не остаётся. Имя, почта
-- и внешняя личность стираются, сессии обрываются, а подписи под работой
-- продолжают указывать на того же, кто её делал, — просто у него больше
-- нет имени.
--
-- Отметка нужна, чтобы отличать обезличенного от человека, которого
-- зовут странно: без неё интерфейсу пришлось бы угадывать по почте,
-- а угаданное однажды окажется неверным.
alter table users
    add column anonymized_at timestamptz;

comment on column users.anonymized_at is
    'Когда личность обезличена по требованию об удалении данных. Строка остаётся: на неё ссылаются подписи под работой.';
