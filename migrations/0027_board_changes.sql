-- Версия доски у операции: чтобы догонять изменения, а не перечитывать
-- доску целиком.
--
-- Сейчас клиент, узнав из потока «доска доехала до версии N», запрашивает
-- весь снимок. На десяти карточках это незаметно, на трёхстах — заметно,
-- и заметно тем сильнее, чем активнее работают: чем больше людей на доске,
-- тем чаще каждый из них перечитывает её целиком.
--
-- Между тем результат каждой операции уже сохранён в operations.result —
-- вместе с патчем, который клиент умеет применять. Не хватало одного:
-- по какому полю выбрать «всё, что случилось после версии N». Версия
-- лежала внутри jsonb, а выбирать по ней означало читать все строки доски
-- и разбирать json у каждой.
--
-- Отдельная колонка вместо выражения по jsonb: индекс по выражению тоже
-- возможен, но тогда порядок догоняющих патчей зависит от того, что кто-то
-- когда-то положил в json правильное число. Колонка с индексом честнее
-- и дешевле.

alter table operations
    add column board_version bigint;

comment on column operations.board_version is
    'Версия доски после этой операции. Пусто у операций, применённых до появления колонки: по ним догнать нельзя, клиент перечитает снимок.';

-- Догоняющий запрос всегда одинаков: «патчи этой доски после версии N
-- по возрастанию». Частичный индекс — потому что у старых операций
-- версии нет, и в индексе им делать нечего.
create index operations_catch_up_idx
    on operations (org_id, board_id, board_version)
    where board_version is not null;
