-- Пятый вид ссылки карточки — внешняя задача.
--
-- Работа живёт не только здесь: эпик заводят и в корпоративном трекере,
-- там он получает свой номер, и по этому номеру о нём говорят. Записать
-- номер было некуда: виды ссылок — заявки сервис-деска (0066), а
-- описание и своё поле номер прячут.
--
-- Вид один на все внешние системы, а не по виду на систему: системы
-- у заказчиков разные, и чья она, видно в самом номере («PRJ-482»)
-- или в адресе. Перечисление по-прежнему закрыто (0066): отчёт
-- сравнивает вид, а не подписи.
--
-- Совместимость со старой версией: условие только расширяется. Старый
-- код такую ссылку прочтёт и покажет без названия вида, завести её
-- не сможет — его проверка вида старая.
alter table card_refs drop constraint card_refs_kind_valid;
alter table card_refs add constraint card_refs_kind_valid
    check (kind in ('external', 'rds', 'zno', 'zni', 'problem'));
