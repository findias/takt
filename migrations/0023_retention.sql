-- Срок хранения: что убирается само и что не убирается никогда.
--
-- Три таблицы растут без предела и ничем не чистятся. Две из них
-- служебные, и хранить их вечно незачем; третья — журнал, и вот с ним
-- надо быть осторожным.
--
-- КЛЮЧИ ПОВТОРА. В своей миграции мы написали, что они живут недолго,
-- и на этом остановились: удалять их никто не начал. Смысл ключа —
-- пережить обрыв связи и повтор через минуту; недельной давности ключ
-- повторять уже некому. Сутки с запасом.
--
-- ДОСТАВКИ ВЕБХУКОВ. Доставленное держим месяц: по нему отвечают
-- на вопрос «дошло ли», и через месяц этот вопрос уже не задают.
-- Несдавшиеся не трогаем вовсе — они ждут ручного повтора, и вычистить
-- их значит потерять единственный след того, что не доехало.
--
-- ЖУРНАЛ ДЕЙСТВИЙ. По умолчанию не убирается никогда, и это не лень.
-- Журнал заводят ровно затем, чтобы ответить на вопрос через год;
-- срок хранения по умолчанию превратил бы его в журнал на месяц.
-- Но требование «хранить не дольше N» существует и приходит не от нас,
-- а снаружи — от закона или от политики заказчика. Поэтому срок
-- задаётся организацией и пустой по умолчанию.

alter table orgs
    add column audit_retention_days int
        constraint orgs_audit_retention_positive
        check (audit_retention_days is null or audit_retention_days >= 30);

comment on column orgs.audit_retention_days is
    'Через сколько дней убирать записи журнала действий. Пусто — хранить всегда. Меньше месяца не бывает: журнал, который не переживает квартальную проверку, бесполезен.';

-- Уборщик ходит без арендатора, а рестриктивная политика изоляции
-- у этих двух таблиц требует его выставленным — значит, до строк он
-- не доберётся вовсе. У доставок вебхуков эта же политика написана
-- иначе, и там уборка работает; здесь приводим к тому же виду.
--
-- Читать это никому не открывает: разрешающие политики остались прежними.
-- Ключи повтора требуют app_can_write(), журнал — app_view_all(), и обе
-- без личности ложны. Меняется ровно одно: уборщик перестаёт быть
-- невидим сам для себя.
alter policy tenant_isolation on api_idempotency
    using (org_id = coalesce((select app_current_org()), org_id))
    with check (org_id = coalesce((select app_current_org()), org_id));

alter policy tenant_isolation on audit_events
    using (org_id = coalesce((select app_current_org()), org_id))
    with check (org_id = coalesce((select app_current_org()), org_id));

-- Работник чистит без арендатора: обход по кругу всех организаций
-- значил бы, что он заранее знает, какие они есть. Политики ниже это
-- допускают ровно для него — при выставленном арендаторе удалять
-- по-прежнему нельзя никому.
create policy cleanup on api_idempotency for delete
    using ((select app_current_org()) is null);

-- Ключи повтора хранят тело ответа, то есть данные арендатора, и открывать
-- их уборщику целиком незачем. Он видит ровно просроченное — то, что и так
-- обязан стереть. Тот же срок стоит в internal/retention; разойтись им
-- нельзя, иначе уборка молча перестанет что-либо находить.
create policy cleanup_reads on api_idempotency for select
    using (
        (select app_current_org()) is null
        and created_at < now() - interval '24 hours'
    );

create policy cleanup on webhook_deliveries for delete
    using ((select app_current_org()) is null);

-- Журнал действий по-прежнему нельзя ни изменить, ни удалить изнутри
-- организации: политик update и delete у него нет. Уборщик — исключение,
-- и оно названо явно.
create policy cleanup on audit_events for delete
    using ((select app_current_org()) is null);

-- Одного разрешения на удаление мало. Чтобы понять, какие строки удалять,
-- база их читает, и к delete подмешивается политика чтения — а она без
-- личности ложна. Проверено планом: в фильтре удаления стоит app_view_all().
-- У доставок вебхуков такое разрешение для работника уже есть (worker_reads).
--
-- Здесь оно уже: уборщик видит не весь журнал, а ровно то, что и так
-- обязан стереть — записи организаций, назвавших срок, и только старше
-- этого срока. Организация без срока остаётся невидимой целиком, потому
-- что сравнение с пустым сроком даёт неизвестность, а не истину.
create policy cleanup_reads on audit_events for select
    using (
        (select app_current_org()) is null
        and at < now() - make_interval(
            days => (select o.audit_retention_days from orgs o where o.id = org_id))
    );
