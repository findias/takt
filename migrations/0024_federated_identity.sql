-- Вход через корпоративный провайдер: чем узнавать вернувшегося человека.
--
-- Почта для этого не годится. Она меняется — при замужестве, при переходе
-- в другое подразделение, при смене домена компании, — и человек,
-- вернувшийся с новой почтой, получил бы новую учётную запись, а вместе
-- с ней потерял бы свои доски. Провайдер же выдаёт неизменный
-- идентификатор (sub), который для того и существует.
--
-- Пара «издатель + идентификатор», а не один идентификатор: sub уникален
-- внутри провайдера, но не между провайдерами. Установка с двумя
-- провайдерами сегодня не поддерживается, однако закладывать в ключ
-- предположение «он у нас один» — верный способ переписывать схему потом,
-- под нагрузкой и в спешке.

alter table users
    add column oidc_issuer text,
    add column oidc_subject text;

-- Один человек — одна запись у провайдера. Частичный индекс, потому что
-- у заведённых паролем оба поля пусты, и таких большинство.
create unique index users_federated_identity
    on users (oidc_issuer, oidc_subject)
    where oidc_subject is not null;

-- Либо оба поля, либо ни одного: наполовину заполненная связь означала бы,
-- что мы не знаем, чьё это имя у провайдера.
alter table users
    add constraint users_federation_complete
    check ((oidc_issuer is null) = (oidc_subject is null));

comment on column users.oidc_subject is
    'Неизменный идентификатор человека у провайдера входа. Пусто у тех, кто заведён паролем.';
