-- Внешний ключ карточки (ROADMAP 23.1): откуда она переехала и как
-- называлась там.
--
-- Нужен, чтобы повторный импорт того же файла не плодил двойников:
-- второй прогон находит уже перенесённое по ключу и пропускает его.
-- Он же — отметка «перенесено, а не прожито здесь»: отчёт обязан уметь
-- отделить одно от другого. И он же потом свяжет карточку с задачей
-- Jira (этап 26).
--
-- Уникальность — в пределах организации и источника: номер PROJ-12
-- из таблицы и из Jira — разные ключи, а одинаковые номера в двух
-- организациях друг другу не мешают.
--
-- Старая версия приложения колонок не знает и не пишет: они
-- необязательные, а индекс частичный — её карточки в него не попадают.

alter table cards
    add column external_source text,
    add column external_id     text,
    add constraint cards_external_pair
        check ((external_source is null) = (external_id is null));

create unique index cards_external_key
    on cards (org_id, external_source, external_id)
    where external_id is not null;
