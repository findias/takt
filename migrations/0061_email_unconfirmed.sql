-- Почта, которую человек вписал себе сам (ROADMAP 23.6).
--
-- Писем takt не шлёт, поэтому подтвердить новый адрес нечем. Сама по себе
-- это не беда: входят паролем, и чужой адрес в профиле никого не пускает
-- в чужую учётную запись. Беда в корпоративном входе: он один раз
-- привязывает запись по подтверждённой провайдером почте, и адрес,
-- вписанный заранее, отдал бы вписавшему того, кто придёт с ним позже.
-- Поэтому такая почта помечается, и привязка по ней не идёт.
--
-- Умолчание false: всё заведённое до этой миграции и всё, что заводит
-- старая версия, ведёт себя как прежде.
alter table users add column email_unconfirmed boolean not null default false;

comment on column users.email_unconfirmed is
    'Почту вписал сам человек, и никто её не подтверждал: корпоративный вход по ней запись не привязывает.';
