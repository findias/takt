-- Отказы дерева говорят «подразделение», как и весь экран.
--
-- Тексты этих отказов написаны в 0009 и с тех пор попадают человеку
-- на экран «Структура» слово в слово. На экране всё зовётся
-- подразделением — заголовок раздела, кнопки, пустое состояние,
-- сообщения самого приложения («у подразделения должно быть
-- название»), — а из базы приходило «глубина вложенности команд»
-- и «команда не может быть вложена в собственного потомка». «Команда»
-- в интерфейсе называет соседний экран, где люди и роли; человек,
-- прочитавший отказ, ищет его там.
--
-- Меняются только слова: условия, коды ошибок и поведение те же.
-- Функция переписывается целиком, потому что иначе её не переписать —
-- в этом и разница между сменой текста и сменой правила.

create or replace function teams_path_before() returns trigger
language plpgsql as $$
declare
    parent_path uuid[];
begin
    if new.parent_id is null then
        new.ancestor_ids := array[new.id];
        return new;
    end if;

    select ancestor_ids into parent_path from teams where id = new.parent_id;
    if parent_path is null then
        raise exception 'старшее подразделение не найдено'
            using errcode = 'foreign_key_violation';
    end if;

    -- Цикл: узел не может оказаться среди собственных предков. База сама
    -- от этого не защищает — рекурсивный обход просто зациклился бы.
    if new.id = any (parent_path) then
        raise exception 'подразделение не может быть вложено в собственный отдел'
            using errcode = 'check_violation';
    end if;

    new.ancestor_ids := parent_path || new.id;

    -- Ограничение таблицы поймало бы это и само, но сообщением про
    -- нарушение check-констрейнта. Гарантия остаётся за ограничением,
    -- объяснение — здесь: до пользователя дойдёт именно оно.
    if cardinality(new.ancestor_ids) > 5 then
        raise exception 'глубина вложенности подразделений ограничена пятью уровнями'
            using errcode = 'check_violation';
    end if;
    return new;
end $$;
