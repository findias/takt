import { expect, test } from '@playwright/test'

for (const lang of ['ru', 'en'] as const) for (const width of [1440, 360]) for (const theme of ['light', 'dark'] as const) {
  test(`Гант: ${lang}, ${width}, ${theme}`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 900 })
    await page.emulateMedia({ colorScheme: theme })
    await page.addInitScript(({ lang, theme }) => { localStorage.setItem('lang', lang); localStorage.setItem('theme', theme) }, { lang, theme })
    const id = crypto.randomUUID()
    const registered = await page.request.post('/api/auth/register', { data: { org: `План ${id}`, name: 'Планировщик', email: `gantt-${id}@example.test`, password: 'parol12345' } })
    expect(registered.ok()).toBeTruthy()
    const board = await (await page.request.post('/api/boards', { data: { name: lang === 'ru' ? 'План поставки' : 'Delivery plan' } })).json()
    const snapshot = await (await page.request.get(`/api/boards/${board.id}`)).json()
    const columnId = snapshot.columns[0].id
    const op = async (type: string, payload: unknown) => {
      const res = await page.request.post(`/api/boards/${board.id}/operations`, { data: { operationId: crypto.randomUUID(), type, payload } })
      expect(res.ok(), await res.text()).toBeTruthy()
      return res.json()
    }
    const title = lang === 'ru' ? 'Подготовить поставку и согласовать порядок приёмки оборудования с подрядчиком и командой эксплуатации' : 'Prepare the delivery and agree equipment acceptance with the contractor and the operations team'
    const parent = (await op('CREATE_CARD', { columnId, title, place: 'end' })).patch.cards[0].id
    await op('SET_CARD_PLAN', { cardId: parent, plannedStartOn: '2026-11-05', plannedEndOn: '2026-11-12', expected: { plannedStartOn: null, plannedEndOn: null } })
    await op('SET_CARD_PERCENT', { cardId: parent, percent: 42 })
    await op('UPDATE_CARD', { cardId: parent, dueOn: '2026-11-14' })
    await op('UPDATE_CARD', { cardId: parent, priority: 'highest' })
    const child = (await op('CREATE_SUBTASK', { parentCardId: parent, title: lang === 'ru' ? 'Согласовать окно поставки' : 'Agree the delivery window' })).patch.cards.find((c: { id: string }) => c.id !== parent).id
    await op('UPDATE_CARD', { cardId: child, priority: 'high' })
    await op('SET_CARD_PLAN', { cardId: child, plannedStartOn: '2026-11-06', plannedEndOn: '2026-11-06', expected: { plannedStartOn: null, plannedEndOn: null } })
    await op('CREATE_CARD', { columnId, title: lang === 'ru' ? 'Задача без дат' : 'Task without dates', place: 'end' })
    await page.goto(`/board/${board.id}?view=gantt&ganttFrom=2026-11-01`)
    const chart = page.getByRole('region', { name: lang === 'ru' ? 'Гант' : 'Gantt', exact: true })
    await expect(chart).toBeVisible()
    const bar = page.locator('.gantt-handle--move').first()
    await expect(bar).toBeVisible()
    await expect(chart.getByTitle(lang === 'ru' ? 'Наивысший' : 'Highest', { exact: true })).toBeVisible()
    await expect(chart.getByTitle(lang === 'ru' ? 'Высокий' : 'High', { exact: true })).toBeVisible()
    await expect(page.locator('.gantt-row')).toHaveCount(4)
    // Общая строка удерживает длинное название и полосу на одной высоте.
    const row = page.locator(`.gantt-row[data-card-id="${parent}"]`)
    const nameBox = await row.locator('.gantt-name').boundingBox(), trackBox = await row.locator('.gantt-track').boundingBox()
    expect(nameBox && trackBox).toBeTruthy()
    expect(Math.abs(nameBox!.y - trackBox!.y)).toBeLessThan(1)
    expect(Math.abs(nameBox!.height - trackBox!.height)).toBeLessThan(1)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
    const childRow = page.locator(`.gantt-row[data-card-id="${child}"]`)
    await expect(childRow.locator('.gantt-child-label')).toContainText(lang === 'ru' ? 'Подзадача' : 'Subtask')
    await expect(childRow).toHaveAttribute('data-parent-id', parent)
    const parentTitleBox = await row.locator('.gantt-title').boundingBox()
    const childTitleBox = await childRow.locator('.gantt-title').boundingBox()
    expect(childTitleBox!.x).toBeGreaterThan(parentTitleBox!.x + 12)
    const toggle = row.locator('.gantt-branch-toggle')
    await expect(toggle).toHaveAttribute('aria-expanded', 'true')
    await toggle.click()
    await expect(childRow).toHaveCount(0)
    await expect(page.locator('.gantt-row')).toHaveCount(3)
    await toggle.press('Space')
    await expect(childRow).toBeVisible()
    const childTrackBox = await childRow.locator('.gantt-track').boundingBox()
    const childNameBox = await childRow.locator('.gantt-name').boundingBox()
    expect(Math.abs(childTrackBox!.height - childNameBox!.height)).toBeLessThan(1)
    expect(Math.abs(childTrackBox!.y - childNameBox!.y)).toBeLessThan(1)
    // Снимок обеих тем и языков, включая узкую раскладку.
    await page.screenshot({ path: info.outputPath('gantt.png'), fullPage: true })
    const view = page.getByRole('combobox', { name: lang === 'ru' ? 'Вид доски' : 'Board view', exact: true })
    await view.selectOption('board')
    const parentCard = page.locator('.card').filter({ hasText: title })
    await parentCard.locator('button[aria-controls^="subtasks-"]').click()
    const subtaskPriority = parentCard.locator('.subtasks').getByTitle(lang === 'ru' ? 'Высокий' : 'High', { exact: true })
    await expect(subtaskPriority).toBeVisible()
    const priorityBox = await subtaskPriority.boundingBox(), cardBox = await parentCard.boundingBox()
    expect(priorityBox!.x + priorityBox!.width).toBeLessThanOrEqual(cardBox!.x + cardBox!.width)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
    await page.screenshot({ path: info.outputPath('priority-board.png'), fullPage: true })
    await view.selectOption('tree')
    await expect(page.locator('.tree-view').getByTitle(lang === 'ru' ? 'Высокий' : 'High', { exact: true })).toBeVisible()
    await page.screenshot({ path: info.outputPath('priority-tree.png'), fullPage: true })
    await view.selectOption('gantt')
    await expect(chart).toBeVisible()
    if (lang === 'ru' && width === 1440 && theme === 'light') {
      await bar.click({ trial: true })
      const before = await bar.boundingBox()
      await page.mouse.move(before!.x + before!.width / 2, before!.y + before!.height / 2)
      await page.mouse.down(); await page.mouse.move(before!.x + before!.width / 2 + 64, before!.y + before!.height / 2, { steps: 8 }); await page.mouse.up()
      const readPlan = async () => (await (await page.request.get(`/api/boards/${board.id}`)).json()).cards.find((c: { id: string }) => c.id === parent)
      await expect.poll(async () => (await readPlan()).plannedStartOn).toBe('2026-11-07')
      expect((await readPlan()).plannedEndOn).toBe('2026-11-14')
      expect((await readPlan()).dueOn).toBe('2026-11-14')
      expect((await readPlan()).percent).toBe(42)
      // У однодневной полосы в масштабе месяца остаётся место для переноса:
      // ручки краёв не перекрывают её середину.
      await page.getByRole('combobox', { name: 'Масштаб' }).selectOption('month')
      const short = await page.locator('.gantt-handle--move').nth(1).boundingBox()
      await page.mouse.move(short!.x + short!.width / 2, short!.y + short!.height / 2)
      await page.mouse.down(); await page.mouse.move(short!.x + short!.width / 2 + 12, short!.y + short!.height / 2, { steps: 4 }); await page.mouse.up()
      await expect.poll(async () => (await (await page.request.get(`/api/boards/${board.id}`)).json()).cards.find((c: { id: string }) => c.id === child).plannedStartOn).toBe('2026-11-07')
      await page.screenshot({ path: info.outputPath('gantt-month.png'), fullPage: true })
      await row.locator('.gantt-title').click()
      await page.locator('.panel-card').getByRole('tab', { name: 'Работа', exact: true }).click()
      await page.getByLabel('Плановое начало', { exact: true }).fill('2026-11-08')
      await page.getByLabel('Плановое окончание', { exact: true }).fill('2026-11-15')
      await page.getByRole('heading', { name: 'План', exact: true }).click()
      await expect.poll(async () => (await readPlan()).plannedEndOn).toBe('2026-11-15')
      await page.reload()
      await page.locator('.panel-card').getByRole('tab', { name: 'Работа', exact: true }).click()
      await expect(page.getByLabel('Плановое начало', { exact: true })).toHaveValue('2026-11-08')
      await expect(page.getByLabel('Плановое окончание', { exact: true })).toHaveValue('2026-11-15')
    }
    if (lang === 'ru' && width === 1440 && theme === 'dark') {
      // Отрисовка тысячи задач без тысячи операций подготовки:
      // это замер клиента на настоящей сборке, сервер проверен выше.
      const large = await (await page.request.get(`/api/boards/${board.id}`)).json()
      const source = large.cards.find((c: { id: string }) => c.id === parent)
      large.cards = Array.from({ length: 1000 }, (_, i) => ({ ...source, id: crypto.randomUUID(), number: `ПЛАН-${i + 1}`, title: `Задача ${i + 1}`, position: String(i).padStart(6, '0') }))
      large.links = []
      await page.route(`**/api/boards/${board.id}`, (route) => route.fulfill({ json: large }))
      await page.addInitScript(() => {
        const observer = new MutationObserver(() => {
          if (document.querySelector('.gantt-track')) {
            (window as unknown as { ganttAt: number }).ganttAt = performance.now()
            observer.disconnect()
          }
        })
        observer.observe(document, { childList: true, subtree: true })
      })
      await page.reload()
      await expect(page.locator('.gantt-track')).toHaveCount(100)
      const firstPaint = await page.evaluate(() => (window as unknown as { ganttAt: number }).ganttAt)
      expect(firstPaint).toBeLessThan(1000)
      console.log(`Гант, 1000 задач: ${Math.round(firstPaint)} мс, 100 строк в DOM`)
    }
    await page.unroute(`**/api/boards/${board.id}`)
    await page.goto(`/board/${board.id}/card/${parent}?view=gantt&ganttFrom=2026-11-01`)
    await page.locator('.panel-card').getByRole('tab', { name: lang === 'ru' ? 'Работа' : 'Work', exact: true }).click()
    await page.getByLabel(lang === 'ru' ? 'Плановое начало' : 'Planned start', { exact: true }).fill('2026-11-30')
    await page.getByRole('heading', { name: lang === 'ru' ? 'План' : 'Plan', exact: true }).click()
    const end = page.getByLabel(lang === 'ru' ? 'Плановое окончание' : 'Planned end', { exact: true })
    await expect(end).toHaveAttribute('aria-invalid', 'true')
    await end.scrollIntoViewIfNeeded()
    await page.screenshot({ path: info.outputPath('plan-error.png'), fullPage: true })
    const panel = page.locator('.panel-card')
    await panel.getByRole('tab', { name: lang === 'ru' ? 'Задачи' : 'Tasks', exact: true }).click()
    await expect(panel.getByTitle(lang === 'ru' ? 'Наивысший' : 'Highest', { exact: true })).toBeVisible()
    await expect(panel.getByTitle(lang === 'ru' ? 'Высокий' : 'High', { exact: true })).toBeVisible()
    await page.screenshot({ path: info.outputPath('priority-parts.png'), fullPage: true })
  })
}
