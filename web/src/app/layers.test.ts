// Слои: числа живут в одном месте, и верхний слой — не из этого набора.
//
// Порядок наложения — та же измеримая величина, что отступ, и правило
// у неё то же: набранное в правиле число означает, что кто-то подбирал
// на глаз. Только расхождение здесь выглядит не как кривой отступ,
// а как «почему меню оказалось под панелью», и находится оно глазами,
// потому что в разметке всё правильно.
//
// Вторая половина проверки — про то, чего никаким z-index не выразить.
// Верхний слой браузера (`<dialog>` с showModal, `popover`) стоит над
// любым z-index. Прогон 23.08.2026: при открытом диалоге
// document.elementFromPoint над тостом с z-index 40 возвращает диалог,
// а не тост. Значит, диалог обязан закрыться ДО действия, о котором
// доложит тост. Сегодня так и сделано везде, и проверка следит, чтобы
// осталось: закрытие стоит раньше вызова, а не после.

import assert from 'node:assert/strict'
import { readFileSync, readdirSync } from 'node:fs'
import { test } from 'node:test'

const стили = readFileSync(new URL('./styles.css', import.meta.url), 'utf8')

test('порядок наложения задан токенами, а не числами в правилах', () => {
  const сырые = [...стили.matchAll(/z-index:\s*([^;]+);/g)]
    .map((m) => m[1].trim())
    .filter((v) => !v.startsWith('var(--layer-') && !v.startsWith('calc(var(--layer-'))
  assert.deepEqual(сырые, [], `сырой z-index: ${сырые.join(', ')}`)
})

test('у каждого слоя своё число: делить один — значит зависеть от порядка в разметке', () => {
  const объявленные = [...стили.matchAll(/--layer-([\w-]+):\s*(\d+);/g)].map((m) => [m[1], Number(m[2])])
  assert.ok(объявленные.length >= 4, 'слоёв объявлено меньше, чем есть на экране')
  const числа = объявленные.map(([, n]) => n)
  assert.equal(new Set(числа).size, числа.length, `у слоёв совпали номера: ${JSON.stringify(объявленные)}`)
})

test('диалог закрывается до действия, а не после: иначе доклад о нём спрячется', () => {
  // Верхний слой перекрывает тосты, поэтому порядок «сначала закрыть,
  // потом делать» — не стиль, а условие того, чтобы результат был виден.
  const виджеты = readdirSync(new URL('../widgets/', import.meta.url))
    .filter((f) => f.endsWith('.tsx') && !f.includes('.test.'))
    .map((f) => readFileSync(new URL(`../widgets/${f}`, import.meta.url), 'utf8'))
  const палитра = readFileSync(new URL('../features/board/Palette.tsx', import.meta.url), 'utf8')

  const плохие: string[] = []
  for (const исходник of [...виджеты, палитра]) {
    for (const m of исходник.matchAll(/onConfirm=\{\(\) => \{([\s\S]*?)\n\s{8}\}\}/g)) {
      const тело = m[1]
      const закрытие = тело.search(/set\w+\(null\)|onClose\(\)/)
      const вызов = тело.search(/\bapi\./)
      if (вызов < 0) continue
      // Два случая, а не один: закрытие после вызова — и закрытия нет
      // вовсе. Второй хуже, и первая редакция этой проверки его
      // не видела: у неё «закрытия нет» и «закрытие вовремя» давали
      // одинаковый зелёный.
      if (закрытие < 0) плохие.push(`без закрытия: ${тело.slice(0, 50).trim()}`)
      else if (закрытие > вызов) плохие.push(`закрытие после вызова: ${тело.slice(0, 50).trim()}`)
    }
  }
  assert.deepEqual(плохие, [], `подтверждение действует раньше, чем закрывается: ${плохие.join(' | ')}`)
})
