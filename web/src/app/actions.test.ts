// Убирающее действие не выглядит как созидающее (разбор интерфейса
// 21.09.2026).
//
// «Убрать подразделение» стояло той же зелёной ссылкой, что
// «Переименовать» и «+ отдел», «В архив» — той же, что «Доступ».
// Глазу нечем было отличить действие, после которого что-то пропадёт,
// от действия, после которого что-то появится. Ступеней три:
// созидательное — обычная ссылка; убирающее, но обратимое —
// `link--remove`, тихо и серо; необратимое — `link--danger`, цветом
// тревоги. Красного при этом остаётся мало: «Удалить данные», «удалить
// насовсем», «Отозвать ключ».
//
// Проверяется по исходникам: кнопка-ссылка, чья подпись начинается
// с глагола убирания, обязана нести одну из двух ступеней.

import assert from 'node:assert/strict'
import { readFileSync, readdirSync } from 'node:fs'
import { test } from 'node:test'
// Каталог целиком, с разделами экранов: его загружает подготовка
// проверок (node-setup.ts).
import { t as ru } from '../shared/i18n/index.ts'

/** Подпись из каталога: с выбором языка (ROADMAP 30.2) кнопки пишут
 *  `{t.boards.archive}`, а не слово, — и разбор, не развернувший
 *  ссылку, перестал бы видеть глагол. Развернуть можно только строку;
 *  функцию с аргументами — нет, и такая подпись остаётся ссылкой. */
function развернуть(подпись: string): string {
  return подпись.replace(/\{t\.([\w.]+)\}/g, (всё, путь: string) => {
    let узел: unknown = ru
    for (const шаг of путь.split('.')) {
      узел = узел && typeof узел === 'object' ? (узел as Record<string, unknown>)[шаг] : undefined
    }
    return typeof узел === 'string' ? узел : всё
  })
}

function исходники(): { путь: string; текст: string }[] {
  const корень = new URL('../', import.meta.url)
  const out: { путь: string; текст: string }[] = []
  const обойти = (каталог: URL, префикс: string) => {
    for (const запись of readdirSync(каталог, { withFileTypes: true })) {
      if (запись.isDirectory()) {
        обойти(new URL(`${запись.name}/`, каталог), `${префикс}${запись.name}/`)
        continue
      }
      if (!запись.name.endsWith('.tsx') || запись.name.includes('.test.')) continue
      out.push({
        путь: `${префикс}${запись.name}`,
        текст: readFileSync(new URL(запись.name, каталог), 'utf8'),
      })
    }
  }
  обойти(корень, '')
  return out
}

const УБИРАЮЩИЕ = /^(Убрать|В архив|Отозвать|Исключить|Удалить|Снять полномочия)/

/** Кнопки файла: атрибуты открывающего тега и видимая подпись. Тег
 *  разбирается со счётом фигурных скобок: в `onClick={() => …}` стоит
 *  «>», и наивное «до первой >» теряло почти все кнопки — первая версия
 *  этой проверки находила две из тринадцати. */
function кнопки(текст: string): { атрибуты: string; подпись: string; где: number }[] {
  const out: { атрибуты: string; подпись: string; где: number }[] = []
  let от = 0
  for (;;) {
    const начало = текст.indexOf('<button', от)
    if (начало < 0) return out
    let i = начало + 7
    let глубина = 0
    for (; i < текст.length; i++) {
      const c = текст[i]
      if (c === '{') глубина++
      else if (c === '}') глубина--
      else if (c === '>' && глубина === 0) break
    }
    const конец = текст.indexOf('</button>', i)
    if (конец < 0) return out
    const тело = текст
      .slice(i + 1, конец)
      .replace(/\{\/\*[\s\S]*?\*\/\}/g, '')
      .replace(/<[^>]+>/g, '')
      .trim()
    out.push({ атрибуты: текст.slice(начало, i), подпись: развернуть(тело), где: начало })
    от = конец
  }
}

test('убирающие действия отличимы от созидающих', () => {
  const найдено: string[] = []
  let проверено = 0
  for (const { путь, текст } of исходники()) {
    for (const { атрибуты, подпись, где } of кнопки(текст)) {
      if (!/className="link\b/.test(атрибуты)) continue
      if (!УБИРАЮЩИЕ.test(подпись)) continue
      проверено++
      if (/link--(remove|danger)/.test(атрибуты)) continue
      const строка = текст.slice(0, где).split('\n').length
      найдено.push(`${путь}:${строка} «${подпись}»`)
    }
  }
  // Сторож самой проверки: если разбор снова разучится находить кнопки,
  // пустой список найденного будет не успехом, а слепотой.
  assert.ok(проверено >= 10, `убирающих кнопок найдено ${проверено} — разбор потерял кнопки`)
  assert.deepEqual(найдено, [], `убирающее набрано как созидающее:\n${найдено.join('\n')}`)
})
