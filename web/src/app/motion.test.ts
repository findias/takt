// Движение: у каждого назван переход, который оно объясняет.
//
// Правило записано в дизайн-языке давно — «движение объясняет
// перемещение объекта, и только», — но проверять его было нечем,
// и оно держалось на честном слове. Держалось, кстати, неплохо:
// перепись 23.08.2026 нашла в продукте четыре движения, и три из них
// действительно объясняли переход. Зато нашла и другое: длительности
// назывались по величине (`--fast`, `--slow`), то есть имя отвечало
// на вопрос «сколько», а не «зачем», и одно число (0.2s у полосы
// подзадач) было набрано мимо обеих.
//
// Это та же болезнь, что у слоёв, названных числами, и у цветов,
// набранных hex'ом: пока у роли нет имени, каждый новый случай
// набирается на глаз. Поэтому роли названы отдельно — `--motion-moved`,
// `--motion-arrived`, `--motion-grew`, `--motion-pending`, — а проверка
// следит, чтобы новое движение не завелось безымянным.

import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { test } from 'node:test'

const стили = readFileSync(new URL('./styles.css', import.meta.url), 'utf8')

/** Объявления токенов ролей: имя → значение. */
function роли(): Record<string, string> {
  return Object.fromEntries(
    [...стили.matchAll(/--(motion-[\w-]+):\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]),
  )
}

test('длительность берётся у роли, а не набирается числом', () => {
  // Ищем времена в объявлениях `transition` и `animation`: секунды
  // и миллисекунды, написанные прямо в правиле.
  const сырые: string[] = []
  for (const m of стили.matchAll(/\n\s*(transition|animation)(-duration)?:\s*([^;]+);/g)) {
    const значение = m[3]
    // Исключение одно и оно названо: глобальный сброс для тех, кто
    // просил меньше движения, гасит анимации в один приём, и число
    // 0.01ms там значит «не показывать», а не длительность.
    if (значение.includes('0.01ms')) continue
    for (const время of значение.matchAll(/(?<![\w-])(\d*\.?\d+)(s|ms)\b/g)) {
      сырые.push(`${m[1]}: ${время[0]} в «${значение.trim().slice(0, 40)}»`)
    }
  }
  assert.deepEqual(сырые, [], `длительность набрана числом: ${сырые.join(' | ')}`)
})

test('движение ссылается на объявленную роль, а не на выдуманную', () => {
  const объявлены = роли()
  const неизвестные = [...стили.matchAll(/var\(--(motion-[\w-]+)\)/g)]
    .map((m) => m[1])
    .filter((имя) => !(имя in объявлены))
  assert.deepEqual(неизвестные, [], `роль не объявлена: ${неизвестные.join(', ')}`)
  assert.ok(Object.keys(объявлены).length >= 3, 'ролей меньше, чем движений в продукте')
})

test('у каждой роли сказано, что она объясняет', () => {
  // Имя роли — половина ответа; вторая половина в комментарии над ней,
  // и без неё роль через полгода будет означать «столько же, сколько
  // у соседа». Проверяется наличие комментария вплотную к объявлению.
  const безОбъяснения: string[] = []
  for (const m of стили.matchAll(/--(motion-[\w-]+):/g)) {
    const до = стили.slice(Math.max(0, m.index - 400), m.index)
    const конец = до.lastIndexOf('*/')
    // Между комментарием и объявлением не должно стоять другое
    // объявление: иначе засчитается чужое объяснение.
    if (конец === -1 || до.slice(конец).includes(';')) безОбъяснения.push(m[1])
  }
  assert.deepEqual(безОбъяснения, [], `роль без объяснения: ${безОбъяснения.join(', ')}`)
})

test('просьба меньше движения заменяет его, а не выключает', () => {
  // Правило записано в самом файле: «заменяем сдвиг на проявление,
  // а не выключаем всё — иначе объяснение перемещения теряется вовсе».
  // И оно же нарушалось собственным глобальным сбросом: замер 23.08.2026
  // показал у вспышки после переноса длительность 1e-05 с, то есть
  // не «короче», а «нет».
  //
  // Проверяется здесь только то, что видно в тексте стилей: движение,
  // объясняющее перенос, переживает сброс. Что оно действительно живёт
  // в браузере — меряет `e2e/a11y.spec.ts`.
  const блок = стили.match(
    /@media \(prefers-reduced-motion: reduce\) \{\s*\.card--flash \{([\s\S]*?)\}/,
  )
  assert.ok(блок, 'вспышка после переноса не пережила сброс: правила для неё нет вовсе')
  assert.match(
    блок[1],
    /animation-duration:\s*var\(--motion-moved\)\s*!important/,
    'без !important глобальный сброс гасит вспышку своим !important',
  )
})
