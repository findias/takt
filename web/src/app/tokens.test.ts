// Токены: значения живут в объявлении, правила — только ссылаются.
//
// Правило это записано в дизайн-языке с самого начала и до сих пор
// держалось только чтением. Перепись 23.08.2026 показала, чего оно
// стоило: при 471 правиле в стилях восемьдесят с лишним сырых цветов
// сидели вне объявления тем.
//
// Важно, что это была не расхлябанность. Почти всё сырое сидело
// в двух местах, о которых набор токенов не говорил ничего: палитра
// меток (категориальный цвет — не роль, а множество, и в наборе ролей
// ему нет места) и затемнение под панелью. Отраслевой разбор называет
// это главной причиной, по которой дизайн-системы обходят: система
// молчит о вопросе, который у людей есть. Значит, всякое сырое
// значение здесь — указатель на непредусмотренный вопрос, и проверка
// нужна не как надзиратель, а как счётчик таких указателей.

import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { test } from 'node:test'

const стили = readFileSync(new URL('./styles.css', import.meta.url), 'utf8')

/** Строки объявлений: `--что-то: значение` — единственное место для сырых значений. */
const объявление = (строка: string) => /^\s*--[\w-]+\s*:/.test(строка)

test('сырых цветов вне объявления токенов нет', () => {
  const исключения = [
    // Заливка кружка от темы не зависит, и `var(--surface)` в тёмной
    // делал буквы почти чёрными — 3.15 вместо 4.5 (замерено).
    'color: #fff;',
  ]
  const найдено = стили
    .split('\n')
    .map((строка, i) => [i + 1, строка.trim()] as const)
    .filter(([, строка]) => !строка.startsWith('/*') && !строка.startsWith('*'))
    .filter(([, строка]) => !объявление(строка))
    .filter(([, строка]) => /#[0-9a-fA-F]{3,8}\b|rgba?\(|hsla?\(/.test(строка))
    .filter(([, строка]) => !исключения.includes(строка))
    .map(([n, строка]) => `${n}: ${строка}`)
  assert.deepEqual(найдено, [], `сырой цвет в правиле:\n${найдено.join('\n')}`)
})

test('тона аватаров разведены шагом, а не подобраны', () => {
  // Аватары различают людей, и различает их только тон: светлота
  // и насыщенность у всех общие. Значит соседние тона обязаны стоять
  // далеко, и «далеко» здесь — величина, а не впечатление.
  //
  // Проверка заведена после собственной ошибки: аватары сперва посадили
  // на набор тонов меток, где `slate` (172°) отличается от `green`
  // (170°) насыщенностью, а не тоном. У меток это работает, у аватаров
  // при общей насыщенности два цвета слились бы в один.
  const тона = [...стили.matchAll(/--avatar-hue-\d+:\s*(\d+);/g)].map((m) => Number(m[1]))
  assert.equal(тона.length, 8, `тонов аватара ${тона.length}, ожидалось восемь`)
  const по_кругу = [...тона].sort((a, b) => a - b)
  const зазоры = по_кругу.map((h, i) => (i === 0 ? h + 360 - по_кругу.at(-1)! : h - по_кругу[i - 1]))
  const тесно = зазоры.filter((з) => з < 30)
  assert.deepEqual(тесно, [], `тона аватаров сходятся ближе тридцати градусов: ${зазоры.join(', ')}`)
})

test('оттенки различаются тоном, а рецепт у них общий', () => {
  const тона = [...стили.matchAll(/--hue-([\w-]+):\s*([\d.]+);/g)].map((m) => [m[1], Number(m[2])])
  assert.ok(тона.length >= 8, `тонов объявлено ${тона.length}, ожидалось не меньше восьми`)

  // Тон — единственное, чем оттенки отличаются, поэтому совпавшие тона
  // означают два имени для одного цвета.
  const числа = тона.map(([, n]) => n)
  assert.equal(new Set(числа).size, числа.length, `совпали тона: ${JSON.stringify(тона)}`)

  // Рецепт объявлен целиком: половина рецепта — это половина оттенков,
  // собранных из чего попало.
  for (const имя of ['chip-bg-l', 'chip-bg-c', 'chip-fg-l', 'chip-fg-c', 'avatar-l', 'avatar-c']) {
    assert.match(стили, new RegExp(`--${имя}:`), `в рецепте нет --${имя}`)
  }
})

test('цвет объявляется один раз на обе темы, а не трижды', () => {
  // `light-dark()` выбирает значение по `color-scheme`, и потому цветной
  // токен стоит в одном месте. Пока их было три — светлая, системная
  // тёмная и явная тёмная, — правка одного из трёх проходила молча:
  // так `--warn` полгода простоял на Lc 47 при пороге 60, потому что
  // тёмную шкалу расставили по APCA, а его забыли.
  //
  // Не цвет объявляется по темам законно: тень — не цвет, галочка
  // флажка — картинка, рецепт меток — числа. Их `light-dark()`
  // не берёт, и требовать этого от них незачем.
  const объявления = [...стили.matchAll(/^\s*(--[a-z0-9-]+):\s*([^;]+);/gm)]
  const счёт = new Map<string, string[]>()
  for (const [, имя, значение] of объявления) {
    счёт.set(имя, [...(счёт.get(имя) ?? []), значение.trim()])
  }
  const цветом = (значение: string) => /^(#|rgb|oklch|hsl)/.test(значение)
  const дважды: string[] = []
  for (const [имя, значения] of счёт) {
    if (значения.length > 1 && значения.every(цветом)) дважды.push(имя)
  }
  assert.deepEqual(
    дважды,
    [],
    `цвет объявлен в нескольких темах: ${дважды.join(', ')} — ` +
      `используйте light-dark(светлый, тёмный), иначе правку одной темы забудут`,
  )
})

test('ступень шкалы кегля различима глазом', () => {
  // До 23.08.2026 ступеней было пять, и первая — 12 против 13 —
  // не была ступенью: разница в пиксель не читается ни при тройном
  // увеличении снимка, ни на экране. Стояли они при этом вплотную
  // («ПОСТ» тринадцатью, «v65» двенадцатью в шапке доски), а один
  // и тот же класс `.link` получал то одно, то другое — от того,
  // внутри чего оказался.
  //
  // Порог — 10%: на мелких кеглях это ровно тот минимум, на котором
  // два размера в одном ряду ещё различаются. Не «пиксель»: шкала
  // задана в `rem`, и пиксель на 22 и на 13 — разные вещи.
  const кегли = [...стили.matchAll(/^\s*(--text[\w-]*):\s*([\d.]+)rem/gm)].map(([, имя, знач]) => ({
    имя,
    px: parseFloat(знач) * 16,
  }))
  assert.ok(кегли.length >= 3, `шкала не найдена: ${кегли.length}`)
  кегли.sort((a, b) => a.px - b.px)

  const тесные: string[] = []
  for (let i = 1; i < кегли.length; i++) {
    const шаг = кегли[i].px / кегли[i - 1].px
    if (шаг < 1.1) {
      тесные.push(
        `${кегли[i - 1].имя} (${кегли[i - 1].px}px) и ${кегли[i].имя} (${кегли[i].px}px) — ` +
          `шаг ${Math.round((шаг - 1) * 100)}%`,
      )
    }
  }
  assert.deepEqual(
    тесные,
    [],
    `ступени неразличимы: ${тесные.join(' | ')} — уровни различают цветом, ` +
      `насыщенностью и капителью, а не пикселем кегля`,
  )
})
