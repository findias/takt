// Токены: значения живут в объявлении, правила — только ссылаются.
//
// Правило это записано в дизайн-языке с самого начала и до сих пор
// держалось только чтением. Перепись 23.08.2026 показала, чего оно
// стоило: при 471 правиле в стилях восемьдесят с лишним сырых цветов
// сидели вне объявления тем.
//
// Важно, что это была не расхлябанность. Почти всё сырое сидело
// в двух местах, о которых набор токенов не говорил ничего: палитра
// меток (категориальный цвет — не роль, а множество, и в наборе ролей
// ему нет места) и затемнение под панелью. Отраслевой разбор называет
// это главной причиной, по которой дизайн-системы обходят: система
// молчит о вопросе, который у людей есть. Значит, всякое сырое
// значение здесь — указатель на непредусмотренный вопрос, и проверка
// нужна не как надзиратель, а как счётчик таких указателей.

import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { test } from 'node:test'

const стили = readFileSync(new URL('./styles.css', import.meta.url), 'utf8')

/** Строки объявлений: `--что-то: значение` — единственное место для сырых значений. */
const объявление = (строка: string) => /^\s*--[\w-]+\s*:/.test(строка)

test('сырых цветов вне объявления токенов нет', () => {
  const исключения = [
    // Заливка кружка от темы не зависит, и `var(--surface)` в тёмной
    // делал буквы почти чёрными — 3.15 вместо 4.5 (замерено).
    'color: #fff;',
  ]
  const найдено = стили
    .split('\n')
    .map((строка, i) => [i + 1, строка.trim()] as const)
    .filter(([, строка]) => !строка.startsWith('/*') && !строка.startsWith('*'))
    .filter(([, строка]) => !объявление(строка))
    .filter(([, строка]) => /#[0-9a-fA-F]{3,8}\b|rgba?\(|hsla?\(/.test(строка))
    .filter(([, строка]) => !исключения.includes(строка))
    .map(([n, строка]) => `${n}: ${строка}`)
  assert.deepEqual(найдено, [], `сырой цвет в правиле:\n${найдено.join('\n')}`)
})

test('тона аватаров разведены шагом, а не подобраны', () => {
  // Аватары различают людей, и различает их только тон: светлота
  // и насыщенность у всех общие. Значит соседние тона обязаны стоять
  // далеко, и «далеко» здесь — величина, а не впечатление.
  //
  // Проверка заведена после собственной ошибки: аватары сперва посадили
  // на набор тонов меток, где `slate` (172°) отличается от `green`
  // (170°) насыщенностью, а не тоном. У меток это работает, у аватаров
  // при общей насыщенности два цвета слились бы в один.
  const тона = [...стили.matchAll(/--avatar-hue-\d+:\s*(\d+);/g)].map((m) => Number(m[1]))
  assert.equal(тона.length, 8, `тонов аватара ${тона.length}, ожидалось восемь`)
  const по_кругу = [...тона].sort((a, b) => a - b)
  const зазоры = по_кругу.map((h, i) => (i === 0 ? h + 360 - по_кругу.at(-1)! : h - по_кругу[i - 1]))
  const тесно = зазоры.filter((з) => з < 30)
  assert.deepEqual(тесно, [], `тона аватаров сходятся ближе тридцати градусов: ${зазоры.join(', ')}`)
})

test('оттенки различаются тоном, а рецепт у них общий', () => {
  const тона = [...стили.matchAll(/--hue-([\w-]+):\s*([\d.]+);/g)].map((m) => [m[1], Number(m[2])])
  assert.ok(тона.length >= 8, `тонов объявлено ${тона.length}, ожидалось не меньше восьми`)

  // Тон — единственное, чем оттенки отличаются, поэтому совпавшие тона
  // означают два имени для одного цвета.
  const числа = тона.map(([, n]) => n)
  assert.equal(new Set(числа).size, числа.length, `совпали тона: ${JSON.stringify(тона)}`)

  // Рецепт объявлен целиком: половина рецепта — это половина оттенков,
  // собранных из чего попало.
  for (const имя of ['chip-bg-l', 'chip-bg-c', 'chip-fg-l', 'chip-fg-c', 'avatar-l', 'avatar-c']) {
    assert.match(стили, new RegExp(`--${имя}:`), `в рецепте нет --${имя}`)
  }
})

test('цвет объявляется один раз на обе темы, а не трижды', () => {
  // `light-dark()` выбирает значение по `color-scheme`, и потому цветной
  // токен стоит в одном месте. Пока их было три — светлая, системная
  // тёмная и явная тёмная, — правка одного из трёх проходила молча:
  // так `--warn` полгода простоял на Lc 47 при пороге 60, потому что
  // тёмную шкалу расставили по APCA, а его забыли.
  //
  // Не цвет объявляется по темам законно: тень — не цвет, галочка
  // флажка — картинка, рецепт меток — числа. Их `light-dark()`
  // не берёт, и требовать этого от них незачем.
  const объявления = [...стили.matchAll(/^\s*(--[a-z0-9-]+):\s*([^;]+);/gm)]
  const счёт = new Map<string, string[]>()
  for (const [, имя, значение] of объявления) {
    счёт.set(имя, [...(счёт.get(имя) ?? []), значение.trim()])
  }
  const цветом = (значение: string) => /^(#|rgb|oklch|hsl)/.test(значение)
  const дважды: string[] = []
  for (const [имя, значения] of счёт) {
    if (значения.length > 1 && значения.every(цветом)) дважды.push(имя)
  }
  assert.deepEqual(
    дважды,
    [],
    `цвет объявлен в нескольких темах: ${дважды.join(', ')} — ` +
      `используйте light-dark(светлый, тёмный), иначе правку одной темы забудут`,
  )
})

test('ступень шкалы кегля различима глазом', () => {
  // До 23.08.2026 ступеней было пять, и первая — 12 против 13 —
  // не была ступенью: разница в пиксель не читается ни при тройном
  // увеличении снимка, ни на экране. Стояли они при этом вплотную
  // («ПОСТ» тринадцатью, «v65» двенадцатью в шапке доски), а один
  // и тот же класс `.link` получал то одно, то другое — от того,
  // внутри чего оказался.
  //
  // Порог — 10%: на мелких кеглях это ровно тот минимум, на котором
  // два размера в одном ряду ещё различаются. Не «пиксель»: шкала
  // задана в `rem`, и пиксель на 22 и на 13 — разные вещи.
  const кегли = [...стили.matchAll(/^\s*(--text[\w-]*):\s*([\d.]+)rem/gm)].map(([, имя, знач]) => ({
    имя,
    px: parseFloat(знач) * 16,
  }))
  assert.ok(кегли.length >= 3, `шкала не найдена: ${кегли.length}`)
  кегли.sort((a, b) => a.px - b.px)

  const тесные: string[] = []
  for (let i = 1; i < кегли.length; i++) {
    const шаг = кегли[i].px / кегли[i - 1].px
    if (шаг < 1.1) {
      тесные.push(
        `${кегли[i - 1].имя} (${кегли[i - 1].px}px) и ${кегли[i].имя} (${кегли[i].px}px) — ` +
          `шаг ${Math.round((шаг - 1) * 100)}%`,
      )
    }
  }
  assert.deepEqual(
    тесные,
    [],
    `ступени неразличимы: ${тесные.join(' | ')} — уровни различают цветом, ` +
      `насыщенностью и капителью, а не пикселем кегля`,
  )
})

// --- Колонки не сливаются (ROADMAP 28.3) ---
//
// Замер 21.09.2026: в светлой теме колонка отличалась от фона доски
// на 1.07, её граница — на 1.20 при пороге 3:1, и разделение держалось
// на разнице, которой нет. А ступень была разной в двух темах:
// в светлой колонка углублена (темнее фона) и карточка лежит сверху
// (светлее колонки), в тёмной — наоборот, колонка приподнята, а
// карточка темнее её и выглядит вдавленной. Один продукт читался как
// два материала.
//
// Какие токены проверять, берётся из самих правил `.column` и `.card`,
// а не из списка здесь: иначе правило переедет на новый токен, а
// проверка останется сторожить старый.

/** Токен из `:root`: `light-dark(#светлое, #тёмное)` → оба значения. */
function токен(имя: string): { светлая: string; тёмная: string } {
  const m = стили.match(new RegExp(`--${имя}:\\s*light-dark\\((#[0-9a-fA-F]{6}),\\s*(#[0-9a-fA-F]{6})\\)`))
  assert.ok(m, `токен --${имя} не объявлен через light-dark(#…, #…)`)
  return { светлая: m[1], тёмная: m[2] }
}

/** Какой токен правило берёт в свойство: `.column { background: var(--x) }` → x. */
function изПравила(селектор: string, свойство: RegExp): string {
  const блок = стили.match(new RegExp(`\\n${селектор.replace('.', '\\.')} \\{([^}]*)\\}`))
  assert.ok(блок, `правила ${селектор} нет`)
  const m = блок[1].match(свойство)
  assert.ok(m, `в ${селектор} не нашлось ${свойство}`)
  return m[1]
}

/** Относительная яркость по WCAG 2.x. */
function яркость(цвет: string): number {
  const [r, g, b] = [1, 3, 5].map((i) => {
    const c = parseInt(цвет.slice(i, i + 2), 16) / 255
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4
  })
  return 0.2126 * r + 0.7152 * g + 0.0722 * b
}

function контраст(а: string, б: string): number {
  const [x, y] = [яркость(а), яркость(б)].sort((p, q) => p - q)
  return (y + 0.05) / (x + 0.05)
}

// Фон доски — фон страницы: доска своей подложки не заводит.
const фонДоски = токен('paper')
const заливкаКолонки = токен(изПравила('.column', /\bbackground:\s*var\(--([\w-]+)\)/))
const границаКолонки = токен(изПравила('.column', /\bborder:\s*1px solid var\(--([\w-]+)\)/))
const заливкаКарточки = токен(изПравила('.card', /\bbackground:\s*var\(--([\w-]+)\)/))

test('ступень доска → колонка → карточка идёт в одну сторону в обеих темах', () => {
  const ступень = (тема: 'светлая' | 'тёмная') => ({
    колонка: Math.sign(яркость(заливкаКолонки[тема]) - яркость(фонДоски[тема])),
    карточка: Math.sign(яркость(заливкаКарточки[тема]) - яркость(заливкаКолонки[тема])),
  })
  assert.deepEqual(
    ступень('тёмная'),
    ступень('светлая'),
    'направление ступени в тёмной теме не то, что в светлой',
  )
  // Карточка — то, что берут в руки, — лежит сверху в обеих темах.
  assert.equal(ступень('светлая').карточка, 1, 'в светлой карточка не светлее колонки')
  assert.equal(ступень('тёмная').карточка, 1, 'в тёмной карточка не светлее колонки — выглядит вдавленной')
})

test('граница колонки держит 3:1 и к фону доски, и к своей заливке', () => {
  // Разделение держится на границе, а не на заливках: развести заливки
  // на 3:1 значит заплатить из бюджета, которым платят за контраст
  // мелкого текста на колонке.
  for (const тема of ['светлая', 'тёмная'] as const) {
    const кФону = контраст(границаКолонки[тема], фонДоски[тема])
    const кЗаливке = контраст(границаКолонки[тема], заливкаКолонки[тема])
    assert.ok(кФону >= 3, `${тема}: граница колонки к фону доски ${кФону.toFixed(2)} < 3`)
    assert.ok(кЗаливке >= 3, `${тема}: граница колонки к её заливке ${кЗаливке.toFixed(2)} < 3`)
  }
})

// --- Красный значит «стоит» (разбор интерфейса 21.09.2026) ---
//
// Красным были помечены шесть разных вещей: блокировка, просроченное
// обязательство, возраст сверх обещания, срок блокировки, загрузка
// человека и возраст в таблице. На демо-доске красное стояло у пяти
// карточек из семи — и переставало значить что-либо. Теперь два тона:
// красный — «работа стоит или обещание нарушено», янтарный — «обратите
// внимание, но работа идёт». Проверяется, какой токен берёт правило
// для каждого смысла: имя класса называет смысл, токен — тон.

function цветПравила(селектор: string): string | null {
  const блок = стили.match(new RegExp(`\\n${селектор.replace(/[.-]/g, (c) => '\\' + c)} \\{([^}]*)\\}`))
  return блок?.[1].match(/(?:^|\s)color:\s*var\(--([\w-]+)\)/)?.[1] ?? null
}

test('красное — только то, что стоит или нарушено; обратить внимание — янтарём', () => {
  const стоит = ['.blocked', '.mark--alarm', '.table-overdue', '.subtask-blocked']
  const внимание = ['.mark--aging', '.table-aging', '.workload-item--aging', '.count--over']
  for (const с of стоит) assert.equal(цветПравила(с), 'warn', `${с} обязан быть красным`)
  for (const с of внимание) assert.equal(цветПравила(с), 'caution', `${с} — не «стоит», а «обратите внимание»`)
  // Срок блокировки — хорошая новость («снимется само»), не тревога.
  assert.notEqual(цветПравила('.card-block-until'), 'warn', 'срок блокировки окрашен тревогой')
})

test('янтарь читается: 4.5:1 к поверхности и к своей подложке в обеих темах', () => {
  const янтарь = токен('caution')
  const подложка = токен('caution-soft')
  const поверхность = токен('surface')
  for (const тема of ['светлая', 'тёмная'] as const) {
    assert.ok(контраст(янтарь[тема], поверхность[тема]) >= 4.5, `${тема}: янтарь к поверхности`)
    assert.ok(контраст(янтарь[тема], подложка[тема]) >= 4.5, `${тема}: янтарь к своей подложке`)
    // Янтарь отличим от красного — иначе второй тон ничего не даёт.
    assert.notEqual(янтарь[тема], токен('warn')[тема])
  }
})
