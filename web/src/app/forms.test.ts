// Формы: у поля есть имя, у подписи — поле, у отказа — адрес.
//
// Перепись 23.08.2026, с которой начался этот этап: тринадцать полей
// звались одним `placeholder` — то есть для диктора не звались никак,
// а для зрячего теряли имя с первым набранным символом; одна подпись
// («Действует до» у срока ключа) стояла отдельным `label` без `for` —
// на вид подпись, на деле просто текст; и во всех формах до одной отказ
// сервера показывался общей плашкой внизу, хотя правило «ошибка поля
// живёт у поля» записано в правилах компонентов давно.
//
// Правило не нарушали от небрежности. Его не нарушить было дороже,
// чем нарушить: связку «подпись — подсказка — отказ» каждая форма
// собирала руками. Отсюда `Field` — и отсюда эта проверка: она следит
// не за красотой, а за тем, чтобы обходной путь снова не оказался
// дешевле прямого.

import assert from 'node:assert/strict'
import { readFileSync, readdirSync } from 'node:fs'
import { test } from 'node:test'

/** Все исходники клиента, кроме проверок: они и есть то, что проверяют. */
function исходники(): { путь: string; текст: string }[] {
  const корень = new URL('../', import.meta.url)
  const out: { путь: string; текст: string }[] = []
  const обойти = (каталог: URL, префикс: string) => {
    for (const запись of readdirSync(каталог, { withFileTypes: true })) {
      if (запись.isDirectory()) {
        обойти(new URL(`${запись.name}/`, каталог), `${префикс}${запись.name}/`)
        continue
      }
      if (!запись.name.endsWith('.tsx') || запись.name.includes('.test.')) continue
      out.push({
        путь: префикс + запись.name,
        текст: readFileSync(new URL(запись.name, каталог), 'utf8'),
      })
    }
  }
  обойти(корень, '')
  return out
}

/**
 * Открывающий тег поля целиком.
 *
 * Регулярным выражением это не берётся: в JSX внутри свойств живут
 * стрелки `=>` и вложенные фигурные скобки, и «до первого `>`» обрезает
 * тег на середине — а обрезанный тег выглядит как поле без имени.
 * Поэтому конец ищется счётом скобок и кавычек.
 */
function поля(текст: string): { свойства: string; где: number; тег: string }[] {
  const out: { свойства: string; где: number; тег: string }[] = []
  for (const m of текст.matchAll(/<(input|textarea|select)\b/g)) {
    let глубина = 0
    let кавычка = ''
    let i = m.index + m[0].length
    for (; i < текст.length; i++) {
      const c = текст[i]
      if (кавычка) {
        if (c === кавычка) кавычка = ''
        continue
      }
      if (c === '"' || c === "'" || c === '`') кавычка = c
      else if (c === '{') глубина++
      else if (c === '}') глубина--
      else if (c === '>' && глубина === 0) break
    }
    out.push({ свойства: текст.slice(m.index + m[0].length, i), где: m.index, тег: m[0] })
  }
  return out
}

test('у каждого поля есть имя: `placeholder` именем не бывает', () => {
  const безымянные: string[] = []
  for (const { путь, текст } of исходники()) {
    if (путь.endsWith('shared/ui/Field.tsx')) continue
    for (const { свойства, где, тег } of поля(текст)) {
      // `{...bind}` — поле стоит внутри `Field`, и подпись связана там.
      if (/aria-label|aria-labelledby|\{\.\.\.bind\}/.test(свойства)) continue
      // Флажок и переключатель подписываются обёрткой: подпись стоит
      // рядом с квадратом, а не над ним, и `for` ей не нужен.
      if (/type=['"](checkbox|radio)['"]/.test(свойства) && вОбёртке(текст, где)) continue
      // Поле, обёрнутое подписью, названо ею же.
      if (вОбёртке(текст, где)) continue
      // Подпись стоит рядом и связана по `id`: «Видна» у видимости
      // доски. Совпадение проверяется тем же выражением — в этом коде
      // `id` бывает вычисляемым.
      const свой = /\bid=(\{[^}]*\}|"[^"]*")/.exec(свойства)
      if (свой && текст.includes(`htmlFor=${свой[1]}`)) continue
      const строка = текст.slice(0, где).split('\n').length
      безымянные.push(`${путь}:${строка} ${тег}${свойства.slice(0, 40).replace(/\s+/g, ' ')}`)
    }
  }
  assert.deepEqual(безымянные, [], `поле без имени: ${безымянные.join(' | ')}`)
})

/** Стоит ли поле внутри `<label>`, который его и подписывает. */
function вОбёртке(текст: string, где: number): boolean {
  const до = текст.slice(0, где)
  return до.lastIndexOf('<label') > до.lastIndexOf('</label>')
}

test('подпись связана с полем: иначе это просто текст рядом', () => {
  // `<label>` без `for` и без поля внутри не подписывает ничего:
  // щелчок по нему не ставит фокус, а диктор не читает его вместе
  // с полем. На вид — подпись, на деле — надпись.
  const беспризорные: string[] = []
  for (const { путь, текст } of исходники()) {
    for (const m of текст.matchAll(/<label\b([^>]*)>([\s\S]*?)<\/label>/g)) {
      const [, свойства, внутри] = m
      if (/htmlFor=/.test(свойства)) continue
      if (/<(input|textarea|select)\b/.test(внутри)) continue
      const строка = текст.slice(0, m.index).split('\n').length
      беспризорные.push(`${путь}:${строка} «${внутри.trim().slice(0, 30)}»`)
    }
  }
  assert.deepEqual(беспризорные, [], `подпись ни к чему не привязана: ${беспризорные.join(' | ')}`)
})

test('своя проверка и чужая не смешиваются', () => {
  // `noValidate` — не отказ от проверки, а отказ от браузерных
  // пузырьков: они не стилизуются, исчезают при переключении вкладки,
  // показываются по одному и переведены не нами. Значит, эти двое
  // ходят парой: форма без `noValidate` покажет и своё, и чужое разом,
  // а форма с `noValidate` и без своей проверки не покажет ничего —
  // и `required` в ней станет украшением.
  const плохие: string[] = []
  for (const { путь, текст } of исходники()) {
    for (const m of текст.matchAll(/<form\b([\s\S]*?)<\/form>/g)) {
      const тело = m[0]
      const строка = текст.slice(0, m.index).split('\n').length
      // Форма проверяет сама, если привязана к `useFormErrors`:
      // сам вызов `check` обычно стоит в обработчике выше по файлу,
      // а не внутри разметки.
      const своя = тело.includes('.check(') || тело.includes('ref={form.ref}')
      const чужая = !тело.includes('noValidate')
      if (своя && чужая) плохие.push(`${путь}:${строка} проверяет сама, но не отключила пузырьки`)
      if (!своя && !чужая) плохие.push(`${путь}:${строка} отключила пузырьки и не проверяет сама`)
    }
  }
  assert.deepEqual(плохие, [], плохие.join(' | '))
})

test('отказ уровня экрана объявляется, а не появляется', () => {
  // Диктор объявляет изменение области, которая уже была. Узел,
  // появившийся вместе с текстом, он пропускает молча — и человеку,
  // не видящему экрана, нажатая кнопка кажется не сработавшей.
  //
  // До 23.08.2026 так было написано двадцать мест из двадцати:
  // `{error && <p className="error">{error}</p>}`. Условие тут и есть
  // поломка. Поэтому оформление отказа экрана живёт в `ScreenError`,
  // а руками класс `error` не ставят: обходной путь должен быть
  // дороже прямого, иначе двадцать первое место напишут снова так же.
  const свои: string[] = []
  for (const { путь, текст } of исходники()) {
    if (путь.endsWith('shared/ui/Field.tsx')) continue // здесь он и объявлен
    for (const m of текст.matchAll(/className=(?:"error"|\{`error)/g)) {
      const строка = текст.slice(0, m.index).split('\n').length
      свои.push(`${путь}:${строка}`)
    }
    // Условие перед самим `ScreenError` — та же поломка, только
    // с правильным именем: узел снова появляется вместе с текстом.
    for (const m of текст.matchAll(/(?:&&|\?)\s*\n?\s*<ScreenError/g)) {
      const строка = текст.slice(0, m.index).split('\n').length
      свои.push(`${путь}:${строка} условие перед самим ScreenError`)
    }
  }
  assert.deepEqual(
    свои,
    [],
    `отказ экрана нарисован руками вместо <ScreenError>: ${свои.join(' | ')} — ` +
      `узел с role="alert" должен стоять всегда, иначе диктор о нём не скажет`,
  )
})
