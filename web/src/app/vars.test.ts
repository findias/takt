// Каждая переменная, на которую ссылаются, объявлена.
//
// Найдено глазами и по счастливой случайности: `--space-5` стоял
// в правиле, отводящем место под отказ в ряду формы, и не был объявлен
// нигде. `var()` без объявления и без запасного значения означает,
// что свойство не применяется вовсе, — правило выглядит написанным
// и не делает ничего. Ни браузер, ни сборка об этом не говорят.
//
// Соседние проверки ловят своё: `tokens.test.ts` — сырые цвета,
// `motion.test.ts` — сырые длительности. Эта ловит обратное: ссылку
// на то, чего нет.

import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { test } from 'node:test'

const стили = readFileSync(new URL('./styles.css', import.meta.url), 'utf8')

test('переменная, на которую ссылаются, объявлена', () => {
  const объявленные = new Set(
    [...стили.matchAll(/^\s*(--[a-z0-9-]+)\s*:/gm)].map((m) => m[1]),
  )
  assert.ok(объявленные.size > 20, 'объявлений токенов подозрительно мало')

  const висячие = new Set<string>()
  for (const m of стили.matchAll(/var\(\s*(--[a-z0-9-]+)\s*(,)?/g)) {
    // Запасное значение делает ссылку безопасной: `var(--x, 4px)`
    // работает и без объявления, и это законный приём.
    if (m[2]) continue
    if (!объявленные.has(m[1])) висячие.add(m[1])
  }
  assert.deepEqual(
    [...висячие],
    [],
    `ссылка на необъявленную переменную: ${[...висячие].join(', ')} — ` +
      `правило с ней не применяется вовсе, и об этом никто не скажет`,
  )
})
