/**
 * Слово в форме, которую требует число.
 *
 * Три формы, потому что их три: «1 карточка», «2 карточки»,
 * «5 карточек». Число не подставляется — иначе функцию нельзя вставить
 * в предложение, где оно уже написано словами или стоит отдельно.
 *
 * Отсюда, а не из трёх мест, где эта же таблица исключений была
 * переписана заново: в двух из них дробное число склонялось неверно,
 * а в диаграммах её не применили вовсе — и в подписи стояло
 * «за 91 дней».
 */
export function plural(n: number, one: string, few: string, many: string): string {
  // Дробное склоняется как «часа»: 1.5 часа, 2.5 часа.
  if (!Number.isInteger(n)) return few
  const mod100 = Math.abs(n) % 100
  const mod10 = Math.abs(n) % 10
  if (mod100 >= 11 && mod100 <= 14) return many
  if (mod10 === 1) return one
  if (mod10 >= 2 && mod10 <= 4) return few
  return many
}
