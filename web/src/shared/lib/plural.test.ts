// Склонение по числу.
//
// Таблица исключений русского счёта была переписана в трёх местах, и
// в двух из них дробное число склонялось по-своему. Проверяется здесь,
// один раз — в том числе то, ради чего дробное вообще встречается:
// «1.5 дня» на карточке и в диаграммах.

import assert from 'node:assert/strict'
import { test } from 'node:test'
import { plural } from './plural.ts'

const дни = (n: number) => plural(n, 'день', 'дня', 'дней')

test('целые склоняются по последней цифре, кроме подростков', () => {
  assert.equal(дни(1), 'день')
  assert.equal(дни(2), 'дня')
  assert.equal(дни(5), 'дней')
  assert.equal(дни(11), 'дней')
  assert.equal(дни(14), 'дней')
  assert.equal(дни(21), 'день')
  assert.equal(дни(22), 'дня')
  assert.equal(дни(91), 'день')
  assert.equal(дни(111), 'дней')
  assert.equal(дни(0), 'дней')
})

test('дробное склоняется как «дня»', () => {
  assert.equal(дни(1.5), 'дня')
  assert.equal(дни(4.7), 'дня')
})
