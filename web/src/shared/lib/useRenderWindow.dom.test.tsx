// Окно отрисовки: длинный список дорисовывается по мере прокрутки —
// и потому на бумагу попадало не всё.
//
// Проверяется здесь, а не в браузере, ровно одно обещание: перед
// печатью список раскрывается целиком. Остальное про печать —
// раскладка листа, обрезка, лишнее управление — живёт в сквозной
// проверке: это про стили, а не про хук.

import { act, render, screen } from '@testing-library/react'
import { expect, it } from 'vitest'
import { useRenderWindow } from './useRenderWindow.ts'

function Список({ всего }: { всего: number }) {
  const окно = useRenderWindow<HTMLParagraphElement>(всего)
  return (
    <div>
      <p>показано {окно.limit}</p>
      <p ref={окно.tail}>хвост {окно.rest}</p>
    </div>
  )
}

it('перед печатью список раскрывается целиком', () => {
  render(<Список всего={347} />)
  // Сто — обычное окно: столько дорисовывается сразу.
  expect(screen.getByText(/показано/).textContent).toBe('показано 100')

  act(() => {
    window.dispatchEvent(new Event('beforeprint'))
  })

  // Замер 23.08.2026: доска из ста двадцати карточек уходила на бумагу
  // семью строками. Сто одна была отрисована, остальные не дорисованы,
  // а из отрисованных на лист попало то, что помещалось в область
  // прокрутки, — и никто об этом не сказал.
  expect(screen.getByText(/показано/).textContent).toBe('показано 347')
})

it('после печати показанное не сворачивается обратно', () => {
  render(<Список всего={200} />)
  act(() => {
    window.dispatchEvent(new Event('beforeprint'))
  })
  act(() => {
    window.dispatchEvent(new Event('afterprint'))
  })
  // Свернуть значит выкинуть из разметки то, что человек уже видел:
  // поиск по странице перестал бы находить, а фокус — уехал бы.
  expect(screen.getByText(/показано/).textContent).toBe('показано 200')
})
