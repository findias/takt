import { useEffect } from 'react'

/** Как называется приложение, когда сказать больше нечего. */
const APP = 'Доска'

/**
 * Заголовок вкладки браузера.
 *
 * До этого он был один на всё приложение — «Доска», — и десять открытых
 * вкладок выглядели одинаково: найти среди них ту, где идёт нужная
 * работа, можно было только перебором. А открытых вкладок здесь много
 * по устройству работы: доска соседей, своя доска, карточка, которую
 * держат открытой, отчёт по итерации.
 *
 * Отличающее слово идёт первым: вкладка показывает начало заголовка
 * и обрезает конец, поэтому «ПОСТ-14 · Доска» различимо, а
 * «Доска · ПОСТ-14» — нет.
 *
 * Пустое `what` оставляет прежний заголовок вместо мигания именем
 * приложения: экран, который ещё грузится, знает своё имя через
 * мгновение, и промежуточное «Доска» человек успевает увидеть.
 */
export function useDocumentTitle(what: string | null): void {
  useEffect(() => {
    if (!what) return
    const было = document.title
    document.title = `${what} · ${APP}`
    // Возврат прежнего важен для карточки: закрыли панель — заголовок
    // обязан вернуться к доске, а не остаться на закрытой карточке.
    return () => {
      document.title = было
    }
  }, [what])
}
