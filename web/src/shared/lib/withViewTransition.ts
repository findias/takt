/**
 * Показать смену вида движением, а не подменой.
 *
 * View Transitions в документе — Baseline newly с 14.10.2025 (сверено
 * 23.08.2026). Цена замерена на доске в пятьсот карточек: подготовка
 * снимка 7 мс, дальше работает браузер. То есть препятствия по времени
 * отклика нет — вопрос только в том, что именно объясняется.
 *
 * Объясняется одно: **доска и таблица — это одни и те же карточки,
 * показанные иначе.** Мгновенная подмена читается как переход на другой
 * экран, и человек заново ищет, где он был; проявление говорит «то же
 * место, другая раскладка».
 *
 * Переносу карточки этого не дали намеренно, хотя технически он тот же
 * случай. Карточка уезжает в конец соседней колонки — часто за нижний
 * край экрана, — и полёт к невидимой точке объясняет хуже, чем вспышка
 * на новом месте: она отвечает на вопрос «где она теперь», а траектория
 * ведёт в никуда. Плюс следом идёт возврат фокуса, а он прокручивает
 * доску сам, и два движения разом складываются в кашу.
 *
 * Просивших меньше движения не трогаем вовсе: у перехода вида нет
 * версии «поспокойнее», а `prefers-reduced-motion` — просьба, а не
 * пожелание.
 */
export function withViewTransition(apply: () => void): void {
  const start = (
    document as Document & {
      startViewTransition?: (callback: () => void) => unknown
    }
  ).startViewTransition
  const тише = window.matchMedia('(prefers-reduced-motion: reduce)').matches
  if (!start || тише) {
    apply()
    return
  }
  start.call(document, apply)
}
