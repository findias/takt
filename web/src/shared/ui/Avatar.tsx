/**
 * Кто делает карточку.
 *
 * Инициалы, а не фотография. Фотографий у нас нет и не будет: доска
 * рассчитана на сотню человек, которые друг друга знают, а плитка
 * из аватаров съедает ту самую плотность, ради которой доска
 * и существует. Инициалы отвечают на вопрос «моё ли это» с одного
 * взгляда и занимают двадцать пикселей.
 *
 * Цвет выводится из имени, а не хранится: поле «цвет человека» — это
 * поле, которое кто-то однажды должен заполнить, а потом поддерживать.
 * Оттенок берётся из фиксированного набора, согласованного с темой,
 * поэтому в тёмной теме он не начинает светиться.
 */

import { initials } from '../lib/initials.ts'

const TONES = 8

/** Размер по умолчанию — один на аватар и на «+2» в конце стопки.
 *  Числа стояли в двух местах, в разметке и в стилях, и разъехались
 *  на четыре пикселя: кружок «+2» выпирал из стопки. */
const SIZE = 20

/** Второй план: кто делает части. Мельче обычного — в полный рост
 *  эти аватары спорили бы с исполнителями самой карточки. Было
 *  записано классом `.avatars--small`, который не работал никогда:
 *  размер приходит вписанным стилем, а он сильнее класса. */
export const AVATAR_SMALL = 18

/** Кегль монограммы — доля от кружка.
 *
 *  Букв в кружке одна, и это не про длину имени, а про шрифт.
 *  Продукт не везёт своего начертания: `--font-ui` — системный стек,
 *  и на разных машинах он разрешается в разные шрифты. Две заглавные
 *  считались влезающими по одному замеру — «ШЩ» при кегле восемь
 *  занимали семнадцать пикселей из двадцати (23.08.2026), — а на
 *  машине с более широким запасным начертанием те же «ШЩ» заняли
 *  двадцать один и из кружка вылезли. Три пикселя запаса на весь
 *  разброс системных шрифтов — не запас.
 *
 *  Одна буква снимает вопрос: «Ш» при кегле одиннадцать занимает
 *  пятнадцать пикселей даже в самом широком из встреченных
 *  начертаний. Потери при этом нет: монограмма спрятана от диктора,
 *  имя целиком стоит рядом в `title`, и задача у неё не читаться,
 *  а узнаваться. */
const ДОЛЯ_БУКВЫ = 0.55

/** Кегль счётчика — доля поменьше: знаков там до трёх («+99»),
 *  и места им нужно втрое больше, чем одной букве. */
const ДОЛЯ_СЧЁТЧИКА = 0.42

/** Размер задаётся вписанным стилем, а не классом, потому что он
 *  приходит числом из вызова. Класс с размером тот же стиль
 *  не перебьёт — так уже был мёртвый `.avatars--small`. */
function sizing(size: number, доля: number) {
  return { inlineSize: size, blockSize: size, fontSize: Math.round(size * доля) }
}

/** Разброс по имени. Не криптография: нужно лишь, чтобы два соседних
 *  имени не сливались в один цвет. */
function toneOf(name: string): number {
  let sum = 0
  for (const ch of name) sum = (sum + ch.codePointAt(0)!) % 997
  return sum % TONES
}

export function Avatar({ name, size = SIZE }: { name: string; size?: number }) {
  return (
    <span
      className={`avatar avatar--tone-${toneOf(name)}`}
      style={sizing(size, ДОЛЯ_БУКВЫ)}
      // Имя целиком — рядом, а не вместо: инициалы читаются глазами,
      // скринридер читает имя.
      title={name}
      aria-hidden="true"
    >
      {/* Инициалов у имени два, в кружок идёт первый: второй — ровно
          то, что перестало помещаться при чужом шрифте. */}
      {initials(name).slice(0, 1)}
    </span>
  )
}

/**
 * «И ещё двое» в конце стопки.
 *
 * Отдельный компонент, а не модификатор аватара, и класс тоже
 * отдельный. Имя `avatar--more` три раза подряд читалось как «этому
 * нужен базовый класс `avatar`», хотя базовый класс ему только вредит:
 * он красит текст цветом подложки, рассчитанным на заливку оттенком,
 * которой здесь нет, — «+2» стало бы невидимым. Это не аватар без
 * лица, это счётчик; общего у них только форма и размер.
 */
export function AvatarMore({ count, size = SIZE }: { count: number; size?: number }) {
  return (
    <span className="avatar-more" style={sizing(size, ДОЛЯ_СЧЁТЧИКА)} title={`и ещё ${count}`}>
      +{count}
    </span>
  )
}
