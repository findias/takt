import { defineConfig } from '@playwright/test'

// Сквозные сценарии: настоящий браузер, настоящий сервер, настоящая база.
//
// Всё остальное на фронтенде проверяется с подменённым сервером, и это
// правильно — так проверки быстрые и точные. Но подменённый сервер
// не поймает то, ради чего сценарии и существуют: что собранный клиент
// и собранный сервер вообще договариваются между собой. Именно на этом
// стыке уже ломались: клиент ждал полей, которых старый снимок не отдавал,
// и доска переставала отрисовываться — выглядело как «пусто», а не как
// ошибка.
//
// Браузер берётся системный (channel: 'chrome'), а не скачивается
// Playwright'ом: полтораста мегабайт ради того, что уже установлено, —
// плохая сделка, а в закрытом контуре ещё и невыполнимая.

const PORT = Number(process.env.E2E_PORT ?? 8098)
const DATABASE_URL =
  process.env.E2E_DATABASE_URL ??
  process.env.TEST_DATABASE_URL ??
  'postgres://takt:takt@localhost:55432/takt?sslmode=disable'

export default defineConfig({
  testDir: './e2e',
  // Сценарии ходят в общую базу, но каждый заводит свою организацию,
  // поэтому мешать друг другу им нечем.
  fullyParallel: true,
  // Один повтор: сценарий, падающий через раз, — это не «моргнуло»,
  // а находка, и её надо увидеть. Больше повторов прячут находку.
  retries: 1,
  timeout: 30_000,
  use: {
    baseURL: `http://127.0.0.1:${PORT}`,
    channel: 'chrome',
    headless: true,
    // След оставляем только от упавшей попытки: по нему видно, что было
    // на экране, а глазами интерфейс всё ещё никто не смотрел.
    trace: 'retain-on-failure',
    screenshot: 'only-on-failure',
    locale: 'ru-RU',
  },
  // Сервер поднимается тот же самый, что едет в образе: свой бинарник
  // и своя статика. Отдельная сборка «для тестов» проверяла бы себя.
  webServer: {
    // SIGNUP=open: сценарии начинаются с заведения организации, а
    // умолчание `first` закрывает регистрацию после первой же — база
    // у прогонов общая. Сами режимы проверяются в Go, против базы.
    command: `DATABASE_URL='${DATABASE_URL}' LISTEN_ADDR=':${PORT}' BASE_URL='http://127.0.0.1:${PORT}' WEB_DIR=./web/dist SIGNUP=open go run ./cmd/takt serve`,
    cwd: '..',
    url: `http://127.0.0.1:${PORT}/readyz`,
    reuseExistingServer: !process.env.CI,
    timeout: 120_000,
  },
})
