import { defineConfig } from '@playwright/test'

// Сквозные сценарии против тестового стенда ветки (ROADMAP 30.7).
//
// Отдельный набор, а не прежний с другим адресом: прежний заводит свои
// организации регистрацией и поднимает свой сервер, а на стенде
// регистрация закрыта и сервер уже выложен. Здесь — то, что должно
// работать на любой выложенной ветке поверх демонстрационных данных:
// вход под каждой ролью, доска, карточка, «Поток», личные настройки,
// заметка стенда. Правит сценарий только своё: заводит доску и в конце
// убирает её в архив.
//
// Адрес — из STAND_URL; без него набор не запускается, а не идёт
// на localhost, где стенда нет.

const url = process.env.STAND_URL
if (!url) throw new Error('STAND_URL не задан: против чего гонять сценарии стенда?')

export default defineConfig({
  testDir: './e2e-stand',
  // Последовательно: база стенда общая, а люди в ней одни и те же.
  workers: 1,
  retries: 1,
  // Бесплатный стенд после простоя просыпается около минуты, и первый
  // сценарий платит за это целиком.
  timeout: 120_000,
  expect: { timeout: 15_000 },
  use: {
    baseURL: url.replace(/\/$/, ''),
    channel: 'chrome',
    headless: true,
    trace: 'retain-on-failure',
    screenshot: 'only-on-failure',
    locale: 'ru-RU',
  },
})
